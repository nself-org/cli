#!/usr/bin/env python3
"""Generate wiki pricing pointers; commercial terms live at nself.org/pricing."""
from pathlib import Path
import re

wiki = Path(__file__).resolve().parents[2] / '.github/wiki'
pages = {
    'Feature-Plugins': 'Plugin features',
    'Plugin-Licensing': 'Plugin licensing',
    'Plugin-Overview': 'Plugin overview',
    'Licensing-Guide': 'Licensing guide',
    'bundle-nchat': 'nChat bundle',
    'bundle-nfamily': 'nFamily bundle',
    'bundle-nclaw': 'nClaw bundle',
}
pointer = ('See [nSelf pricing](https://nself.org/pricing) for current offerings, '
           'bundle contents, availability and licensing terms.\n')
for name, title in pages.items():
    (wiki / f'{name}.md').write_text(
        '<!-- Generated by scripts/docs/generate-pricing-pointers.py -->\n'
        f'# {title}\n\n{pointer}')

# The command page is owned by wikigen; only its preserved prose is authored here.
command = wiki / 'cmd-bundle.md'
body = command.read_text()
for block, content in {
    'summary': '> Manage and inspect nSelf plugin bundles.\n',
    'description': pointer,
    'examples': 'Run `nself config bundles --help` for current usage.\n',
    'see-also': '[nSelf pricing](https://nself.org/pricing)\n',
}.items():
    body, count = re.subn(
        rf'(<!-- BEGIN PROSE:{block} -->)\n.*?(<!-- END PROSE:{block} -->)',
        lambda match: match[1] + '\n' + content + match[2], body, flags=re.S)
    if count != 1:
        raise SystemExit(f'expected one {block} block, found {count}')
command.write_text(body)
