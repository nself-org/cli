package main

import (
	"fmt"
	"os"
	"path/filepath"
)

const coreServicesOut = ".github/wiki/Core-Services.md"

// runCoreServices ports generate-core-services.sh.
func runCoreServices(d Deps) int {
	const svccat = "bin/servicecatalog"
	if _, err := d.Runner.Run("go", "build", "-mod=vendor", "-o", svccat, "./tools/servicecatalog"); err != nil {
		fmt.Fprintf(d.Stderr, "error: build servicecatalog: %v\n", err)
		return 1
	}
	fmt.Fprintf(d.Stdout, "Generating %s ...\n", coreServicesOut)
	table, err := d.Runner.Run(svccat, "-format", "markdown")
	if err != nil {
		fmt.Fprintf(d.Stderr, "error: servicecatalog: %v\n", err)
		return 1
	}
	page := "# Core Services\n\n" +
		"<!-- GENERATED BY scripts/sport/generate-core-services.sh — DO NOT HAND EDIT -->\n\n" +
		"The services an nSelf stack is made of, generated from\n" +
		"`internal/compose/service_catalog.go`. The same data backs\n" +
		"`nself service list --core`, so the CLI and this page cannot disagree.\n\n" +
		table +
		"\n## Checking your own stack\n\n```bash\nnself service list --core\n```\n\n---\n\n" +
		"[[Home]] · [[Commands]] · [[Config-Optional-Services]]\n"
	if code := writeFile(d, coreServicesOut, page); code != 0 {
		return code
	}
	if dir := d.Env("NSELF_SPORT_DIR"); dirExists(dir) {
		out := filepath.Join(dir, "F08-CORE-SERVICES.md")
		fmt.Fprintf(d.Stdout, "Generating %s ...\n", out)
		sport := "# F08 — Core Services (generated)\n\n" +
			"<!-- GENERATED BY cli/scripts/sport/generate-core-services.sh — DO NOT HAND EDIT -->\n\n" +
			"Last generated: " + d.Now().UTC().Format("2006-01-02") + "\n" +
			"Source: `cli/internal/compose/service_catalog.go`.\n\n" + table
		if err := os.WriteFile(out, []byte(sport), 0o644); err != nil {
			fmt.Fprintf(d.Stderr, "error: %v\n", err)
			return 1
		}
	} else {
		fmt.Fprintln(d.Stdout, "NSELF_SPORT_DIR not set or missing — skipping SPORT refresh.")
	}
	fmt.Fprintln(d.Stdout, "Done.")
	return 0
}

// writeFile writes a repo-relative file.
func writeFile(d Deps, rel, content string) int {
	if err := os.WriteFile(filepath.Join(d.Root, rel), []byte(content), 0o644); err != nil {
		fmt.Fprintf(d.Stderr, "error: %v\n", err)
		return 1
	}
	return 0
}

func dirExists(p string) bool {
	if p == "" {
		return false
	}
	fi, err := os.Stat(p)
	return err == nil && fi.IsDir()
}
