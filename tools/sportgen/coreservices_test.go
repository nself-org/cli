package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// catalogOf extracts what servicecatalog printed from the committed page.
func catalogOf(t *testing.T) string {
	page := readRepo(t, coreServicesOut)
	i := strings.Index(page, "disagree.\n\n") + len("disagree.\n\n")
	j := strings.Index(page, "\n## Checking your own stack")
	return page[i:j]
}

func TestSportGenCoreF02F17CoreServicesMatchesCommitted(t *testing.T) {
	e := newEnv(t)
	e.r.out["bin/servicecatalog"] = catalogOf(t)
	if code := RunWith(e.d, []string{"core-services"}); code != 0 {
		t.Fatalf("code %d: %s", code, e.err)
	}
	wantEq(t, "Core-Services.md", e.read(t, coreServicesOut), readRepo(t, coreServicesOut))
	wantEq(t, "stdout", e.out.String(),
		"Generating .github/wiki/Core-Services.md ...\nNSELF_SPORT_DIR not set or missing — skipping SPORT refresh.\nDone.\n")
	wantEq(t, "calls", strings.Join(e.r.calls, "|"),
		"go build -mod=vendor -o bin/servicecatalog ./tools/servicecatalog|bin/servicecatalog -format markdown")
}

func TestSportGenCoreF02F17CoreServicesSportFile(t *testing.T) {
	e := newEnv(t)
	sport := t.TempDir()
	e.vars["NSELF_SPORT_DIR"] = sport
	e.r.out["bin/servicecatalog"] = "TABLE\n"
	if code := RunWith(e.d, []string{"core-services"}); code != 0 {
		t.Fatalf("code %d", code)
	}
	b, _ := os.ReadFile(filepath.Join(sport, "F08-CORE-SERVICES.md"))
	wantEq(t, "F08", string(b), "# F08 — Core Services (generated)\n\n"+
		"<!-- GENERATED BY cli/scripts/sport/generate-core-services.sh — DO NOT HAND EDIT -->\n\n"+
		"Last generated: 2026-11-07\nSource: `cli/internal/compose/service_catalog.go`.\n\nTABLE\n")
	if !strings.Contains(e.out.String(), "Generating "+sport+"/F08-CORE-SERVICES.md ...\n") {
		t.Errorf("stdout: %q", e.out)
	}
}

func TestSportGenCoreF02F17CoreServicesBuildFailure(t *testing.T) {
	e := newEnv(t)
	e.r.fail = "go build"
	code := RunWith(e.d, []string{"core-services"})
	wantEq(t, "stderr", e.err.String(), "error: build servicecatalog: fake failure\n")
	if code != 1 || len(e.r.calls) != 1 {
		t.Errorf("code %d calls %v", code, e.r.calls)
	}
	if _, err := os.Stat(filepath.Join(e.d.Root, coreServicesOut)); err == nil {
		t.Error("page written despite failure")
	}
}

func TestSportGenCoreF02F17Usage(t *testing.T) {
	e := newEnv(t)
	RunWith(e.d, nil)
	wantEq(t, "usage", e.err.String(), "usage: sportgen <core-services|f02|f17>\n")
	e.err.Reset()
	RunWith(e.d, []string{"nope"})
	wantEq(t, "unknown", e.err.String(), "unknown command: nope\n")
}
