package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const (
	f02JSON  = ".github/command-inventory.json"
	f02Reg   = ".github/command-registry.json"
	f02Wiki  = ".github/wiki/Commands.md"
	f02Canon = ".github/wiki/Command-Canon.md"
	cmdBegin = "<!-- BEGIN GENERATED:command-table -->"
	cmdEnd   = "<!-- END GENERATED:command-table -->"
	pageNav  = "← [[Home]] | [[_Sidebar]]"
)

// dropLast removes the last n lines of s (sed '$d' repeated n times).
func dropLast(s string, n int) string {
	lines := strings.Split(strings.TrimSuffix(s, "\n"), "\n")
	if s == "" || len(lines) <= n {
		return ""
	}
	return strings.Join(lines[:len(lines)-n], "\n") + "\n"
}

// spliceBlock replaces the generated block in page, or appends it before the nav.
func spliceBlock(page, block string) string {
	block = strings.TrimRight(block, "\n")
	b, e := strings.Index(page, cmdBegin), strings.Index(page, cmdEnd)
	if b >= 0 && e >= 0 {
		return page[:b] + block + page[e+len(cmdEnd):]
	}
	if p := strings.TrimRight(page, " \t\r\n"); strings.HasSuffix(p, pageNav) {
		p = strings.TrimRight(p[:len(p)-len(pageNav)], " \t\r\n")
		page = strings.TrimRight(strings.TrimRight(p, "-"), " \t\r\n")
	}
	return strings.TrimRight(page, "\n") + "\n\n" + block + "\n---\n" + pageNav + "\n"
}

// runF02 ports generate-f02.sh.
func runF02(d Deps) int {
	const inv = "bin/cmdinventory"
	fail := func(what string, err error) int {
		fmt.Fprintf(d.Stderr, "error: %s: %v\n", what, err)
		return 1
	}
	if _, err := d.Runner.Run("go", "build", "-mod=vendor", "-o", inv, "./tools/cmdinventory"); err != nil {
		return fail("build cmdinventory", err)
	}
	for _, g := range []struct {
		out  string
		args []string
	}{
		{f02JSON, []string{"-format", "json", "-depth", "2"}},
		{f02Reg, []string{"-format", "registry"}},
		{f02Canon, []string{"-format", "canon", "-prose-from", f02Canon}},
	} {
		fmt.Fprintf(d.Stdout, "Generating %s ...\n", g.out)
		s, err := d.Runner.Run(inv, g.args...)
		if err != nil {
			return fail("cmdinventory", err)
		}
		if c := writeFile(d, g.out, s); c != 0 {
			return c
		}
	}
	names, err := d.Runner.Run(inv, "-format", "names")
	if err != nil {
		return fail("cmdinventory names", err)
	}
	count := strings.Count(names, "\n")
	fmt.Fprintf(d.Stdout, "Updating %s (%d top-level commands) ...\n", f02Wiki, count)
	md, err := d.Runner.Run(inv, "-format", "markdown", "-depth", "2")
	if err != nil {
		return fail("cmdinventory markdown", err)
	}
	table := dropLast(md, 2)
	block := cmdBegin + "\n\n## Complete index\n\n" +
		"Generated from the cobra registration tree in `cmd/commands/`.\n" +
		fmt.Sprintf("Run `make cmd-inventory` to refresh. **Total top-level commands: %d**\n\n", count) +
		table + "\n" + cmdEnd + "\n"
	raw, err := os.ReadFile(filepath.Join(d.Root, f02Wiki))
	if err != nil {
		return fail("read "+f02Wiki, err)
	}
	if c := writeFile(d, f02Wiki, spliceBlock(string(raw), block)); c != 0 {
		return c
	}
	if dir := d.Env("NSELF_SPORT_DIR"); dirExists(dir) {
		out := filepath.Join(dir, "F02-COMMAND-INVENTORY.md")
		fmt.Fprintf(d.Stdout, "Generating %s ...\n", out)
		s := "# F02 — CLI Command Inventory\n\n" +
			"<!-- GENERATED BY cli/scripts/sport/generate-f02.sh — DO NOT HAND EDIT -->\n\n" +
			"Last generated: " + d.Now().UTC().Format("2006-01-02") + "\n" +
			"Source: `cli/cmd/commands` cobra registration tree (not a hand count).\n\n" +
			fmt.Sprintf("**Counts: %d top-level commands.** Subcommands listed but not counted separately.\n\n", count) +
			table
		if err := os.WriteFile(out, []byte(s), 0o644); err != nil {
			return fail("write "+out, err)
		}
	} else {
		fmt.Fprintln(d.Stdout, "NSELF_SPORT_DIR not set or missing — skipping SPORT F02 refresh.")
	}
	return f02Facts(d, count)
}

// f02Facts runs the last steps: openapi.json, then facts.json and the README blocks.
func f02Facts(d Deps, count int) int {
	steps := [][]string{
		{"go", "run", "-mod=vendor", "./tools/openapigen"},
		{"go", "build", "-mod=vendor", "-o", "bin/facts", "./tools/facts"},
		{"bin/facts", "-readme", "README.md"},
	}
	for i, s := range steps {
		switch i {
		case 0:
			fmt.Fprintln(d.Stdout, "Refreshing .github/openapi.json (facts.json hashes it) ...")
		case 1:
			fmt.Fprintln(d.Stdout, "Generating .github/facts.json ...")
		}
		out, err := d.Runner.Run(s[0], s[1:]...)
		fmt.Fprint(d.Stdout, out)
		if err != nil {
			fmt.Fprintf(d.Stderr, "error: %s: %v\n", s[0], err)
			return 1
		}
	}
	fmt.Fprintf(d.Stdout, "Done. %d top-level commands.\n", count)
	return 0
}
