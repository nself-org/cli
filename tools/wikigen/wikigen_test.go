package main

// Tests for the hand-written notes on the ci and runner command pages (P7-NODE-25).
//
// Purpose: wikigen -check is only run by hand and in the gate; this test makes `go test` fail too
// when cmd-ci.md or cmd-runner.md drift from what the generator renders (a generated region edited
// by hand, a flag added without regenerating, a PROSE marker damaged), and when the migration and
// serve notes are lost.
// Inputs: the committed pages under .github/wiki, read from the repo root two levels up.
// Outputs: test failures only; nothing is written.

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const nodesGuideLink = "https://github.com/nself-org/plugins/wiki/Nodes-and-Runners"

// TestWikiPagesMatchGenerator fails when wikigen -check would report any command page stale. The ci and
// runner pages are plugin-owned in the v1.5 tree (no builtin top-level command, so wikigen renders
// nothing for them); they are covered by TestCIAndRunnerPagesStructure instead.
func TestWikiPagesMatchGenerator(t *testing.T) {
	registry, undo, err := prepareWikiRegistry()
	if err != nil {
		t.Fatalf("wiki registry: %v", err)
	}
	defer undo()

	dir := filepath.Join("..", "..", ".github", "wiki")
	for _, c := range topLevelCommands() {
		entry, ok := registry[c.CommandPath()]
		if !ok {
			t.Fatalf("wiki registry lacks %s", c.CommandPath())
		}
		page := renderPage(c, entry, registry, readExisting(dir, c.Name()))
		if path := filepath.Join(dir, pageName(c.Name())); pageStale(path, page) {
			t.Errorf("%s drifts from the generator: run `go run ./tools/wikigen` and commit the result", path)
		}
	}
}

// TestCIAndRunnerPagesStructure guards the two pages the generator does not render: the generated
// header stays, every GENERATED and PROSE block opens and closes once and in order, and the
// description prose is the block the notes live in.
func TestCIAndRunnerPagesStructure(t *testing.T) {
	dir := filepath.Join("..", "..", ".github", "wiki")
	for _, name := range []string{"ci", "runner"} {
		b, err := os.ReadFile(filepath.Join(dir, pageName(name)))
		if err != nil {
			t.Fatal(err)
		}
		page := string(b)
		if !strings.HasPrefix(page, "<!-- GENERATED BY tools/wikigen") {
			t.Errorf("%s lost its generated header", pageName(name))
		}
		for _, sec := range []string{"synopsis", "flags", "subcommands", "contract"} {
			checkBlock(t, name, page, beginGenerated(sec), endGenerated(sec))
		}
		for _, sec := range []string{"summary", "description", "examples", "see-also"} {
			checkBlock(t, name, page, beginProse(sec), endProse(sec))
		}
	}
}

// checkBlock reports a missing, duplicated or reversed marker pair.
func checkBlock(t *testing.T, name, page, begin, end string) {
	t.Helper()
	bi, ei := strings.Index(page, begin), strings.Index(page, end)
	if bi < 0 || ei < 0 || ei < bi || strings.Count(page, begin) != 1 || strings.Count(page, end) != 1 {
		t.Errorf("%s: block %q is missing, duplicated or out of order", pageName(name), begin)
	}
}

// TestCIAndRunnerNotes pins the facts the two notes state, inside the description prose block.
func TestCIAndRunnerNotes(t *testing.T) {
	dir := filepath.Join("..", "..", ".github", "wiki")
	for _, tc := range []struct {
		page  string
		wants []string
	}{
		{"runner", []string{"nself ci nodes", "v1.6", nodesGuideLink}},
		{"ci", []string{"127.0.0.1:3845", "--addr", ":3864", "127.0.0.1:3865", nodesGuideLink}},
	} {
		b, err := os.ReadFile(filepath.Join(dir, pageName(tc.page)))
		if err != nil {
			t.Fatal(err)
		}
		page := string(b)
		prose := rawBetween(page, beginProse("description"), endProse("description"))
		for _, w := range tc.wants {
			if !strings.Contains(prose, w) {
				t.Errorf("%s description prose lacks %q", pageName(tc.page), w)
			}
		}
	}
}
