package main

// Purpose: turn the parsed contract into the generated TypeScript files.
// Inputs: Model. Outputs: relative path -> file bytes (types.ts, client.ts).
// Constraints: deterministic order; naming collisions fail the run.

import (
	"bytes"
	"embed"
	"fmt"
	"sort"
	"strings"
	"text/template"
)

//go:embed templates/*.tmpl
var templateFS embed.FS

const header = "// GENERATED BY tools/sdkgen — DO NOT HAND EDIT"

// reservedMembers are client members the runtime adds next to the operations.
var reservedMembers = map[string]bool{"stream": true, "openapi": true, "call": true}

// runtimeComponents are hand-written in the runtime, not emitted as types.
var runtimeComponents = map[string]bool{"envelope": true, "error_envelope": true, "confirmation_envelope": true}

type typeDecl struct {
	Doc  string
	Name string
	Body string
	Kind string // "interface" or "type"
}

type opView struct {
	Method   string
	Name     string
	Path     string
	Summary  string
	DataType string
	Optional bool
}

func parseTemplate(name string) (*template.Template, error) {
	b, err := templateFS.ReadFile("templates/" + name)
	if err != nil {
		return nil, err
	}
	return template.New(name).Parse(string(b))
}

func execTemplate(name string, data any) ([]byte, error) {
	t, err := parseTemplate(name)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := t.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("sdkgen: render %s: %w", name, err)
	}
	return buf.Bytes(), nil
}

func componentDecls(m *Model) []typeDecl {
	names := make([]string, 0, len(m.Schemas))
	for n := range m.Schemas {
		if !runtimeComponents[n] {
			names = append(names, n)
		}
	}
	sort.Strings(names)
	out := make([]typeDecl, 0, len(names))
	for _, n := range names {
		s := m.Schemas[n]
		d := typeDecl{Name: typeName(n), Doc: comment(s.Description), Body: tsType(s, 0), Kind: "type"}
		if strings.HasPrefix(d.Body, "{\n") {
			d.Kind = "interface"
		}
		out = append(out, d)
	}
	return out
}

// requestDecls renders {Name}Args, {Name}Flags and {Name}Request for op.
func requestDecls(name string, op Operation) ([]typeDecl, bool, error) {
	props := map[string]*Schema{}
	if op.Request != nil {
		props = op.Request.Properties
	}
	for k := range props {
		if k != "args" && k != "flags" && k != "confirm" {
			return nil, false, fmt.Errorf("sdkgen: %s request has unsupported member %q", op.ID, k)
		}
	}
	args, flags := props["args"], props["flags"]
	if args == nil {
		args = &Schema{Type: []byte(`"array"`)}
	}
	if flags == nil {
		flags = &Schema{Type: []byte(`"object"`), Properties: map[string]*Schema{}, AdditionalProperties: []byte("false")}
	}
	argsRequired := args.MinItems != nil && *args.MinItems > 0
	req := "{\n  args" + map[bool]string{true: "", false: "?"}[argsRequired] + ": " + name + "Args;\n  flags?: " + name + "Flags;\n  confirm?: string;\n}"
	decls := []typeDecl{
		{Name: name + "Args", Body: tsType(args, 0), Kind: "type"},
		{Name: name + "Flags", Body: tsType(flags, 0), Kind: "type"},
		{Doc: comment(op.Summary), Name: name + "Request", Body: req, Kind: "interface"},
	}
	return decls, !argsRequired, nil
}

// Render produces every generated TypeScript file keyed by path under the package dir.
func Render(m *Model) (map[string][]byte, []opView, error) {
	decls := componentDecls(m)
	views := make([]opView, 0, len(m.Ops))
	methods, typesSeen := map[string]string{}, map[string]string{}
	for _, d := range decls {
		typesSeen[d.Name] = "component"
	}
	for _, op := range m.Ops {
		method, name := methodName(op.ID), pascal(strings.TrimPrefix(op.ID, "nself_"))
		if reservedMembers[method] {
			return nil, nil, fmt.Errorf("sdkgen: %s maps to reserved client member %q", op.ID, method)
		}
		if prev, dup := methods[method]; dup {
			return nil, nil, fmt.Errorf("sdkgen: %s and %s both map to method %q", prev, op.ID, method)
		}
		methods[method] = op.ID
		rd, optional, err := requestDecls(name, op)
		if err != nil {
			return nil, nil, err
		}
		for _, d := range rd {
			if prev, dup := typesSeen[d.Name]; dup {
				return nil, nil, fmt.Errorf("sdkgen: type %s from %s collides with %s", d.Name, op.ID, prev)
			}
			typesSeen[d.Name] = op.ID
		}
		decls = append(decls, rd...)
		data := "unknown"
		if _, ok := m.Schemas[op.ID+"_data"]; ok {
			data = "T." + typeName(op.ID+"_data")
		}
		views = append(views, opView{Method: method, Name: name, Path: op.Path, Summary: comment(op.Summary), DataType: data, Optional: optional})
	}
	sort.SliceStable(decls, func(i, j int) bool { return decls[i].Name < decls[j].Name })
	files := map[string][]byte{}
	var err error
	if files["src/generated/types.ts"], err = execTemplate("types.ts.tmpl", map[string]any{"Header": header, "Decls": decls}); err != nil {
		return nil, nil, err
	}
	if files["src/generated/client.ts"], err = execTemplate("client.ts.tmpl", map[string]any{"Header": header, "Ops": views}); err != nil {
		return nil, nil, err
	}
	return files, views, nil
}
