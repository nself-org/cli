const testBuildMarker = "# Generated by nself build - DO NOT EDIT MANUALLY\n"

// scratchBuildStub is a deployScratchBuildFn that writes a finished build in the
// scratch dir (compose, manifests, a generated site conf) and then runs extra.
func scratchBuildStub(t *testing.T, ran *int, extra func(workdir string)) func(context.Context, string, bool, []deployStep) ([]deployStep, error) {
	return func(_ context.Context, workdir string, _ bool, steps []deployStep) ([]deployStep, error) {
		*ran++
		wf(t, filepath.Join(workdir, "docker-compose.yml"), build.ComposeGeneratedHeader+"services:\n  web:\n    volumes:\n      - "+workdir+"/nginx:/etc/nginx:ro\n")
		wf(t, filepath.Join(workdir, ".nself", "compose-files.txt"), filepath.Join(workdir, "docker-compose.yml")+"\n")
		wf(t, filepath.Join(workdir, ".nself", "compose-env-files.txt"), filepath.Join(workdir, ".env")+"\n")
		wf(t, filepath.Join(workdir, "nginx", "sites", "api.conf"), testBuildMarker+"server { listen 80; }\n")
		wf(t, filepath.Join(workdir, "nginx", "conf.d", "default.conf"), testBuildMarker+"# default\n")
		if extra != nil {
			extra(workdir)
		}
		return steps, nil
	}
}

func useScratchBuild(t *testing.T, fn func(context.Context, string, bool, []deployStep) ([]deployStep, error)) {
	t.Helper()
	old := deployScratchBuildFn
	t.Cleanup(func() { deployScratchBuildFn = old })
	deployScratchBuildFn = fn
}

// stdoutOf runs fn with os.Stdout redirected (the shared captureStdout helper)
// and returns what it printed.
func stdoutOf(t *testing.T, fn func()) string {
	t.Helper()
	out, _ := captureStdout(t, func() error { fn(); return nil })
	return out
}

// nginxProject is an operator project with marked, unmarked and conf.d nginx files.
func nginxProject(t *testing.T, env string) string {
	t.Helper()
	root := t.TempDir()
	wf(t, filepath.Join(root, ".env"), "PROJECT_NAME=demo\n"+env)
	wf(t, filepath.Join(root, "nginx", "sites", "stale.conf"), testBuildMarker+"# stale generated output\n")
	wf(t, filepath.Join(root, "nginx", "sites", "hand.conf"), "# hand written\n")
	wf(t, filepath.Join(root, "nginx", "includes", "extra.conf"), "# hand include\n")
	wf(t, filepath.Join(root, "nginx", "conf.d", "default.conf"), testBuildMarker+"# stale default\n")
	wf(t, filepath.Join(root, "nginx", "conf.d", "custom-example-com.conf"), "# Generated by nself ssl add\nserver {}\n")
	wf(t, filepath.Join(root, "nginx", "conf.d", "bluegreen-upstream.conf"), "upstream nself_api { server 127.0.0.1:8080; }\n")
	return root
}

func TestScratchCopyLeavesOnlyStaleGeneratedNginxFiles(t *testing.T) {
	proj := nginxProject(t, "")
	scratch := filepath.Join(t.TempDir(), "scratch")
	if err := scratchCopyProject(proj, scratch, &deploy.NginxPolicy{Generated: build.IsGeneratedNginxConf}); err != nil {
		t.Fatal(err)
	}
	for _, gone := range []string{"nginx/sites/stale.conf", "nginx/conf.d/default.conf"} {
		if _, err := os.Lstat(filepath.Join(scratch, filepath.FromSlash(gone))); err == nil {
			t.Errorf("%s carries the build marker and must not be copied: the build regenerates what it owns", gone)
		}
	}
	for _, kept := range []string{"nginx/sites/hand.conf", "nginx/includes/extra.conf", "nginx/conf.d/custom-example-com.conf", "nginx/conf.d/bluegreen-upstream.conf"} {
		if _, err := os.Lstat(filepath.Join(scratch, filepath.FromSlash(kept))); err != nil {
			t.Errorf("%s must still be copied (the build may read it): %v", kept, err)
		}
	}
	// The operator's tree is untouched.
	if _, err := os.Stat(filepath.Join(proj, "nginx", "sites", "stale.conf")); err != nil {
		t.Errorf("the operator's file is gone: %v", err)
	}
}

// Writers outside the build never stamp the build marker, so their files read as
// hand-managed here: not shipped unless allowlisted (conf.d never).
func TestNonBuildNginxWritersAreNotBuildGenerated(t *testing.T) {
	for name, head := range map[string]string{
		"nself ssl add custom-domain conf": "# Generated by nself ssl add\nserver {}\n",
		"blue/green upstream conf":         "upstream nself_api {\n    server 127.0.0.1:8080 weight=100;   # blue\n}\n",
		"hand written":                     "# my own\n",
		"marker past the head window":      strings.Repeat("#", 200) + testBuildMarker,
	} {
		if build.IsGeneratedNginxConf([]byte(head)) {
			t.Errorf("%s is treated as written by the build", name)
		}
	}
	for name, head := range map[string]string{
		"service conf": testBuildMarker, "plugin conf": "# Generated by nself build\nlocation / {}\n", "default.conf": testBuildMarker + "# default\n",
	} {
		if !build.IsGeneratedNginxConf([]byte(head)) {
			t.Errorf("%s is not recognised as generated", name)
		}
	}
}

func TestScratchStageShipsGeneratedAndAllowlisted(t *testing.T) {
	cases := []struct {
		name, env  string
		shipped    []string
		notShipped []string
	}{
		{"marker only", "", []string{"nginx/sites/api.conf", "nginx/conf.d/default.conf"}, []string{"nginx/includes/extra.conf", "nginx/sites/hand.conf"}},
		{"allowlist", "NSELF_DEPLOY_NGINX_INCLUDE=sites/hand.conf, includes/*.conf\n", []string{"nginx/sites/api.conf", "nginx/sites/hand.conf", "nginx/includes/extra.conf"}, nil},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			proj := nginxProject(t, c.env)
			ran := 0
			useScratchBuild(t, scratchBuildStub(t, &ran, nil))
			scratch, err := runScratchBuild(context.Background(), proj, "staging", deploy.TargetSnapshot{})
			if err != nil {
				t.Fatal(err)
			}
			p := v15Params{workdir: proj, target: "staging", srv: controlplane.Server{Name: "s1", RemotePath: "/opt/nself"}}
			var set deploy.ArtifactSet
			out := stdoutOf(t, func() { set, err = stageScratch(p, scratch) })
			if err != nil {
				t.Fatal(err)
			}
			for _, want := range c.shipped {
				if !contains(set.Files, want) {
					t.Errorf("%s not shipped: %v", want, set.Files)
				}
			}
			if contains(set.Files, "nginx/sites/stale.conf") || contains(set.Files, "nginx/conf.d/custom-example-com.conf") || contains(set.Files, "nginx/conf.d/bluegreen-upstream.conf") {
				t.Errorf("a stale or non-build file shipped: %v", set.Files)
			}
			if strings.Join(set.NotShipped, ",") != strings.Join(c.notShipped, ",") {
				t.Errorf("NotShipped = %v, want %v", set.NotShipped, c.notShipped)
			}
			for _, np := range c.notShipped {
				if want := "  [not shipped] " + np + " (not generated by this build; add it to NSELF_DEPLOY_NGINX_INCLUDE to ship it)\n"; !strings.Contains(out, want) {
					t.Errorf("no report line %q in:\n%s", want, out)
				}
			}
			if len(c.notShipped) == 0 && strings.Contains(strings.ReplaceAll(out, "  [not shipped] nginx/sites/stale.conf (stale generated output this build did not regenerate)", ""), "[not shipped]") {
				t.Errorf("unexpected report:\n%s", out)
			}
			if i, j := strings.Index(out, "includes/extra.conf"), strings.Index(out, "sites/hand.conf"); i >= 0 && j >= 0 && i > j {
				t.Errorf("the report is not sorted:\n%s", out)
			}
		})
	}
}

func TestScratchBuildRefusesBadAllowlistBeforeBuilding(t *testing.T) {
	for _, bad := range []string{"/etc/nginx/x.conf", "../x.conf", "sites/../../x", "conf.d/default.conf", "conf.d-prod/x.conf"} {
		proj := nginxProject(t, "NSELF_DEPLOY_NGINX_INCLUDE="+bad+"\n")
		ran := 0
		useScratchBuild(t, scratchBuildStub(t, &ran, nil))
		_, err := runScratchBuild(context.Background(), proj, "staging", deploy.TargetSnapshot{})
		if err == nil || !strings.Contains(err.Error(), "NSELF_DEPLOY_NGINX_INCLUDE") || !strings.Contains(err.Error(), "nothing was sent") {
			t.Errorf("%q: err = %v", bad, err)
		}
		if ran != 0 {
			t.Errorf("%q: the build ran before the allowlist was refused", bad)
		}
	}
}

func frontedProject(t *testing.T) string {
	t.Helper()
	proj := nginxProject(t, "NGINX_FRONTED_BY=nself-web\n")
	return proj
}

// frontedStub is a scratch build for a fronted project: the per-service site
// confs go to the fronting stack's nginx/sites, as resolveNginxSitesDir does.
func frontedStub(t *testing.T, ran *int, ranIn *string, extra func(front string)) func(context.Context, string, bool, []deployStep) ([]deployStep, error) {
	return scratchBuildStub(t, ran, func(workdir string) {
		*ranIn = workdir
		sites, err := nginxtopo.ServedNginxDir(workdir, "nself-web")
		if err != nil {
			t.Errorf("the build could not resolve its fronting root from %s: %v", workdir, err)
			return
		}
		front := filepath.Dir(sites)
		wf(t, filepath.Join(sites, "sites", "api.conf"), testBuildMarker+"# root "+workdir+"/public\n# front "+front+"/nginx\n")
		wf(t, filepath.Join(sites, "sites", "other-stack.conf"), "# not ours\n")
		if extra != nil {
			extra(front)
		}
	})
}

func TestFrontedScratchStagesFront(t *testing.T) {
	proj := frontedProject(t)
	var ran int
	var ranIn string
	useScratchBuild(t, frontedStub(t, &ran, &ranIn, nil))
	snap := deploy.TargetSnapshot{
		SSL:      []deploy.CertDir{{Name: "project-example-com", Fullchain: true}},
		FrontSSL: []deploy.CertDir{{Name: "api-example-com", Fullchain: true, Privkey: true}},
	}
	scratch, err := runScratchBuild(context.Background(), proj, "staging", snap)
	if err != nil {
		t.Fatal(err)
	}
	front := filepath.Join(proj, ".nself", "deploy-build", "staging", "nself-web")
	if want := filepath.Join(front, "backend"); scratch != want || ranIn != want {
		t.Fatalf("scratch %q, build ran in %q, want %q", scratch, ranIn, want)
	}
	// The project's stub mirrors the project's certs; the fronting stack's mirrors
	// <front>/ssl/certificates from the snapshot (FrontSSL), PEM presence included.
	for stub, c := range map[string]string{filepath.Join(scratch, "ssl"): "project-example-com", filepath.Join(front, "ssl"): "api-example-com"} {
		if _, err := os.Stat(filepath.Join(stub, "certificates", c, "fullchain.pem")); err != nil {
			t.Errorf("ssl stub missing in %s: %v", stub, err)
		}
	}
	if _, err := os.Stat(filepath.Join(front, "ssl", "certificates", "api-example-com", "privkey.pem")); err != nil {
		t.Errorf("the front stub lost the privkey.pem presence: %v", err)
	}
	if _, err := os.Stat(filepath.Join(front, "ssl", "certificates", "project-example-com")); err == nil {
		t.Error("the front stub mirrors the project's certs instead of the fronting stack's")
	}
	if _, err := os.Stat(filepath.Join(proj, ".nself", "deploy-build", "staging", "docker-compose.yml")); err == nil {
		t.Error("the flat layout was used for a fronted project")
	}
	// A second run rebuilds the whole root, flat leftovers included.
	wf(t, filepath.Join(proj, ".nself", "deploy-build", "staging", "stale.txt"), "x")
	if _, err := runScratchBuild(context.Background(), proj, "staging", snap); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(proj, ".nself", "deploy-build", "staging", "stale.txt")); err == nil {
		t.Error("the scratch root was not cleared")
	}

	p := v15Params{workdir: proj, target: "staging", srv: controlplane.Server{Name: "s1", RemotePath: "/srv/nself-web/backend"}}
	var set deploy.ArtifactSet
	out := stdoutOf(t, func() { set, err = stageScratch(p, scratch) })
	if err != nil {
		t.Fatalf("a fronted project must stage, not be refused: %v", err)
	}
	if set.Front == nil || set.Front.RemotePath != "/srv/nself-web" || strings.Join(set.Front.Files, ",") != "nginx/sites/api.conf" {
		t.Fatalf("front root = %+v, want /srv/nself-web with nginx/sites/api.conf only", set.Front)
	}
	if strings.Contains(out, "[staged, not shipped]") || strings.Contains(out, "other-stack.conf") {
		t.Errorf("unexpected report:\n%s", out)
	}
	staged := filepath.Join(scratch, ".nself", "deploy-stage-front", "nginx", "sites", "api.conf")
	b, rerr := os.ReadFile(staged)
	if rerr != nil {
		t.Fatal(rerr)
	}
	if !strings.Contains(string(b), "# root /srv/nself-web/backend/public") || !strings.Contains(string(b), "# front /srv/nself-web/nginx") || strings.Contains(string(b), proj) {
		t.Errorf("front file not rewritten in both directions:\n%s", b)
	}
}

func TestFrontedLayoutMismatchIsRefusedBeforeStaging(t *testing.T) {
	proj := frontedProject(t)
	var ran int
	var ranIn string
	useScratchBuild(t, frontedStub(t, &ran, &ranIn, nil))
	scratch, err := runScratchBuild(context.Background(), proj, "staging", deploy.TargetSnapshot{})
	if err != nil {
		t.Fatal(err)
	}
	p := v15Params{workdir: proj, target: "staging", srv: controlplane.Server{Name: "s1", RemotePath: "/srv/other/backend"}}
	var serr error
	out := stdoutOf(t, func() { _, serr = stageScratch(p, scratch) })
	var ce *errs.CLIError
	if !errors.As(serr, &ce) || ce.Code != "E485" || !strings.Contains(serr.Error(), "nself-web") {
		t.Fatalf("err = %v, want E485 naming the fronting stack", serr)
	}
	if strings.Contains(out, "[staged, not shipped]") {
		t.Errorf("staged before the layout check:\n%s", out)
	}
}

func TestFrontedByIsOneSafePathElement(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("path element rules are POSIX here")
	}
	for _, bad := range []string{"../evil", "a/b", `a\b`, ".", "..", ".hidden", "bad\x01name"} {
		proj := nginxProject(t, "NGINX_FRONTED_BY='"+bad+"'\n")
		ran := 0
		useScratchBuild(t, scratchBuildStub(t, &ran, nil))
		if _, err := runScratchBuild(context.Background(), proj, "staging", deploy.TargetSnapshot{}); err == nil || ran != 0 {
			t.Errorf("NGINX_FRONTED_BY=%q: err %v, build ran %d times", bad, err, ran)
		}
	}
	// No fronting: the layout is the flat scratch dir, as before.
	proj := nginxProject(t, "")
	ran := 0
	useScratchBuild(t, scratchBuildStub(t, &ran, nil))
	scratch, err := runScratchBuild(context.Background(), proj, "staging", deploy.TargetSnapshot{})
	if err != nil || scratch != scratchDirFor(proj, "staging") {
		t.Errorf("unfronted scratch %q err %v", scratch, err)
	}
}

// The deploy side keeps its own copy of the marker text (it cannot import build);
// this pins it to the build's exported marker test, both directions.
func TestDeployNginxMarkerMatchesBuild(t *testing.T) {
	m := deploy.BuildNginxMarker
	if !build.IsGeneratedNginxConf([]byte(m)) {
		t.Errorf("build does not accept deploy.BuildNginxMarker %q", m)
	}
	if build.IsGeneratedNginxConf([]byte(m[:len(m)-1])) {
		t.Errorf("deploy.BuildNginxMarker %q is longer than the build marker", m)
	}
	if build.IsGeneratedNginxConf([]byte(strings.ToLower(m))) {
		t.Error("the marker test must be case-sensitive")
	}
}

