func wf(t *testing.T, p, body string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

// hashProject returns "path sha256 mode" for every entry outside skipPrefix.
func hashProject(t *testing.T, root, skipPrefix string) string {
	t.Helper()
	var lines []string
	_ = filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		rel, _ := filepath.Rel(root, p)
		if skipPrefix != "" && (rel == skipPrefix || strings.HasPrefix(rel, skipPrefix+string(filepath.Separator))) {
			return filepath.SkipDir
		}
		info, _ := d.Info()
		line := rel + " " + info.Mode().String() + " " + info.ModTime().String()
		if runtime.GOOS == "windows" && d.IsDir() {
			// NTFS updates a directory's time lazily after its children change: not a signal.
			line = rel + " " + info.Mode().String()
		}
		if d.Type().IsRegular() {
			b, _ := os.ReadFile(p)
			sum := sha256.Sum256(b)
			line += " " + hex.EncodeToString(sum[:])
		}
		lines = append(lines, line)
		return nil
	})
	sort.Strings(lines)
	return strings.Join(lines, "\n")
}

// seedProject is an operator project with everything a deploy must not disturb.
func seedProject(t *testing.T) string {
	t.Helper()
	isolateDeployConfigEnv(t)
	root := t.TempDir()
	wf(t, filepath.Join(root, ".env"), "PROJECT_NAME=demo\n")
	wf(t, filepath.Join(root, ".env.dev"), "ENV=dev\n")
	wf(t, filepath.Join(root, ".env.prod"), "ENV=prod\nSECRET=hunter2\n")
	wf(t, filepath.Join(root, ".env.computed"), "COMPUTED=1\n")
	wf(t, filepath.Join(root, "docker-compose.yml"), "# OLD local compose\n")
	wf(t, filepath.Join(root, "nginx", "sites", "hand.conf"), "# hand written\n")
	wf(t, filepath.Join(root, "hasura", "metadata", "version.yaml"), "version: 3\n")
	wf(t, filepath.Join(root, "ssl", "certificates", "operator-only", "fullchain.pem"), "OPERATOR CERT\n")
	wf(t, filepath.Join(root, ".volumes", "pg", "data"), "database bytes\n")
	wf(t, filepath.Join(root, "backups", "old.tar.gz"), "backup\n")
	wf(t, filepath.Join(root, "node_modules", "x", "index.js"), "x\n")
	wf(t, filepath.Join(root, ".git", "HEAD"), "ref: refs/heads/main\n")
	wf(t, filepath.Join(root, ".nself", "ci.yaml"), "version: 1\n")
	wf(t, filepath.Join(root, ".nself", "deploy-build", "prod", "stale.txt"), "left from the last deploy\n")
	if err := os.Symlink(filepath.Join(root, "nginx"), filepath.Join(root, "abs-link")); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	if err := os.Symlink("nginx/sites/hand.conf", filepath.Join(root, "rel-link")); err != nil {
		t.Fatal(err)
	}
	return root
}

// fakeScratchBuild stands in for `nself build` in the scratch dir: it writes
// the generated output there and records where it was run.
func fakeScratchBuild(t *testing.T, ranIn *string, remoteArg *bool, needStub []string) func(context.Context, string, bool, []deployStep) ([]deployStep, error) {
	return func(_ context.Context, workdir string, remote bool, steps []deployStep) ([]deployStep, error) {
		*ranIn, *remoteArg = workdir, remote
		for _, pem := range needStub {
			if _, err := os.Stat(filepath.Join(workdir, "ssl", "certificates", pem)); err != nil {
				t.Errorf("stub ssl file %s missing when the build ran: %v", pem, err)
			}
		}
		wf(t, filepath.Join(workdir, "docker-compose.yml"), build.ComposeGeneratedHeader+"services:\n  web:\n    build: .\n    volumes:\n      - "+workdir+"/nginx:/etc/nginx:ro\n")
		wf(t, filepath.Join(workdir, ".nself", "compose-files.txt"), filepath.Join(workdir, "docker-compose.yml")+"\n")
		wf(t, filepath.Join(workdir, ".nself", "compose-env-files.txt"), filepath.Join(workdir, ".env")+"\n")
		wf(t, filepath.Join(workdir, "nginx", "sites", "api.conf"), "# Generated by nself build - DO NOT EDIT MANUALLY\nssl_certificate /etc/nginx/ssl/certificates/api-example-com/fullchain.pem;\n")
		return steps, nil
	}
}

func TestDeployScratchUntouched(t *testing.T) {
	proj := seedProject(t)
	snap := deploy.TargetSnapshot{SSL: []deploy.CertDir{
		{Name: "api-example-com", Fullchain: true, Privkey: true, Chain: true},
		{Name: "www-example-com", Fullchain: true},
	}}
	var ranIn string
	var remoteArg bool
	old := deployScratchBuildFn
	defer func() { deployScratchBuildFn = old }()
	deployScratchBuildFn = fakeScratchBuild(t, &ranIn, &remoteArg, []string{"api-example-com/fullchain.pem", "api-example-com/privkey.pem", "api-example-com/chain.pem", "www-example-com/fullchain.pem"})

	before := hashProject(t, proj, filepath.Join(".nself", "deploy-build"))
	for run := 1; run <= 2; run++ { // the second run rebuilds the scratch dir
		scratch, err := runScratchBuild(context.Background(), proj, "prod", snap)
		if err != nil {
			t.Fatal(err)
		}
		if want := filepath.Join(proj, ".nself", "deploy-build", "prod"); scratch != want || ranIn != want || !remoteArg {
			t.Fatalf("scratch %q, build ran in %q (remote=%v), want %q", scratch, ranIn, remoteArg, want)
		}
		if after := hashProject(t, proj, filepath.Join(".nself", "deploy-build")); after != before {
			t.Fatalf("run %d changed the operator's project tree:\nbefore:\n%s\nafter:\n%s", run, before, after)
		}
		for _, gone := range []string{"stale.txt", "ssl/certificates/operator-only", ".volumes", "backups", "node_modules", ".git", ".nself/ci.yaml", "abs-link"} {
			if _, err := os.Lstat(filepath.Join(scratch, filepath.FromSlash(gone))); err == nil {
				t.Errorf("run %d: %s must not be in the scratch copy", run, gone)
			}
		}
		for _, kept := range []string{".env", ".env.prod", ".env.computed", "nginx/sites/hand.conf", "hasura/metadata/version.yaml", "rel-link", "ssl/certificates/api-example-com/chain.pem"} {
			if _, err := os.Lstat(filepath.Join(scratch, filepath.FromSlash(kept))); err != nil {
				t.Errorf("run %d: %s missing from the scratch copy: %v", run, kept, err)
			}
		}
		if _, err := os.Stat(filepath.Join(scratch, "ssl", "certificates", "www-example-com", "privkey.pem")); err == nil {
			t.Error("a stub appeared for a file the target does not have")
		}
		if b, _ := os.ReadFile(filepath.Join(scratch, "docker-compose.yml")); strings.Contains(string(b), "OLD") {
			t.Error("the previous docker-compose.yml was copied, so the freshness check could not prove this build wrote it")
		}
	}

	// The staged artifact set never holds the stub ssl tree, and an unmarked nginx
	// file the operator wrote is no longer shipped: it is reported instead (D-0423).
	scratch := scratchDirFor(proj, "prod")
	stage := filepath.Join(t.TempDir(), "stage")
	policy, err := nginxPolicyFor(proj, "prod")
	if err != nil {
		t.Fatal(err)
	}
	set, err := deploy.Stage(deploy.StageInput{
		Map:      deploy.PathMap{ScratchRoot: scratch, OperatorRoot: proj, PluginDir: filepath.Join(t.TempDir(), "plugins"), Home: filepath.Join(t.TempDir(), "home"), RemotePath: "/opt/nself"},
		StageDir: stage, Compose: []string{filepath.Join(scratch, "docker-compose.yml")}, EnvFiles: []string{filepath.Join(scratch, ".env")}, EnvName: "prod", Nginx: policy,
	})
	if err != nil {
		t.Fatal(err)
	}
	for _, rel := range append(set.Files, set.EnvFiles...) {
		if strings.HasPrefix(rel, "ssl/") {
			t.Errorf("%s would be shipped: the stub ssl tree must never be", rel)
		}
	}
	if !contains(set.Files, "nginx/sites/api.conf") || contains(set.Files, "nginx/sites/hand.conf") {
		t.Errorf("nginx files in the set: %v (api.conf generated by the build ships, hand.conf does not)", set.Files)
	}
	if len(set.NotShipped) != 1 || set.NotShipped[0] != "nginx/sites/hand.conf" {
		t.Errorf("NotShipped = %v, want hand.conf reported", set.NotShipped)
	}
}

func TestDeployBuildStepForMode(t *testing.T) {
	compattest.Set(t, true)
	steps := []deployStep{{Name: "keep", Status: "done"}}
	got, err := deployBuildStepForMode(context.Background(), t.TempDir(), true, steps)
	if err != nil || len(got) != 1 || got[0].Name != "keep" {
		t.Fatalf("v1.5 remote: want a no-op, got %v %v", got, err)
	}
}

// isolateDeployConfigEnv blanks every config key in the process. config.Load
// exports project .env files into the process, so an earlier test can leave keys
// that the remote-deploy guard would see as process-only config.
func isolateDeployConfigEnv(t *testing.T) {
	t.Helper()
	for _, key := range config.KnownEnvVars() {
		t.Setenv(key, "")
	}
	for _, entry := range os.Environ() {
		key, value, _ := strings.Cut(entry, "=")
		if value != "" && config.RemoteConfigKey(key) {
			t.Setenv(key, "")
		}
	}
}
