// A prod preview must not enter the installer or the removal path.
func TestExtensionPlanReadOnly(t *testing.T) {
	for _, add := range []bool{true, false} {
		t.Run(map[bool]string{true: "add", false: "remove"}[add], func(t *testing.T) {
			compattest.Set(t, true)
			p := extensionFixture(t, "prod")
			localPluginRegistry(t)
			t.Setenv("NSELF_SKIP_SBOM_CHECK", "1")
			l03Write(t, filepath.Join(p.plugins, "bin", "placeholder"), "binary", 0o755)
			if err := os.Symlink("placeholder", filepath.Join(p.plugins, "bin", "nself-placeholder")); err != nil {
				t.Fatal(err)
			}
			if !add {
				l03Write(t, filepath.Join(p.plugins, "zzfixture", "plugin.json"), `{"name":"zzfixture","version":"1.0.0"}`, 0o644)
				l03Write(t, filepath.Join(p.plugins, "zzfixture", "nginx", "route.conf"), "server { listen 80; server_name fixture.invalid; }\n", 0o644)
				l03Write(t, filepath.Join(p.project, "nginx", "sites", "zzfixture-route.conf"), "# Generated by nself build\nserver { listen 80; server_name fixture.invalid; }\n", 0o644)
			}
			before := p.tree(t, "")
			cmd, run := removeCmd, runRemove
			if add {
				cmd, run = installCmd, runInstall
			}
			if cmd.Flags().Lookup("plan") == nil {
				t.Fatal("missing --plan flag")
			}
			if err := cmd.Flags().Set("plan", "true"); err != nil {
				t.Fatal(err)
			}
			t.Cleanup(func() { _ = cmd.Flags().Set("plan", "false"); cmd.SetOut(nil) })
			var out bytes.Buffer
			cmd.SetOut(&out)
			if err := run(cmd, []string{"zzfixture"}); err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(out.String(), "zzfixture") {
				t.Fatalf("missing plugin in plan: %s", out.String())
			}
			if !strings.Contains(out.String(), "zzfixture-route.conf") {
				t.Fatalf("plugin route missing from plan: %s", out.String())
			}
			if after := p.tree(t, ""); after != before {
				t.Fatalf("preview changed filesystem\nbefore:\n%s\nafter:\n%s", before, after)
			}
			if _, err := os.Stat(filepath.Join(p.project, "docker-compose.yml")); !os.IsNotExist(err) {
				t.Fatal("preview wrote compose")
			}
		})
	}
}

func TestExtensionPlanJSON(t *testing.T) {
	p := extensionFixture(t, "prod")
	l03Write(t, filepath.Join(p.plugins, "zzfixture", "plugin.json"), `{"name":"zzfixture","version":"1.0.0"}`, 0o644)
	out, err := jsonV15(t, removeCmd, map[string]string{"json": "true", "plan": "true"}, func() error {
		return removeCmd.RunE(removeCmd, []string{"zzfixture"})
	})
	if err != nil {
		t.Fatal(err)
	}
	doc := oneEnvelope(t, out, "remove")
	var data struct {
		DryRun  bool            `json:"dry_run"`
		Plan    json.RawMessage `json:"plan"`
		Removed []string        `json:"removed"`
	}
	if err := json.Unmarshal(doc["data"], &data); err != nil {
		t.Fatal(err)
	}
	if !data.DryRun || len(data.Removed) != 0 || len(data.Plan) == 0 {
		t.Fatalf("not a read-only plan: %s", out)
	}
	if _, err := os.Stat(filepath.Join(p.plugins, "zzfixture")); err != nil {
		t.Fatal(err)
	}
}

func TestExtensionPlanRefusesUnsupported(t *testing.T) {
	for _, name := range []string{"https://example.com/plugin.tar.gz", "nchat", "admin", "../escape"} {
		if err := validateExtensionPlan(installCmd, []string{name}); err == nil {
			t.Errorf("accepted unsupported %q", name)
		}
	}
}

func TestExtensionPlanRemovalDependency(t *testing.T) {
	p := extensionFixture(t, "prod")
	l03Write(t, filepath.Join(p.plugins, "zzfixture", "plugin.json"), `{"name":"zzfixture","version":"1.0.0"}`, 0o644)
	l03Write(t, filepath.Join(p.plugins, "dependent", "plugin.json"), `{"name":"dependent","version":"1.0.0","description":"fixture","category":"utility","license":"MIT","dependencies":["zzfixture"]}`, 0o644)
	before := p.tree(t, "")
	if err := runExtensionPlan(removeCmd, []string{"zzfixture"}, false); err == nil || !strings.Contains(err.Error(), "depend") {
		t.Fatalf("missing dependency refusal: %v", err)
	}
	if after := p.tree(t, ""); before != after {
		t.Fatal("refusal changed live state")
	}
}

func TestExtensionPlanForceAcknowledgement(t *testing.T) {
	compattest.Set(t, true)
	p := extensionFixture(t, "dev")
	localPluginRegistry(t)
	t.Setenv("NSELF_SKIP_SBOM_CHECK", "1")
	t.Setenv("NSELF_LICENSE_SKIP_VERIFY", "1")
	t.Setenv("NSELF_LICENSE_SKIP_VERIFY_FORCE", "")
	if err := installCmd.Flags().Set("force", "true"); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = installCmd.Flags().Set("force", "false"); installCmd.SetOut(nil) })
	var out bytes.Buffer
	installCmd.SetOut(&out)
	before := p.tree(t, "")
	if err := runExtensionPlan(installCmd, []string{"zzfixture"}, true); err != nil {
		t.Fatal(err)
	}
	if after := p.tree(t, ""); after != before {
		t.Fatal("force preview changed live state")
	}
}
