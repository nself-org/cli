package commands

// Purpose: which nginx files a v1.5 remote deploy ships from the scratch build
//          (D-0423). The scratch copy brings the operator's whole nginx/ tree
//          along because the build may read it, but only files this build
//          generated ship, plus the files the operator names in
//          NSELF_DEPLOY_NGINX_INCLUDE. Anything else is reported as not shipped
//          (a dry run shows it).
// Inputs:  the operator project, the deploy target, the scratch nginx/ tree.
// Outputs: the scratch copy without marker-carrying nginx files, the
//          deploy.NginxPolicy for Stage, and the "[not shipped]" report.
// Constraints: "generated by this build" is the marker the build stamps
//              (build.IsGeneratedNginxConf). The scratch copy leaves out every
//              marker-carrying nginx/ file of the operator's tree (stale
//              generated output; the build regenerates what it owns) unless the
//              file matches the allowlist, so after the build every
//              marker-carrying file in scratch nginx/ was written by it or was
//              allowlisted. A skipped file the build did not write again is
//              reported as stale (staleGeneratedNginx). Writers outside the
//              build never stamp that exact marker: `nself ssl add` writes
//              conf.d/custom-*.conf stamped "# Generated by nself ssl add", the
//              blue/green upstream conf (conf.d/bluegreen-upstream.conf) has no
//              marker, and the build itself regenerates nginx.conf,
//              includes/rate-limits.conf, conf.d/default.conf and sites/*.conf
//              (services, plugin routes, api-docs). One writer inside the build
//              stamps nothing: plugin configs/ files (internal/build/
//              plugin_configs.go renders them to any project-relative path, with
//              no marker). No plugin renders into nginx/ today; one that did would
//              be reported [not shipped] and need NSELF_DEPLOY_NGINX_INCLUDE. So
//              the built-in allowlist is empty; the unmarked files of the other
//              writers need NSELF_DEPLOY_NGINX_INCLUDE (or, under conf.d, are
//              never shipped: D-0424).

import (
	"fmt"
	"io"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"

	"github.com/nself-org/cli/internal/build"
	"github.com/nself-org/cli/internal/deploy"
	"github.com/nself-org/cli/internal/nginxtopo"
)

// deployNginxIncludeEnv is the operator allowlist: comma-separated globs
// relative to nginx/ for files that should ship, including marked sites that
// the scratch build's stale-site prune would otherwise remove.
const deployNginxIncludeEnv = "NSELF_DEPLOY_NGINX_INCLUDE"

// scratchLeavesGenerated reports whether the scratch copy must leave out the
// regular file at p (rel is its project-relative path): a marker-carrying file
// under nginx/ that the operator did not allowlist. The build regenerates what
// it owns; a file it does not own that carries the marker is stale generated
// output and must not ship as new. An allowlisted file is copied (and ships)
// even when it carries the marker.
func scratchLeavesGenerated(p, rel string, policy *deploy.NginxPolicy) bool {
	top, sub, _ := strings.Cut(filepath.ToSlash(rel), "/")
	if top != "nginx" || policy.Allows(sub) {
		return false
	}
	f, err := os.Open(p)
	if err != nil {
		return false
	}
	defer func() { _ = f.Close() }()
	head := make([]byte, build.NginxGeneratedHeadBytes)
	n, _ := io.ReadFull(f, head)
	return build.IsGeneratedNginxConf(head[:n])
}

// deployCascadeValue returns key as the build resolves it for target: the last
// value in the target's env cascade (config.Load applies the files with
// godotenv.Overload, so a file beats the process environment), else the process
// environment, else "".
func deployCascadeValue(workdir, target, key string) (string, error) {
	val, found := "", false
	for _, f := range deployEnvCascadeFiles(workdir, target) {
		pairs, err := readEnvFileOverrides(f)
		if err != nil {
			return "", fmt.Errorf("reading %s: %w", f, err)
		}
		for _, kv := range pairs {
			if kv.key == key {
				val, found = kv.value, true
			}
		}
	}
	if !found {
		val = os.Getenv(key)
	}
	return val, nil
}

// nginxPolicyFor is the Stage policy of a deploy of target: files carrying the
// build marker ship, as do the files NSELF_DEPLOY_NGINX_INCLUDE names. An
// invalid allowlist entry fails the deploy before anything is sent.
func nginxPolicyFor(workdir, target string) (*deploy.NginxPolicy, error) {
	raw, err := deployCascadeValue(workdir, target, deployNginxIncludeEnv)
	if err != nil {
		return nil, err
	}
	include, err := deploy.ParseNginxInclude(raw)
	if err != nil {
		return nil, fmt.Errorf("deploy: %w; nothing was sent", err)
	}
	return &deploy.NginxPolicy{Generated: build.IsGeneratedNginxConf, Include: include}, nil
}

// reportNotShipped prints the nginx files the stage left out, sorted.
func reportNotShipped(w io.Writer, notShipped []string) {
	sorted := append([]string{}, notShipped...)
	sort.Strings(sorted)
	for _, rel := range sorted {
		_, _ = fmt.Fprintf(w, "  [not shipped] %s (not generated by this build; add it to %s to ship it)\n", rel, deployNginxIncludeEnv)
	}
}

// staleGeneratedNginx lists the marker-carrying nginx/ files of the operator's
// project that the scratch copy left out and the build did not write again
// ("nginx/<rel>", sorted): stale generated output. An allowlisted file was copied
// and so is never listed.
func staleGeneratedNginx(workdir, scratch string) []string {
	root, _ := nginxtopo.ServedNginxDir(workdir, "") // the project's own nginx dir
	scratchNginx, _ := nginxtopo.ServedNginxDir(scratch, "")
	var stale []string
	_ = filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil || !d.Type().IsRegular() {
			return nil
		}
		sub, _ := filepath.Rel(root, p)
		head := make([]byte, build.NginxGeneratedHeadBytes)
		f, oerr := os.Open(p)
		if oerr != nil {
			return nil
		}
		n, _ := io.ReadFull(f, head)
		_ = f.Close()
		if !build.IsGeneratedNginxConf(head[:n]) {
			return nil
		}
		if _, serr := os.Lstat(filepath.Join(scratchNginx, sub)); serr != nil {
			stale = append(stale, path.Join(filepath.Base(root), filepath.ToSlash(sub)))
		}
		return nil
	})
	sort.Strings(stale)
	return stale
}

// reportStale prints the stale generated files the build did not regenerate.
func reportStale(w io.Writer, stale []string) {
	for _, rel := range stale {
		_, _ = fmt.Fprintf(w, "  [not shipped] %s (stale generated output this build did not regenerate)\n", rel)
	}
}
