// Package lock is the project lock nself.lock.yaml (contract:cli.lockfile v1,
// P7-LIVE-09, EPIC D10): which CLI minor, service images and plugin versions a
// project was built with.
//
// Purpose: reproducible stacks. `nself build` writes the file when its inputs
// change and honours its image pins; `nself start --frozen` fails when the
// stack on disk no longer matches it. The file lives at the project root
// because init gitignores .nself/ and git cannot re-include a file under an
// ignored directory.
// Inputs: the project directory (Load) or bytes (Parse); a Lock value
// (Marshal).
// Outputs: canonical bytes (header comment, schema_version, cli, images,
// unpinned, plugins, bundles; map keys sorted, no timestamps), a parsed Lock,
// and the Mismatch list of Compare.
// Constraints: pure (stdlib plus gopkg.in/yaml.v3), no I/O except Load. The
// `cli` field records major.minor only, so a patch upgrade never rewrites a
// committed file. Unknown keys are rejected, so a newer schema is never read
// half-way.
package lock

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"sort"

	"gopkg.in/yaml.v3"
)

const (
	// FileName is the lock's name at the project root.
	FileName = "nself.lock.yaml"
	// Header is the first line of every written lock.
	Header = "# GENERATED BY nself build — DO NOT HAND EDIT (change pins with nself update)"
	// SchemaVersion is the only schema_version this package reads or writes.
	SchemaVersion = 1
	// MaxBytes caps the size of a lock that Parse and Load accept.
	MaxBytes = 4 << 20

	// TierFree and TierLicensed are the plugin tiers (same words as the bundle ledger).
	TierFree     = "free"
	TierLicensed = "licensed"

	// KeyPattern is the shape of a service, plugin or bundle name used as a key.
	KeyPattern = `^[a-z0-9][a-z0-9._-]*$`
	// PinnedPattern is an image reference carrying a sha256 digest.
	PinnedPattern = `^[^\s@]+@sha256:[0-9a-f]{64}$`
	// UnpinnedPattern is a tag-only image reference (no digest).
	UnpinnedPattern = `^[^\s@]+$`
	// ChecksumPattern is a lowercase hex sha256, or empty when unknown.
	ChecksumPattern = `^([0-9a-f]{64})?$`
	// CLIPattern is major.minor, or empty for a build that has no release version.
	CLIPattern = `^([0-9]+\.[0-9]+)?$`
)

var (
	keyRE      = regexp.MustCompile(KeyPattern)
	pinnedRE   = regexp.MustCompile(PinnedPattern)
	unpinnedRE = regexp.MustCompile(UnpinnedPattern)
	checksumRE = regexp.MustCompile(ChecksumPattern)
	cliRE      = regexp.MustCompile(CLIPattern)
)

// Tiers lists the accepted plugin tiers.
var Tiers = []string{TierFree, TierLicensed}

// ErrNotFound means the project has no nself.lock.yaml. Test with errors.Is.
var ErrNotFound = errors.New("lock: no nself.lock.yaml in this project")

// PluginPin pins one installed plugin.
type PluginPin struct {
	Version string `yaml:"version" json:"version"`
	SHA256  string `yaml:"sha256" json:"sha256"`
	Tier    string `yaml:"tier" json:"tier"`
}

// Lock is the file. Field order is the on-disk key order.
type Lock struct {
	SchemaVersion int `yaml:"schema_version" json:"schema_version"`
	// CLI is the CLI major.minor that wrote the file.
	CLI string `yaml:"cli" json:"cli"`
	// Images maps a compose service to its digest-pinned reference.
	Images map[string]string `yaml:"images" json:"images"`
	// Unpinned maps a service to a tag-only reference whose digest is unknown.
	Unpinned map[string]string `yaml:"unpinned" json:"unpinned"`
	// Plugins maps a plugin slug to its pin, from the bundle ledger.
	Plugins map[string]PluginPin `yaml:"plugins" json:"plugins"`
	// Bundles lists the installed bundles, sorted.
	Bundles []string `yaml:"bundles" json:"bundles"`
}

// New returns an empty, valid lock.
func New() Lock {
	return Lock{SchemaVersion: SchemaVersion, Images: map[string]string{}, Unpinned: map[string]string{}, Plugins: map[string]PluginPin{}, Bundles: []string{}}
}

// normalize defaults a zero schema_version, replaces nil collections with empty
// ones and sorts Bundles.
func (l *Lock) normalize() {
	if l.SchemaVersion == 0 {
		l.SchemaVersion = SchemaVersion
	}
	if l.Images == nil {
		l.Images = map[string]string{}
	}
	if l.Unpinned == nil {
		l.Unpinned = map[string]string{}
	}
	if l.Plugins == nil {
		l.Plugins = map[string]PluginPin{}
	}
	b := append([]string{}, l.Bundles...)
	sort.Strings(b)
	l.Bundles = b
}

// Validate checks every rule the JSON Schema states.
func (l Lock) Validate() error {
	if l.SchemaVersion != SchemaVersion {
		return fmt.Errorf("lock: unsupported schema_version %d (this nself reads %d)", l.SchemaVersion, SchemaVersion)
	}
	if !cliRE.MatchString(l.CLI) {
		return fmt.Errorf("lock: cli %q is not major.minor", l.CLI)
	}
	for k, v := range l.Images {
		if !keyRE.MatchString(k) || !pinnedRE.MatchString(v) {
			return fmt.Errorf("lock: images[%q] = %q is not <service>: <ref>@sha256:<64 hex>", k, v)
		}
	}
	for k, v := range l.Unpinned {
		if !keyRE.MatchString(k) || !unpinnedRE.MatchString(v) {
			return fmt.Errorf("lock: unpinned[%q] = %q is not a tag-only reference", k, v)
		}
		if _, dup := l.Images[k]; dup {
			return fmt.Errorf("lock: service %q is both pinned and unpinned", k)
		}
	}
	for k, p := range l.Plugins {
		if !keyRE.MatchString(k) {
			return fmt.Errorf("lock: plugin slug %q does not match %s", k, KeyPattern)
		}
		if p.Tier != TierFree && p.Tier != TierLicensed {
			return fmt.Errorf("lock: plugin %q tier %q is neither free nor licensed", k, p.Tier)
		}
		if !checksumRE.MatchString(p.SHA256) {
			return fmt.Errorf("lock: plugin %q sha256 is not lowercase hex", k)
		}
	}
	seen := map[string]bool{}
	for _, b := range l.Bundles {
		if !keyRE.MatchString(b) || seen[b] {
			return fmt.Errorf("lock: bundle %q is malformed or listed twice", b)
		}
		seen[b] = true
	}
	return nil
}

// Marshal validates l and renders the canonical bytes. It does not change l.
func (l Lock) Marshal() ([]byte, error) {
	c := l
	c.normalize()
	if err := c.Validate(); err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	buf.WriteString(Header + "\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(c); err != nil {
		return nil, fmt.Errorf("lock: encode: %w", err)
	}
	if err := enc.Close(); err != nil {
		return nil, fmt.Errorf("lock: encode: %w", err)
	}
	return buf.Bytes(), nil
}

// Parse reads and validates lock bytes.
func Parse(data []byte) (Lock, error) {
	if len(data) > MaxBytes {
		return Lock{}, fmt.Errorf("lock: file is larger than %d bytes", MaxBytes)
	}
	var l Lock
	dec := yaml.NewDecoder(bytes.NewReader(data))
	dec.KnownFields(true)
	if err := dec.Decode(&l); err != nil {
		if errors.Is(err, io.EOF) {
			return Lock{}, errors.New("lock: file is empty")
		}
		return Lock{}, fmt.Errorf("lock: parse: %w", err)
	}
	l.normalize()
	if err := l.Validate(); err != nil {
		return Lock{}, err
	}
	return l, nil
}

// Path is the lock file of the project at dir.
func Path(dir string) string { return filepath.Join(dir, FileName) }

// Load reads the project's lock. A missing file wraps ErrNotFound (and
// os.ErrNotExist); a damaged one is an error that names the file.
func Load(dir string) (*Lock, error) {
	data, err := os.ReadFile(Path(dir))
	if errors.Is(err, os.ErrNotExist) {
		return nil, fmt.Errorf("%w: %w", ErrNotFound, err)
	}
	if err != nil {
		return nil, fmt.Errorf("lock: read %s: %w", Path(dir), err)
	}
	l, err := Parse(data)
	if err != nil {
		return nil, fmt.Errorf("%w (file %s)", err, Path(dir))
	}
	return &l, nil
}

// PluginVersion returns the pinned version of a plugin, as the ci plugin pin
// of P7-CANON-13 reads it.
func (l *Lock) PluginVersion(slug string) (string, bool) {
	if l == nil {
		return "", false
	}
	p, ok := l.Plugins[slug]
	if !ok || p.Version == "" {
		return "", false
	}
	return p.Version, true
}

// Pins returns every service pin, digest-pinned and tag-only, in one map.
func (l *Lock) Pins() map[string]string {
	out := map[string]string{}
	if l == nil {
		return out
	}
	for k, v := range l.Unpinned {
		out[k] = v
	}
	for k, v := range l.Images {
		out[k] = v
	}
	return out
}
