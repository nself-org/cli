package lock

// mirror.go — keeps the registry-mirror override file (.nself/state/image-overrides.yml)
// from outliving the pin it was written for (contract:cli.lockfile v1, P7-LIVE-09).
//
// Purpose: `nself start` writes the file when it pulled a CLI-owned image from a
// registry mirror. The entry names the mirror reference and the digest of the
// image it replaced. After `nself build` moves the pin, an entry for the old
// digest would make `start --frozen` fail with E455 and `nself build` never
// cleared it. PruneMirror drops those entries.
// Inputs: the file's bytes and the images the compose files render without it.
// Outputs: the file's new bytes, the services whose entry was dropped; nil bytes
// and no error mean the file has no entry left and should be removed.
// Constraints: pure. An entry stays only when its digest equals the digest of
// the service's rendered image. The output keeps the generator's header and
// layout, so start's own rewrite sees identical bytes.

import (
	"fmt"
	"sort"

	"gopkg.in/yaml.v3"
)

// MirrorHeader is the first line of the generated file (written by internal/docker).
const MirrorHeader = "# GENERATED BY nself — DO NOT HAND EDIT\n"

// PruneMirror drops the entries of the mirror override file that no longer
// match rendered (service -> image of the compose files without the file).
func PruneMirror(data []byte, rendered map[string]string) (out []byte, dropped []string, err error) {
	var doc struct {
		Services map[string]map[string]any `yaml:"services"`
	}
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, nil, fmt.Errorf("lock: parse image overrides: %w", err)
	}
	for svc, v := range doc.Services {
		img, _ := v["image"].(string)
		d := RefDigest(img)
		if d == "" || d != RefDigest(rendered[svc]) {
			dropped = append(dropped, svc)
			delete(doc.Services, svc)
		}
	}
	sort.Strings(dropped)
	if len(dropped) == 0 {
		return data, nil, nil
	}
	if len(doc.Services) == 0 {
		return nil, dropped, nil
	}
	body, err := yaml.Marshal(map[string]any{"services": doc.Services})
	if err != nil {
		return nil, nil, fmt.Errorf("lock: render image overrides: %w", err)
	}
	return append([]byte(MirrorHeader), body...), dropped, nil
}
