package reconcile

import (
	"context"
	"os"
	"path/filepath"
	"testing"

	"github.com/nself-org/cli/internal/compat/compattest"
	"github.com/nself-org/cli/internal/errs"
)

func TestUnrecordedMarkedFiles(t *testing.T) {
	for _, missingState := range []bool{false, true} {
		t.Run(map[bool]string{false: "missing entry", true: "missing state"}[missingState], func(t *testing.T) {
			compattest.Set(t, true)
			f := loadFixture(t, "dev-minimal")
			req := Request{Runtime: &fakeRuntime{}, ProjectDir: f.project, Seed: []byte("seed")}
			if _, err := Apply(context.Background(), req, ApplyOptions{Yes: true, Force: true}); err != nil {
				t.Fatal(err)
			}
			target := filepath.Join(f.project, "docker-compose.yml")
			body, err := os.ReadFile(target)
			if err != nil {
				t.Fatal(err)
			}
			edited := append(body, []byte("\n# hand edit\n")...)
			if err := os.WriteFile(target, edited, 0644); err != nil {
				t.Fatal(err)
			}
			orphan := filepath.Join(f.project, "nginx/sites/foreign-copy.conf")
			const copyBody = "# Generated by nself build\n# hand-edited copy\n"
			if err := os.WriteFile(orphan, []byte(copyBody), 0644); err != nil {
				t.Fatal(err)
			}
			if missingState {
				if err := os.Remove(GeneratedStatePath(f.project)); err != nil {
					t.Fatal(err)
				}
			} else {
				state, err := LoadGeneratedState(f.project)
				if err != nil {
					t.Fatal(err)
				}
				delete(state.Files, "docker-compose.yml")
				if err := state.Save(f.project); err != nil {
					t.Fatal(err)
				}
			}
			before := treeHash(t, f.root)
			_, err = Apply(context.Background(), req, ApplyOptions{Yes: true})
			if err == nil || errs.Describe(err) == nil || errs.Describe(err).Code != "E403" {
				t.Fatalf("want E403, got %v", err)
			}
			if after := treeHash(t, f.root); before != after {
				t.Fatal("refusal changed tree")
			}
			if _, err := Apply(context.Background(), req, ApplyOptions{Yes: true, Force: true}); err != nil {
				t.Fatal(err)
			}
			if got, err := os.ReadFile(orphan); err != nil || string(got) != copyBody {
				t.Fatalf("foreign copy lost: %v", err)
			}
		})
	}
}
