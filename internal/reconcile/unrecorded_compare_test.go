package reconcile

import "testing"

func TestUnrecordedMarkedComparison(t *testing.T) {
	for _, row := range []struct {
		name, current, fresh string
		want                 bool
	}{
		{"same", "# Generated by nself\n", "# Generated by nself\n", false},
		{"edited", "# Generated by nself\n# edit\n", "# Generated by nself\n", true},
		{"unmarked", "user file", "# Generated by nself\n", false},
	} {
		t.Run(row.name, func(t *testing.T) {
			before := ArtifactSet{"file": {Data: []byte(row.current)}}
			after := ArtifactSet{"file": {Data: []byte(row.fresh)}}
			for _, state := range []*GeneratedState{nil, {Files: map[string]string{}}} {
				if got := unrecordedHandEdited(before, after, state, nil)("file"); got != row.want {
					t.Fatalf("hand edited = %v, want %v", got, row.want)
				}
			}
		})
	}
}
