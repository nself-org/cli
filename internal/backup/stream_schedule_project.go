package backup

// stream_schedule_project.go — project and environment checks for `backup schedule`.
//
// Purpose: decide whether a directory is an nSelf project and which ENV selector the generated unit must carry, split out of stream_schedule.go for file size.
// Inputs: a project directory, plus the ENV the process was started with (scheduleProcessEnv).
// Outputs: a project yes/no, the ENV selector string, and the service text with an Environment=ENV= line added, or an error for an unsafe selector.
// Constraints: no .nself marker (the CLI creates <cwd>/.nself itself before `backup schedule` runs, so it proves nothing); the selector is validated before it reaches a unit (D-0245, D-0277).

import (
	"bufio"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/joho/godotenv"
)

// scheduleProcessEnv is the ENV the process was started with. It is read at
// program start, before config.Load runs: the loader calls godotenv.Overload,
// which rewrites the process ENV from .env, so a later os.Getenv("ENV") can
// differ from what the operator exported. Tests replace it.
var scheduleProcessEnv = os.Getenv("ENV")

// scheduleEnvRe is the set of characters an ENV selector may use when written
// into the unit as Environment=ENV=<name>. It is never empty.
var scheduleEnvRe = regexp.MustCompile(`^[A-Za-z0-9._-]+$`)

// composeGeneratedHeader is the first line of build.ComposeGeneratedHeader in
// internal/build/orchestrator_compose.go, which `nself build` writes at the top
// of docker-compose.yml. It is copied here so this package does not import
// internal/build; keep the two in step.
const composeGeneratedHeader = "# GENERATED BY nself build"

// looksLikeProject reports whether dir is an nSelf project: it has a .env AND
// at least one nSelf marker. The markers are nself.yaml, nself.yml, or a
// docker-compose.yml whose first line is the header `nself build` writes. A
// hand-written compose file is not a marker. A .nself directory is not one
// either: the CLI creates <cwd>/.nself (project lock, licence cache) before
// `backup schedule` runs, so it would pass in any directory.
func looksLikeProject(dir string) bool {
	if fi, err := os.Stat(filepath.Join(dir, ".env")); err != nil || fi.IsDir() {
		return false
	}
	for _, m := range []string{"nself.yaml", "nself.yml"} {
		if fi, err := os.Stat(filepath.Join(dir, m)); err == nil && !fi.IsDir() {
			return true
		}
	}
	return composeHasGeneratedHeader(filepath.Join(dir, "docker-compose.yml"))
}

// composeHasGeneratedHeader reports whether the first line of the compose file
// at path starts with composeGeneratedHeader. Only the first line is read, and
// that read is bounded, so a huge or odd file costs nothing.
func composeHasGeneratedHeader(path string) bool {
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer func() { _ = f.Close() }()
	line, _ := bufio.NewReaderSize(io.LimitReader(f, 512), 512).ReadString('\n')
	return strings.HasPrefix(line, composeGeneratedHeader)
}

// scheduleEnvSelector returns the ENV value that picked the env cascade for
// projectDir, in the order config.ResolveEnv uses: the ENV the process was
// started with, else the ENV key of <projectDir>/.env, else "dev". The raw
// value is returned; the loader normalises it again when the unit runs.
// godotenv.Read does not touch os.Environ. A missing .env falls through to
// "dev"; an unreadable or unparseable one is an error, because the unit would
// otherwise be written for "dev" while the nightly run fails on the same file.
func scheduleEnvSelector(projectDir string) (string, error) {
	if scheduleProcessEnv != "" {
		return scheduleProcessEnv, nil
	}
	m, err := godotenv.Read(filepath.Join(projectDir, ".env"))
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return "dev", nil
		}
		return "", fmt.Errorf("read the ENV selector from %s: %w", filepath.Join(projectDir, ".env"), err)
	}
	if m["ENV"] != "" {
		return m["ENV"], nil
	}
	return "dev", nil
}

// checkScheduleEnv refuses a selector that could add a directive or expand in
// systemd when written as Environment=ENV=<env>.
func checkScheduleEnv(env string) error {
	if !scheduleEnvRe.MatchString(env) {
		return fmt.Errorf("the ENV selector %q cannot be written into a unit: use only letters, digits, '.', '_' and '-'", env)
	}
	return nil
}

// addScheduleEnvLine inserts Environment=ENV=<env> directly after the
// Environment=PATH line of the rendered service. systemd.go does not know
// about ENV, so the line is added here. Without it the unattended run would
// load the default .env cascade instead of the one the schedule was made with.
func addScheduleEnvLine(service, env string) (string, error) {
	if err := checkScheduleEnv(env); err != nil {
		return "", err
	}
	const pathLine = "Environment=PATH=/usr/local/bin:/usr/bin:/bin\n"
	if !strings.Contains(service, pathLine) {
		return "", fmt.Errorf("internal error: the rendered unit has no PATH line to anchor ENV=%s", env)
	}
	return strings.Replace(service, pathLine, pathLine+"Environment=ENV="+env+"\n", 1), nil
}
