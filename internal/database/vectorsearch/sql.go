package vectorsearch

// sql.go renders the migration. The function must stay inlinable so Hasura's
// limit and the table's select filter apply to the ordered query: LANGUAGE sql,
// STABLE, one SELECT, returns SETOF the table, no LIMIT, no SECURITY DEFINER and
// no SET clause on the function (EPIC D7, review F11).

import (
	"bytes"
	"fmt"
	"text/template"

	"github.com/nself-org/cli/internal/database"
)

// migrationTmpl is rendered only with the quoted identifiers and the operator
// computed in Render; no raw user text reaches it.
var migrationTmpl = template.Must(template.New("migration").Parse(`-- Generated by nself db generate vector-search. Safe to run again: CREATE OR REPLACE.
-- k-NN over {{.Table}}.{{.Column}} ({{.Distance}}). It has no row cap on purpose: a cap
-- here would apply before the select permission filter. Callers pass the GraphQL row count.
SET lock_timeout = '5s';
SET statement_timeout = '30s';

CREATE OR REPLACE FUNCTION {{.Schema}}.{{.Func}}(query vector({{.Dim}}))
RETURNS SETOF {{.Schema}}.{{.Table}}
LANGUAGE sql
STABLE
AS $$
  SELECT * FROM {{.Schema}}.{{.Table}} ORDER BY {{.Column}} {{.Op}} query
$$;
`))

// Render returns the migration SQL for a validated Spec whose Dim is set.
func Render(s Spec) (string, error) {
	if err := s.Validate(); err != nil {
		return "", err
	}
	if s.Dim < 1 {
		return "", fmt.Errorf("vector dimension is not known for %s.%s.%s", s.Schema, s.Table, s.Column)
	}
	q := func(v string) (string, error) { return database.SanitizeIdentifier(v) }
	schema, err := q(s.Schema)
	if err != nil {
		return "", err
	}
	table, err := q(s.Table)
	if err != nil {
		return "", err
	}
	column, err := q(s.Column)
	if err != nil {
		return "", err
	}
	fn, err := q(s.FunctionName())
	if err != nil {
		return "", err
	}
	var buf bytes.Buffer
	err = migrationTmpl.Execute(&buf, map[string]any{
		"Schema": schema, "Table": table, "Column": column, "Func": fn,
		"Dim": s.Dim, "Op": s.Operator(), "Distance": string(s.Distance),
	})
	if err != nil {
		return "", fmt.Errorf("render migration: %w", err)
	}
	return buf.String(), nil
}
