// TestPluginOverlayIsolation reproduces D-0318: a v1.5 build must not change
// the installed fragment or the bytes a v1.4 project subsequently generates.
func TestPluginOverlayIsolation(t *testing.T) {
	plugins := t.TempDir()
	legacy, modern := t.TempDir(), t.TempDir()
	installPlugin(t, plugins, "nself-audit", `{"name":"nself-audit","port":3843}`, fragDefaultNetwork)
	discover := func(project string, v15 bool) (string, []byte) {
		t.Helper()
		compattest.Set(t, v15)
		paths, err := DiscoverPluginComposeFiles(project, plugins)
		if err != nil || len(paths) != 1 {
			t.Fatalf("discovery: %v, %v", paths, err)
		}
		data, err := os.ReadFile(paths[0])
		if err != nil {
			t.Fatal(err)
		}
		return paths[0], data
	}
	_, before := discover(legacy, false)
	path, normalized := discover(modern, true)
	if got := readFragment(t, plugins, "nself-audit"); got != fragDefaultNetwork {
		t.Errorf("shared installed fragment was modified:\n%s", got)
	}
	want := filepath.Join(modern, ".nself", "plugins", "nself-audit", pluginComposeFilename)
	if path != want {
		t.Errorf("compose path = %s, want project overlay %s", path, want)
	}
	if !strings.Contains(string(normalized), `PORT: "3843"`) || strings.Contains(string(normalized), "${DOCKER_NETWORK:-nself_network}") {
		t.Errorf("v1.5 overlay lacks expected normalizations:\n%s", normalized)
	}
	_, after := discover(legacy, false)
	if string(before) != string(after) {
		t.Error("v1.4 generated bytes changed after a v1.5 build")
	}
	_, switched := discover(modern, false)
	if string(before) != string(switched) {
		t.Error("mode switch reused stale v1.5 overlay bytes")
	}
	base := filepath.Join(modern, "docker-compose.yml")
	writeFile(t, base, "services: {}\n")
	if err := WriteComposeManifest(modern, base, []string{path}); err != nil {
		t.Fatal(err)
	}
	manifest, err := ReadComposeManifest(modern)
	if err != nil || len(manifest) != 2 || manifest[1] != want {
		t.Fatalf("manifest must reference the overlay: %v, %v", manifest, err)
	}
}

// TestPluginOverlayPlan verifies the project copy is a planned artifact, while
// both the installation and the project's filesystem remain untouched.
func TestPluginOverlayPlan(t *testing.T) {
	compattest.Set(t, true)
	plugins, project := t.TempDir(), t.TempDir()
	installPlugin(t, plugins, "nself-audit", `{"name":"nself-audit","port":3843}`, fragDefaultNetwork)
	sink, fx := newMemSink(project, ""), &planEffects{}
	paths, err := discoverPluginComposeFilesFx(fx, sink, project, plugins)
	want := filepath.Join(project, ".nself", "plugins", "nself-audit", pluginComposeFilename)
	if err != nil || len(paths) != 1 || paths[0] != want {
		t.Fatalf("planned overlay paths: %v, %v", paths, err)
	}
	if _, err := sink.ReadFile(want); err != nil {
		t.Fatal(err)
	}
	if len(sink.files) != 1 || len(fx.Recorded()) != 0 {
		t.Fatal("overlay must be one project artifact with no shared-fragment effect")
	}
	if _, err := os.Stat(filepath.Join(project, ".nself")); !os.IsNotExist(err) {
		t.Fatalf("plan wrote project files: %v", err)
	}
	if got := readFragment(t, plugins, "nself-audit"); got != fragDefaultNetwork {
		t.Fatal("plan changed installed bytes")
	}
}
