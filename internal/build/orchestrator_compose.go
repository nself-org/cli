func proxyFrontingStack(cfg *config.Config, workdir string) error {
	if cfg.Nginx.FrontedBy == "" {
		return nil
	}
	nginxDir, err := nginxtopo.ServedNginxDir(workdir, cfg.Nginx.FrontedBy)
	if err != nil {
		return nil // The existing topology validation reports unresolved layouts.
	}
	root := filepath.Dir(nginxDir)
	refuse := func(reason string) error {
		return errs.New("E482", "fronting stack "+root+" cannot serve nginx routes: "+reason).
			WithWhy("A fronted project requires the fronting stack's nginx service.").
			WithFix("Restore nginx in the fronting stack or unset NGINX_FRONTED_BY.")
	}
	composePath := filepath.Join(root, "docker-compose.yml")
	data, err := os.ReadFile(composePath)
	if err != nil && !os.IsNotExist(err) {
		return refuse(composePath + ": " + err.Error())
	}
	if bytes.HasPrefix(data, []byte(ComposeGeneratedHeader)) {
		var document struct {
			Services map[string]yaml.Node `yaml:"services"`
		}
		if err := yaml.Unmarshal(data, &document); err != nil {
			return refuse(composePath + ": " + err.Error())
		}
		if _, ok := document.Services[ProviderNginx]; !ok {
			return refuse("generated docker-compose.yml has no nginx service")
		}
	}
	manifestPath := filepath.Join(root, composeManifestFile)
	data, err = os.ReadFile(manifestPath)
	if err != nil && !os.IsNotExist(err) {
		return refuse(manifestPath + ": " + err.Error())
	}
	for _, line := range strings.Split(string(data), "\n") {
		file := strings.TrimSpace(line)
		if file != "" && !strings.HasPrefix(file, "#") && proxyTraefikFragment(file) {
			return refuse("compose manifest loads a traefik fragment: " + file)
		}
	}
	return nil
}
func buildEnvComputed(cfg *config.Config, extra map[string]string) string {
	network := cmp.Or(cfg.DockerNetwork, cfg.ProjectName+"_network")
	content := fmt.Sprintf("# Generated by nself build - DO NOT EDIT MANUALLY\nDATABASE_URL=%s\nDOCKER_NETWORK=%s\n", cfg.DatabaseURL(), network)
	for _, k := range slices.Sorted(maps.Keys(extra)) {
		content += fmt.Sprintf("%s=%s\n", k, extra[k])
	}
	return content
}

const ComposeGeneratedHeader = "# GENERATED BY nself build - DO NOT HAND EDIT\n" + "# Run 'nself build' to regenerate this file.\n"

func prependGeneratedHeader(composeYAML []byte) []byte {
	return append([]byte(ComposeGeneratedHeader), composeYAML...)
}
func collectOllamaEnv() map[string]string {
	if os.Getenv("AI_OLLAMA_ENABLED") != "true" {
		return make(map[string]string)
	}
	env := map[string]string{"AI_OLLAMA_ENABLED": "true"}
	for _, key := range []string{"AI_OLLAMA_MODEL", "AI_OLLAMA_GPU", "AI_OLLAMA_HOST", "AI_OLLAMA_KEEP_ALIVE"} {
		if v := os.Getenv(key); v != "" {
			env[key] = v
		}
	}
	return env
}
func MergeOllamaSidecar(composeYAML []byte, ollamaEnv map[string]string) ([]byte, bool, error) {
	if ollamaEnv["AI_OLLAMA_ENABLED"] != "true" {
		return composeYAML, false, nil
	}
	keepAlive := cmp.Or(ollamaEnv["AI_OLLAMA_KEEP_ALIVE"], "24h")
	enableGPU := ollamaEnv["AI_OLLAMA_GPU"] == "true"
	snippet := buildOllamaSnippet(keepAlive, enableGPU)
	merged := append(bytes.TrimRight(composeYAML, "\n"), []byte("\n"+snippet)...)
	return merged, true, nil
}
func buildOllamaSnippet(keepAlive string, enableGPU bool) string {
	var sb strings.Builder
	sb.WriteString("  ollama:\n    image: ollama/ollama:0.1.38\n    container_name: nself_ollama\n    restart: unless-stopped\n    networks: [nself]\n" +
		"    ports:\n      - \"127.0.0.1:11434:11434\"\n    volumes:\n      - ollama_models:/root/.ollama\n    environment:\n")
	sb.WriteString("      OLLAMA_KEEP_ALIVE: \"" + keepAlive + "\"\n")
	if enableGPU {
		sb.WriteString("    deploy:\n      resources:\n        reservations:\n          devices:\n" +
			"            - driver: nvidia\n              count: all\n              capabilities: [gpu]\n")
	}
	sb.WriteString("\nvolumes:\n  ollama_models:\n")
	return sb.String()
}
func ActiveSocketException(slug string) (SocketException, bool) {
	ex, ok := socketExceptions[slug]
	var c, t [3]int
	nc, _ := fmt.Sscanf(strings.TrimPrefix(strings.TrimSpace(version.GetVersion()), "v"), "%d.%d.%d", &c[0], &c[1], &c[2])
	nt, _ := fmt.Sscanf(ex.RemovalAt, "%d.%d.%d", &t[0], &t[1], &t[2])
	return ex, ok && nc == 3 && nt == 3 && (c[0] < t[0] || c[0] == t[0] && (c[1] < t[1] || c[1] == t[1] && c[2] < t[2]))
}
func SocketProxyService(n string) bool { return n == "nginx" || n == "traefik" }
func SocketPathExposed(p string) bool {
	c := strings.TrimPrefix(path.Clean(strings.ToLower(strings.TrimSpace(p))), "/private")
	switch c {
	case "", "/", "/var", "/var/run", "/run":
		return true
	}
	return path.Base(c) == "docker.sock"
}
func expandSocket(s string, env SocketEnv) (string, bool) {
	if strings.Count(s, "${") != strings.Count(s, "}") {
		return "", false
	}
	ok := true
	out := os.Expand(s, func(ref string) string {
		name, def, hasDef := strings.Cut(ref, ":-")
		switch v, set := env(name); {
		case ref == "$":
			return "\x00"
		case set && (v != "" || !hasDef):
			return v
		case hasDef:
			return def
		}
		ok = false
		return ""
	})
	return strings.ReplaceAll(out, "\x00", "$"), ok && !strings.Contains(out, "$")
}

func scanSocketService(d socketDoc, name string, body map[string]any, lookup SocketEnv, vols map[string]string) ([]SocketUse, error) {
	var uses []SocketUse
	use := func(u bool, f string, a ...any) { uses = append(uses, SocketUse{d.origin, fmt.Sprintf(f, a...), u}) }
	bad := func(w string) error { return fmt.Errorf("%s service %q has an unsupported %s", d.origin, name, w) }
	for _, k := range []string{"extends", "volumes_from", "secrets", "configs"} {
		if v := body[k]; v != nil && fmt.Sprint(v) != "[]" { // an empty list is safe
			use(true, "uses %s, which is not inspected", k)
		}
	}
	if v := body["use_api_socket"]; v != nil && v != false { // the engine API socket, mounted by the provider
		if x, ok := expandSocket(fmt.Sprint(v), lookup); !ok || !slices.Contains([]string{"", "false", "no", "off", "0"}, strings.ToLower(x)) {
			use(true, "enables use_api_socket, which hands the container the engine API socket")
		}
	}
	entries, isList := body["volumes"].([]any)
	if body["volumes"] != nil && !isList {
		return nil, bad("volumes shape")
	}
	for _, e := range entries {
		var src, dst string
		var ok, bind bool
		switch v := e.(type) {
		case string:
			x, xok := expandSocket(v, lookup)
			p := append(strings.Split(x, ":"), "")
			src, dst, ok = p[0], p[1], xok
		case map[string]any:
			s, _ := v["source"].(string)
			t, _ := v["target"].(string)
			xs, ok1 := expandSocket(s, lookup)
			xt, ok2 := expandSocket(t, lookup)
			src, dst, ok, bind = xs, xt, ok1 && ok2, v["type"] == "bind"
		default:
			return nil, bad("volume entry")
		}
		res, rok := src, true
		if bind || strings.IndexAny(src, "./~") == 0 { // a bind path, not a named volume
			res, rok = ResolveSocketPath(d.dir, src)
		}
		switch {
		case !ok || !rok:
			use(true, "mounts a volume that cannot be resolved (%v)", e)
		case SocketPathExposed(src), SocketPathExposed(res), path.Base(dst) == "docker.sock":
			use(false, "mounts the Docker socket (volume %q)", src+":"+dst)
		case vols[src] != "":
			use(strings.HasPrefix(vols[src], "has a backing"), "mounts named volume %q, which %s", src, vols[src])
		}
	}
	env, err := socketFileEnv(d, body["env_file"], lookup)
	if err != nil {
		return nil, err
	}
	switch e := body["environment"].(type) {
	case nil:
	case map[string]any:
		for k, v := range e {
			env[k] = v
		}
	case []any:
		for _, x := range e {
			str, ok := x.(string)
			if !ok {
				return nil, bad("environment entry")
			}
			k, v, has := strings.Cut(str, "=")
			if strings.Contains(k, "$") { // Compose interpolates the whole entry, key included, before splitting
				full, fok := expandSocket(str, lookup)
				if !fok {
					use(true, "environment entry %q cannot be resolved", str)
					continue
				}
				k, v, has = strings.Cut(full, "=")
			}
			if env[k] = nil; has { // no "=": forwarded from the effective env
				env[k] = v
			}
		}
	default:
		return nil, bad("environment shape")
	}
	if v, present := env["DOCKER_HOST"]; present {
		val, _ := lookup("DOCKER_HOST") // null or no "=": forwarded, the effective value counts
		if v != nil {
			val = fmt.Sprint(v)
		}
		if x, ok := expandSocket(val, lookup); !ok || strings.Contains(strings.ToLower(x), "unix:") {
			use(!ok, "sets DOCKER_HOST to %q (a unix socket, or not resolvable)", val)
		}
	}
	return uses, nil
}

func (st *buildState) futureComposeEnv() map[string]string {
	vars := withHostOwner(computePluginEnvVarsForProfileName(st.workdir, st.pluginDir, st.cfg, st.opts.Profile), proxyHostOwner(st.cfg, st.workdir, st.pluginDir))
	sink := newMemSink(st.workdir, "")
	_ = writeComposeEnvVia(sink, st.workdir, st.cfg, SecretEnvMap(st.cfg), vars)
	m := map[string]string{}
	for _, f := range sink.files { // the writer produced exactly one file
		m, _ = config.ParseEnvBytes("planned compose.env", f.Data)
	}
	return m
}
func (st *buildState) guardDockerSocket(g *compose.Generator) error {
	stack, err := g.Generate()
	if err != nil {
		return nil // the real render reports it
	}
	rep, err := AnalyzeSocket(st.workdir, st.pluginDir, NewSocketEnv(st.futureComposeEnv(), filepath.Join(st.workdir, ".env")), stack)
	if err != nil {
		var parse *socketParseError
		if st.planning() && errors.As(err, &parse) && parse.origin == "override" {
			return nil // read-only impact is unknown; the write-mode build still refuses
		}
		return errs.Newf("E130", "compose inputs cannot be checked for the Docker socket: %v", err)
	}
	return rep.Refuse()
}
