// applyProxyProvider applies the derived provider to the compose service gate.
func (st *buildState) applyProxyProvider(g *compose.Generator) error {
	// Step 8 reuses the plugin directory resolved at Step 7.05.
	pluginDir := st.pluginDir
	provider, err := ProxyProvider(st.cfg, st.workdir, pluginDir)
	if err != nil {
		return err
	}
	if err := proxyComposeDiscoverable(st.workdir, pluginDir, provider); err != nil {
		return err
	}
	if provider == ProviderNginx && st.planning() && proxyDeclaredTraefik(st.cfg, st.workdir, pluginDir) {
		// Step 7.05 records the install; reconcile re-plans its services after it.
		provider = ProviderTraefik
	}
	if provider != ProviderNginx {
		if err := checkProviderRoutes(st.withSnippetRoutes(st.routes), provider, st.cfg, st.workdir); err != nil {
			return err
		}
		g.OmitNginx()
		// Compose is generated once per build, even when modelRoutes runs twice.
		if proxyAPIDocsEnabled(st.cfg) {
			slog.Warn("docs." + st.cfg.BaseDomain + " is not served by traefik (D-0310); api-docs is an accepted difference (API_DOCS_* parsing debt D-0455)")
		}
	} else {
		if err := proxyFrontingStack(st.cfg, st.workdir); err != nil {
			return err
		}
		// P7-DEPL-21 (ADR 0027): refuse before any provider output is touched.
		if err := st.guardDockerSocket(g); err != nil {
			return err
		}
		// P7-DEPL-04: nginx serves again, so the traefik renderer's output goes.
		return cleanupProviderOutput(st.sink, st.workdir, provider)
	}
	return st.guardDockerSocket(g)
}

// proxyFrontingStack verifies that the served nginx tree still has a consumer.
// Missing compose files are allowed for a fronting stack's first build.
func proxyFrontingStack(cfg *config.Config, workdir string) error {
	if cfg.Nginx.FrontedBy == "" {
		return nil
	}
	nginxDir, err := nginxtopo.ServedNginxDir(workdir, cfg.Nginx.FrontedBy)
	if err != nil {
		return nil // The existing topology validation reports unresolved layouts.
	}
	root := filepath.Dir(nginxDir)
	refuse := func(reason string) error {
		return errs.New("E482", "fronting stack "+root+" cannot serve nginx routes: "+reason).
			WithWhy("A fronted project requires the fronting stack's nginx service.").
			WithFix("Restore nginx in the fronting stack or unset NGINX_FRONTED_BY.")
	}
	composePath := filepath.Join(root, "docker-compose.yml")
	data, err := os.ReadFile(composePath)
	if err != nil && !os.IsNotExist(err) {
		return refuse(composePath + ": " + err.Error())
	}
	if bytes.HasPrefix(data, []byte(ComposeGeneratedHeader)) {
		var document struct {
			Services map[string]yaml.Node `yaml:"services"`
		}
		if err := yaml.Unmarshal(data, &document); err != nil {
			return refuse(composePath + ": " + err.Error())
		}
		if _, ok := document.Services[ProviderNginx]; !ok {
			return refuse("generated docker-compose.yml has no nginx service")
		}
	}
	manifestPath := filepath.Join(root, composeManifestFile)
	data, err = os.ReadFile(manifestPath)
	if err != nil && !os.IsNotExist(err) {
		return refuse(manifestPath + ": " + err.Error())
	}
	for _, line := range strings.Split(string(data), "\n") {
		file := strings.TrimSpace(line)
		if file != "" && !strings.HasPrefix(file, "#") && proxyTraefikFragment(file) {
			return refuse("compose manifest loads a traefik fragment: " + file)
		}
	}
	return nil
}

// buildEnvComputed generates the .env.computed file content with computed
// values that other tools (e.g., Hasura migrations) depend on. The extra
// map holds additional key=value pairs contributed by plugins or other
// build steps.
func buildEnvComputed(cfg *config.Config, extra map[string]string) string {
	network := cfg.DockerNetwork
	if network == "" {
		network = cfg.ProjectName + "_network"
	}
	content := fmt.Sprintf("# Generated by nself build - DO NOT EDIT MANUALLY\n"+
		"DATABASE_URL=%s\n"+
		"DOCKER_NETWORK=%s\n",
		cfg.DatabaseURL(),
		network,
	)
	// Sorted keys: map order would change the file on every build, and plan
	// mode could never equal apply byte for byte.
	keys := make([]string, 0, len(extra))
	for k := range extra {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		content += fmt.Sprintf("%s=%s\n", k, extra[k])
	}
	return content
}

// ComposeGeneratedHeader is the canonical marker prepended to every generated
// docker-compose.yml. Pre-commit hooks and auditors grep for this exact line
// to confirm a compose file was produced by `nself build` and not hand-edited.
// See S32-T12 and the PPI nSelf-First Doctrine.
const ComposeGeneratedHeader = "# GENERATED BY nself build - DO NOT HAND EDIT\n" +
	"# Run 'nself build' to regenerate this file.\n"

// prependGeneratedHeader returns composeYAML with ComposeGeneratedHeader
// prefixed. YAML treats `#` as a comment so the resulting file remains valid.
func prependGeneratedHeader(composeYAML []byte) []byte {
	out := make([]byte, 0, len(ComposeGeneratedHeader)+len(composeYAML))
	out = append(out, []byte(ComposeGeneratedHeader)...)
	out = append(out, composeYAML...)
	return out
}

// collectOllamaEnv reads Ollama-related env vars from the OS environment.
// Returns a non-empty map only when AI_OLLAMA_ENABLED=true; callers use this
// to decide whether to inject the Ollama sidecar into docker-compose.yml.
func collectOllamaEnv() map[string]string {
	if os.Getenv("AI_OLLAMA_ENABLED") != "true" {
		return make(map[string]string)
	}
	env := map[string]string{
		"AI_OLLAMA_ENABLED": "true",
	}
	for _, key := range []string{
		"AI_OLLAMA_MODEL",
		"AI_OLLAMA_GPU",
		"AI_OLLAMA_HOST",
		"AI_OLLAMA_KEEP_ALIVE",
	} {
		if v := os.Getenv(key); v != "" {
			env[key] = v
		}
	}
	return env
}

// MergeOllamaSidecar injects an Ollama service into composeYAML when
// AI_OLLAMA_ENABLED=true is present in ollamaEnv. The injected service runs
// the official Ollama image on localhost:11434, which plugin-ai uses for
// local LLM inference without an external API key.
func MergeOllamaSidecar(composeYAML []byte, ollamaEnv map[string]string) ([]byte, bool, error) {
	if ollamaEnv["AI_OLLAMA_ENABLED"] != "true" {
		return composeYAML, false, nil
	}

	keepAlive := ollamaEnv["AI_OLLAMA_KEEP_ALIVE"]
	if keepAlive == "" {
		keepAlive = "24h"
	}
	enableGPU := ollamaEnv["AI_OLLAMA_GPU"] == "true"

	// Build the ollama service snippet and append it to the services section.
	snippet := buildOllamaSnippet(keepAlive, enableGPU)

	merged := append(bytes.TrimRight(composeYAML, "\n"), []byte("\n"+snippet)...)
	return merged, true, nil
}

// buildOllamaSnippet returns a YAML snippet for the ollama service and its
// volume, ready to be appended to the services section of docker-compose.yml.
func buildOllamaSnippet(keepAlive string, enableGPU bool) string {
	var sb strings.Builder
	sb.WriteString("  ollama:\n")
	sb.WriteString("    image: ollama/ollama:0.1.38\n")
	sb.WriteString("    container_name: nself_ollama\n")
	sb.WriteString("    restart: unless-stopped\n")
	sb.WriteString("    networks: [nself]\n")
	sb.WriteString("    ports:\n")
	sb.WriteString("      - \"127.0.0.1:11434:11434\"\n")
	sb.WriteString("    volumes:\n")
	sb.WriteString("      - ollama_models:/root/.ollama\n")
	sb.WriteString("    environment:\n")
	sb.WriteString("      OLLAMA_KEEP_ALIVE: \"" + keepAlive + "\"\n")
	if enableGPU {
		sb.WriteString("    deploy:\n")
		sb.WriteString("      resources:\n")
		sb.WriteString("        reservations:\n")
		sb.WriteString("          devices:\n")
		sb.WriteString("            - driver: nvidia\n")
		sb.WriteString("              count: all\n")
		sb.WriteString("              capabilities: [gpu]\n")
	}
	sb.WriteString("\nvolumes:\n")
	sb.WriteString("  ollama_models:\n")
	return sb.String()
}

// scanSocketService lists how one service reaches the Docker socket; env_file, extends, volumes_from and unresolvable values count.
func scanSocketService(d socketDoc, name string, body map[string]any, lookup SocketEnv, vols map[string]string) ([]SocketUse, error) {
	var uses []SocketUse
	use := func(u bool, f string, a ...any) { uses = append(uses, SocketUse{d.origin, fmt.Sprintf(f, a...), u}) }
	bad := func(w string) error { return fmt.Errorf("%s service %q has an unsupported %s", d.origin, name, w) }
	for _, k := range []string{"env_file", "extends", "volumes_from"} {
		if body[k] != nil {
			use(true, "uses %s, which is not inspected", k)
		}
	}
	entries, isList := body["volumes"].([]any)
	if body["volumes"] != nil && !isList {
		return nil, bad("volumes shape")
	}
	for _, e := range entries {
		src, dst, ok, bind := "", "", true, false
		switch v := e.(type) {
		case string:
			x, xok := expandSocket(v, lookup)
			p := append(strings.Split(x, ":"), "")
			src, dst, ok = p[0], p[1], xok
		case map[string]any:
			s, _ := v["source"].(string)
			t, _ := v["target"].(string)
			xs, ok1 := expandSocket(s, lookup)
			xt, ok2 := expandSocket(t, lookup)
			src, dst, ok, bind = xs, xt, ok1 && ok2, v["type"] == "bind"
		default:
			return nil, bad("volume entry")
		}
		res, rok := src, true
		if bind || strings.IndexAny(src, "./~") == 0 { // a bind path, not a named volume
			res, rok = ResolveSocketPath(d.dir, src)
		}
		switch {
		case !ok || !rok:
			use(true, "mounts a volume that cannot be resolved (%v)", e)
		case SocketPathExposed(src), SocketPathExposed(res), path.Base(dst) == "docker.sock":
			use(false, "mounts the Docker socket (volume %q)", src+":"+dst)
		case vols[src] != "":
			use(strings.HasPrefix(vols[src], "has a backing"), "mounts named volume %q, which %s", src, vols[src])
		}
	}
	env := map[string]any{}
	switch e := body["environment"].(type) {
	case nil:
	case map[string]any:
		env = e
	case []any:
		for _, x := range e {
			str, ok := x.(string)
			if !ok {
				return nil, bad("environment entry")
			}
			k, v, has := strings.Cut(str, "=")
			if env[k] = nil; has { // no "=": forwarded from the effective env
				env[k] = v
			}
		}
	default:
		return nil, bad("environment shape")
	}
	if v, present := env["DOCKER_HOST"]; present {
		val, _ := lookup("DOCKER_HOST") // null or no "=": forwarded, the effective value counts
		if v != nil {
			val = fmt.Sprint(v)
		}
		if x, ok := expandSocket(val, lookup); !ok || strings.Contains(strings.ToLower(x), "unix:") {
			use(!ok, "sets DOCKER_HOST to %q (a unix socket, or not resolvable)", val)
		}
	}
	return uses, nil
}
