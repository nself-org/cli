package build

// nginx_sites_prune.go — safely backs up and prunes nginx/sites/*.conf
// before regenerateSSLAndNginx (orchestrator_build_ssl.go) writes the fresh
// set, instead of unconditionally deleting every file in the directory.
//
// Purpose: a production box running `nself build` had its unconditional
// wipe of nginx/sites/ remove 8 live route confs plus a conf belonging to
// another project that happened to share the directory, with no backup and
// the running nginx left to fail its next reload if any of those routes
// were still referenced. This file makes the sweep additive-safe: only
// files this CLI's own templates stamped with nginxGeneratedMarker are
// candidates for removal, everything else is left in place and reported,
// and the directory's prior contents are snapshotted first regardless.
// Inputs: sitesDir (the directory generateSSLAndNginx is about to
// regenerate into — always the project's own, never a fronting stack's,
// per resolveNginxSitesDir) and workdir (this project's root, for the
// backup directory).
// Outputs: backupNginxSites copies sitesDir's current contents into
// .nself/backups/nginx-sites-<timestamp>/ before anything is touched, and
// prunes snapshots beyond the last maxNginxSitesBackups. pruneGeneratedNginxSites
// removes only marker-carrying files and returns the names of any file it
// left behind so the caller can warn about them.
// Constraints: never removes a subdirectory or a file lacking the marker;
// a read/open error on an individual file is treated as "not safely
// identifiable as generated" (left in place) rather than aborting the
// build; backup failures do abort the build — there is no safety net for a
// destructive prune without one.

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

// nginxGeneratedMarker is the first line every nginx conf this CLI
// generates is stamped with — see internal/nginx/templates/*.tmpl. Only
// files carrying it are safe to delete during a regeneration sweep;
// anything else is either hand-written or belongs to a different project
// sharing the directory.
const nginxGeneratedMarker = "# Generated by nself build"

// maxNginxSitesBackups is how many timestamped nginx/sites/ snapshots are
// kept under .nself/backups/ before the oldest are pruned.
const maxNginxSitesBackups = 5

// backupNginxSites copies the current contents of sitesDir into a fresh
// .nself/backups/nginx-sites-<timestamp>/ directory under workdir before
// generateSSLAndNginx touches anything, then prunes snapshots beyond the
// last maxNginxSitesBackups. A no-op (returns nil) when sitesDir does not
// exist yet or is empty — there is nothing to protect on a first build.
func backupNginxSites(workdir, sitesDir string) error {
	entries, err := os.ReadDir(sitesDir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return fmt.Errorf("reading %s for backup: %w", sitesDir, err)
	}
	if len(entries) == 0 {
		return nil
	}

	backupsRoot := filepath.Join(workdir, ".nself", "backups")
	dest := filepath.Join(backupsRoot, "nginx-sites-"+time.Now().UTC().Format("20060102-150405"))
	if err := os.MkdirAll(dest, 0755); err != nil {
		return fmt.Errorf("creating nginx/sites backup dir %s: %w", dest, err)
	}
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		src := filepath.Join(sitesDir, e.Name())
		content, readErr := os.ReadFile(src)
		if readErr != nil {
			return fmt.Errorf("backing up %s: %w", src, readErr)
		}
		if writeErr := os.WriteFile(filepath.Join(dest, e.Name()), content, 0644); writeErr != nil {
			return fmt.Errorf("writing backup %s: %w", filepath.Join(dest, e.Name()), writeErr)
		}
	}

	return pruneOldNginxSitesBackups(backupsRoot)
}

// pruneOldNginxSitesBackups keeps only the newest maxNginxSitesBackups
// "nginx-sites-*" snapshots under backupsRoot, removing the rest. The
// timestamp suffix (YYYYMMDD-HHMMSS) is lexicographically sortable, so a
// plain name sort orders oldest-first.
func pruneOldNginxSitesBackups(backupsRoot string) error {
	entries, err := os.ReadDir(backupsRoot)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return fmt.Errorf("reading %s to prune old backups: %w", backupsRoot, err)
	}

	var snapshots []string
	for _, e := range entries {
		if e.IsDir() && strings.HasPrefix(e.Name(), "nginx-sites-") {
			snapshots = append(snapshots, e.Name())
		}
	}
	sort.Strings(snapshots)
	if len(snapshots) <= maxNginxSitesBackups {
		return nil
	}
	for _, name := range snapshots[:len(snapshots)-maxNginxSitesBackups] {
		if err := os.RemoveAll(filepath.Join(backupsRoot, name)); err != nil {
			return fmt.Errorf("pruning old nginx/sites backup %s: %w", name, err)
		}
	}
	return nil
}

// pruneGeneratedNginxSites removes only the files in sitesDir that carry
// nginxGeneratedMarker on their first line — this build's own prior
// output — before generateSSLAndNginx writes the fresh set. Any file
// without the marker (hand-written, or belonging to another project
// sharing the directory) is left untouched; its name is returned in
// foreign, sorted, so the caller can warn about it.
func pruneGeneratedNginxSites(sitesDir string) (removed int, foreign []string, err error) {
	entries, readErr := os.ReadDir(sitesDir)
	if readErr != nil {
		if os.IsNotExist(readErr) {
			return 0, nil, nil
		}
		return 0, nil, fmt.Errorf("reading %s: %w", sitesDir, readErr)
	}

	const headBytes = 128
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		path := filepath.Join(sitesDir, e.Name())
		if isGeneratedNginxSiteFile(path, headBytes) {
			if rmErr := os.Remove(path); rmErr != nil {
				return removed, foreign, fmt.Errorf("removing generated file %s: %w", path, rmErr)
			}
			removed++
			continue
		}
		foreign = append(foreign, e.Name())
	}
	sort.Strings(foreign)
	return removed, foreign, nil
}

// isGeneratedNginxSiteFile reports whether path's first headBytes bytes
// contain nginxGeneratedMarker. An open/read error is treated as "not
// identifiable as generated" (false) — the file is left in place rather
// than risking deletion of something this build did not write.
func isGeneratedNginxSiteFile(path string, headBytes int) bool {
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer func() { _ = f.Close() }()

	head := make([]byte, headBytes)
	n, _ := f.Read(head)
	return bytes.Contains(head[:n], []byte(nginxGeneratedMarker))
}
