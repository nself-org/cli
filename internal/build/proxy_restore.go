package build

// Purpose: return the generated tree to its pre-swap shape when the provider is
// nginx again (EPIC DEPL D4/D5): drop the renderer's two output directories,
// .nself/generated/traefik/ and .nself/generated/traefik-static/, if, and only
// if, the traefik renderer wrote them.
// Inputs: the build sink, the project workdir and the derived provider.
// Outputs: the directory's files removed through the sink (so plan mode only
// records them), or one warning when the directory is not provably ours.
// Constraints: never touches a path outside those two directories; a symlinked directory, a symlinked path component or a missing/foreign marker
// leaves everything in place; no Docker calls. Removal is per file, never an
// mv-replace of the directory (bind-mount gotcha 7).

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"log/slog"
	"os"
	"path/filepath"
	"sort"
)

// proxyGeneratedMarker is the file the traefik renderer writes beside its output;
// its text starts with proxyMarkerPrefix (plugins:free/traefik/cmd/render).
const (
	proxyGeneratedMarker = ".nself-generated"
	proxyMarkerPrefix    = "GENERATED BY"
)

// proxyOutputNames are the directories the traefik-config one-shot renders into
// (dynamic file-provider config, static config). Both hold the marker.
var proxyOutputNames = []string{"traefik", "traefik-static"}

// proxyOutputDir is where the traefik plugin renders into.
func proxyOutputDir(workdir string) string { return proxyOutputPath(workdir, "traefik") }

func proxyOutputPath(workdir, name string) string {
	return filepath.Join(workdir, ".nself", "generated", name)
}

// cleanupProviderOutput removes the output of a provider that no longer serves.
// It only acts for nginx; with traefik the plugin owns the directories.
func cleanupProviderOutput(sink Sink, workdir, provider string) error {
	if provider != ProviderNginx {
		return nil
	}
	for _, name := range proxyOutputNames {
		if err := cleanupOutputDir(sink, workdir, proxyOutputPath(workdir, name)); err != nil {
			return err
		}
	}
	return nil
}

func cleanupOutputDir(sink Sink, workdir, dir string) error {
	info, err := os.Lstat(dir)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("inspecting %s: %w", dir, err)
	}
	if !info.IsDir() {
		return proxyKeep(dir, "it is not a directory")
	}
	if ok, why := proxyOwnedDir(workdir, dir); !ok {
		if emptyPrecreatedDir(workdir, dir) {
			return sink.Remove(dir) // pre-created by prepareProxyOutputDirs, never written
		}
		return proxyKeep(dir, why)
	}
	// Decide before any removal so plan and apply see the same thing: the
	// plan-checked sink fails a build that planned a removal which did not happen.
	if why := unwritableIn(filepath.Dir(dir), dir); why != "" {
		return proxyKeep(dir, "it is owned by root (the traefik-config container wrote it): "+why+" is not writable; run `sudo rm -rf "+dir+"` or chown it to your user, then build again")
	}
	err = removeTree(sink, dir, info)
	if errors.Is(err, fs.ErrPermission) {
		// The one-shot runs as root and Docker creates its bind directories
		// root-owned, so an unprivileged build cannot unlink inside them. The
		// marker is removed last, so the next build retries.
		return proxyKeep(dir, "it is owned by root (the traefik-config container wrote it): "+err.Error()+"; run `sudo rm -rf "+dir+"` or chown it to your user, then build again")
	}
	if err != nil {
		return fmt.Errorf("removing generated traefik output %s: %w", dir, err)
	}
	return nil
}

// unwritableIn returns the first directory, the parent first and then dir and
// everything under it, in which this user cannot unlink, or "".
func unwritableIn(parent, dir string) string {
	if !dirWritable(parent) {
		return parent
	}
	var bad string
	_ = filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if bad != "" {
			return nil
		}
		if err != nil { // an unreadable directory cannot be emptied either
			bad = p
			return nil
		}
		if !d.IsDir() {
			return nil
		}
		if !dirWritable(p) {
			bad = p
		}
		return nil
	})
	return bad
}

// proxyKeep warns once that dir stays and why. The build goes on: a leftover
// the renderer did not write is not this build's to delete.
func proxyKeep(dir, why string) error {
	slog.Warn("leaving "+dir+" in place: "+why,
		"fix", "remove it by hand if it is stale; nself deletes it only when the traefik renderer's "+proxyGeneratedMarker+" marker is inside")
	return nil
}

// proxyOwnedDir reports whether dir is exactly <workdir>/.nself/generated/traefik
// with no symlink on the way and a regular renderer marker inside.
func proxyOwnedDir(workdir, dir string) (bool, string) {
	root, err := filepath.EvalSymlinks(workdir)
	if err != nil {
		return false, "the project path does not resolve: " + err.Error()
	}
	real, err := filepath.EvalSymlinks(dir)
	if err != nil || real != proxyOutputPath(root, filepath.Base(dir)) {
		return false, "its path crosses a symlink"
	}
	marker := filepath.Join(dir, proxyGeneratedMarker)
	mi, err := os.Lstat(marker)
	if err != nil || !mi.Mode().IsRegular() {
		return false, "the " + proxyGeneratedMarker + " marker is absent, so nself cannot show it created the directory"
	}
	head := make([]byte, len(proxyMarkerPrefix))
	f, err := os.Open(marker)
	if err != nil {
		return false, "the " + proxyGeneratedMarker + " marker is unreadable"
	}
	defer func() { _ = f.Close() }()
	if _, err := io.ReadFull(f, head); err != nil || !bytes.Equal(head, []byte(proxyMarkerPrefix)) {
		return false, "the " + proxyGeneratedMarker + " file is not a renderer marker"
	}
	return true, ""
}

// removeTree deletes dir's files and then dir, through the sink. A symlink
// entry is removed as a link, never followed. The marker goes last, so an
// interrupted cleanup still leaves a directory the next build recognises.
func removeTree(sink Sink, dir string, before fs.FileInfo) error {
	if !before.IsDir() {
		return fmt.Errorf("cleanup directory %s was replaced", dir)
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		return err
	}
	defer func() { _ = root.Close() }()
	after, err := root.Stat(".")
	if err != nil {
		return err
	}
	if !os.SameFile(before, after) {
		return fmt.Errorf("cleanup directory %s was replaced", dir)
	}
	if err := removeTreeIn(sink, root, dir, "."); err != nil {
		return err
	}
	return sink.Remove(dir)
}

// removeTreeIn anchors both traversal and disk unlinks to the generated output
// directory. A swapped symlink cannot redirect either operation to a sibling.
func removeTreeIn(sink Sink, root *os.Root, dir, relative string) error {
	f, err := root.Open(relative)
	if err != nil {
		return err
	}
	entries, err := f.ReadDir(-1)
	_ = f.Close()
	if err != nil {
		return err
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].Name() < entries[j].Name() })
	for _, e := range entries {
		rel := filepath.Join(relative, e.Name())
		p := filepath.Join(dir, rel)
		if e.Name() == proxyGeneratedMarker {
			continue
		}
		// The listing may be stale: only a directory that is still one is entered.
		if fi, err := root.Lstat(rel); e.IsDir() && err == nil && fi.IsDir() {
			if err := removeTreeIn(sink, root, dir, rel); err != nil {
				return err
			}
			if err := sink.RemoveWithin(root, rel, p); err != nil {
				return err
			}
			continue
		}
		if err := sink.RemoveWithin(root, rel, p); err != nil && !errors.Is(err, fs.ErrNotExist) {
			return err
		}
	}
	marker := filepath.Join(relative, proxyGeneratedMarker)
	if _, err := root.Lstat(marker); err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil
		}
		return err
	}
	if err := sink.RemoveWithin(root, marker, filepath.Join(dir, marker)); err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	return nil
}

// emptyPrecreatedDir reports whether dir is exactly <workdir>/.nself/generated/<name>,
// reached through no symlink, and holds nothing: the leftover of a build that
// pre-created it for a renderer that never ran. Removing it deletes no data.
func emptyPrecreatedDir(workdir, dir string) bool {
	root, err := filepath.EvalSymlinks(workdir)
	if err != nil {
		return false
	}
	real, err := filepath.EvalSymlinks(dir)
	if err != nil || real != proxyOutputPath(root, filepath.Base(dir)) {
		return false
	}
	entries, err := os.ReadDir(dir)
	return err == nil && len(entries) == 0
}
