package build

// Purpose: return the generated tree to its pre-swap shape when the provider is
// nginx again (EPIC DEPL D4/D5): drop .nself/generated/traefik/ if, and only if,
// the traefik renderer wrote it.
// Inputs: the build sink, the project workdir and the derived provider.
// Outputs: the directory's files removed through the sink (so plan mode only
// records them), or one warning when the directory is not provably ours.
// Constraints: never touches a path outside <workdir>/.nself/generated/traefik;
// a symlinked directory, a symlinked path component or a missing/foreign marker
// leaves everything in place; no Docker calls. Removal is per file, never an
// mv-replace of the directory (bind-mount gotcha 7).

import (
	"bytes"
	"fmt"
	"log/slog"
	"os"
	"path/filepath"
)

// proxyGeneratedMarker is the file the traefik renderer writes beside its output;
// its text starts with proxyMarkerPrefix (plugins:free/traefik/cmd/render).
const (
	proxyGeneratedMarker = ".nself-generated"
	proxyMarkerPrefix    = "GENERATED BY"
)

// proxyOutputDir is where the traefik plugin renders into.
func proxyOutputDir(workdir string) string {
	return filepath.Join(workdir, ".nself", "generated", "traefik")
}

// cleanupProviderOutput removes the output of a provider that no longer serves.
// It only acts for nginx; with traefik the plugin owns the directory.
func cleanupProviderOutput(sink Sink, workdir, provider string) error {
	if provider != ProviderNginx {
		return nil
	}
	dir := proxyOutputDir(workdir)
	info, err := os.Lstat(dir)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("inspecting %s: %w", dir, err)
	}
	if !info.IsDir() {
		return proxyKeep(dir, "it is not a directory")
	}
	if ok, why := proxyOwnedDir(workdir, dir); !ok {
		return proxyKeep(dir, why)
	}
	if err := removeTree(sink, dir); err != nil {
		return fmt.Errorf("removing generated traefik output %s: %w", dir, err)
	}
	return nil
}

// proxyKeep warns once that dir stays and why. The build goes on: a leftover
// the renderer did not write is not this build's to delete.
func proxyKeep(dir, why string) error {
	slog.Warn("leaving "+dir+" in place: "+why,
		"fix", "remove it by hand if it is stale; nself deletes it only when the traefik renderer's "+proxyGeneratedMarker+" marker is inside")
	return nil
}

// proxyOwnedDir reports whether dir is exactly <workdir>/.nself/generated/traefik
// with no symlink on the way and a regular renderer marker inside.
func proxyOwnedDir(workdir, dir string) (bool, string) {
	root, err := filepath.EvalSymlinks(workdir)
	if err != nil {
		return false, "the project path does not resolve: " + err.Error()
	}
	real, err := filepath.EvalSymlinks(dir)
	if err != nil || real != proxyOutputDir(root) {
		return false, "its path crosses a symlink"
	}
	marker := filepath.Join(dir, proxyGeneratedMarker)
	mi, err := os.Lstat(marker)
	if err != nil || !mi.Mode().IsRegular() {
		return false, "the " + proxyGeneratedMarker + " marker is absent, so nself cannot show it created the directory"
	}
	head := make([]byte, len(proxyMarkerPrefix))
	f, err := os.Open(marker)
	if err != nil {
		return false, "the " + proxyGeneratedMarker + " marker is unreadable"
	}
	defer f.Close()
	if n, _ := f.Read(head); !bytes.Equal(head[:n], []byte(proxyMarkerPrefix)) {
		return false, "the " + proxyGeneratedMarker + " file is not a renderer marker"
	}
	return true, ""
}

// removeTree deletes dir's files and then dir, through the sink. A symlink
// entry is removed as a link, never followed. The marker goes last, so an
// interrupted cleanup still leaves a directory the next build recognises.
func removeTree(sink Sink, dir string) error {
	entries, err := sink.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		p := filepath.Join(dir, e.Name())
		if e.Name() == proxyGeneratedMarker {
			continue
		}
		if e.IsDir() {
			if err := removeTree(sink, p); err != nil {
				return err
			}
			continue
		}
		if err := sink.Remove(p); err != nil {
			return err
		}
	}
	if err := sink.Remove(filepath.Join(dir, proxyGeneratedMarker)); err != nil && !os.IsNotExist(err) {
		return err
	}
	return sink.Remove(dir)
}
