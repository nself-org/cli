package build

import (
	"os"
	"path/filepath"

	"github.com/nself-org/cli/internal/compose"
	"github.com/nself-org/cli/internal/config"
)

// pluginsNeedingRedis is the authoritative list of plugin names that require
// Redis as a backing service (BullMQ queues, caching). When any of these
// plugins is installed and Redis is not explicitly enabled, DetectServices
// auto-enables Redis and the compose generator emits a redis block.
//
// Mirrors the serviceDependents["redis"] entry in cmd/commands/service.go.
var pluginsNeedingRedis = []string{"ai", "claw", "mux", "cron", "notify", "push"}

// DetectServices returns the list of Docker service names that should be
// generated in docker-compose.yml based on the current configuration.
//
// Core services (4):     postgres, hasura, auth, nginx (nginx is omitted
//
//	when NGINX_FRONTED_BY is set — see NginxConfig.FrontedBy)
//
// Optional services (6): redis, minio, mailpit (email), search, functions, admin
// Custom services:       CS_1..CS_10
//
// Monitoring and MLflow are free plugins — not generated by core.
//
// Redis auto-enable: when any BullMQ-backed plugin (ai, claw, mux, cron,
// notify) is installed in DefaultPluginDir() and cfg.Redis.Enabled is false,
// "redis" is appended automatically. The compose generator is driven from cfg,
// so callers (e.g. Build) must also set cfg.Redis.Enabled = true before
// passing cfg to compose.NewGenerator to keep both outputs consistent.
func DetectServices(cfg *config.Config) []string {
	// ── Core services (always enabled) ───────────────────────────────
	// nginx is omitted when this stack is fronted by another stack's nginx
	// (NGINX_FRONTED_BY set) — see NginxConfig.FrontedBy and the matching
	// gate in compose.Generator.buildDockerCompose. Without this, `nself
	// status` sizes its total off a nginx container that compose never
	// generates, and reports it unhealthy forever.
	services := []string{"postgres", "hasura", "auth"}
	if cfg.Nginx.FrontedBy == "" {
		services = append(services, "nginx")
	}

	// ── Redis (explicit or auto-enabled by BullMQ plugin) ────────────
	if cfg.Redis.Enabled {
		services = append(services, "redis")
	} else if ShouldAutoEnableRedis(DefaultPluginDir()) {
		// A BullMQ-backed plugin is installed but REDIS_ENABLED was not set.
		// Auto-enable so docker-compose.yml includes the redis service.
		services = append(services, "redis")
	}

	// ── Remaining optional services ───────────────────────────────────
	if svc := compose.StoreService(compose.CurrentStore(cfg)); svc != "" { // D-0683
		services = append(services, svc)
	}
	if cfg.Mailpit.Enabled {
		services = append(services, "mailpit")
	}
	if cfg.Search.Enabled {
		switch cfg.Search.Engine {
		case "typesense":
			services = append(services, "typesense")
		default:
			services = append(services, "meilisearch", "meilisearch-init")
		}
	}
	if cfg.Functions.Enabled {
		services = append(services, "functions")
	}
	if cfg.Admin.Enabled {
		services = append(services, "nself-admin")
	}

	// Monitoring: handled by nself-monitoring free plugin
	// MLflow: handled by nself-mlflow free plugin

	// ── Custom services (CS_1..CS_10) ────────────────────────────────
	for _, cs := range cfg.CustomServices {
		if cs.Name != "" {
			services = append(services, cs.Name)
		}
	}

	return services
}

// ShouldAutoEnableRedis reports whether any BullMQ-backed plugin that requires
// Redis (ai, claw, mux, cron, notify) is installed in pluginDir. Detection is
// based on the presence of a plugin.json manifest file in the plugin's
// sub-directory.
//
// Use DefaultPluginDir() when no override is needed.
func ShouldAutoEnableRedis(pluginDir string) bool {
	for _, name := range pluginsNeedingRedis {
		manifestPath := filepath.Join(pluginDir, name, "plugin.json")
		if _, err := os.Stat(manifestPath); err == nil {
			return true
		}
	}
	return false
}
