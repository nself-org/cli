package agentsetup

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"regexp"
	"strings"
)

// FileName is the project file agents read.
const FileName = "AGENTS.md"

// Verb is one canon verb with its one-line summary, from the registry.
type Verb struct {
	Name    string
	Summary string
}

const markerFmt = "<!-- GENERATED BY nself (mcp setup) sha256:%s — edit freely; nself will not overwrite an edited file -->"

var markerRe = regexp.MustCompile(`^<!-- GENERATED BY nself \(mcp setup\) sha256:([0-9a-f]{64}) — edit freely; nself will not overwrite an edited file -->$`)

// Body renders the AGENTS.md body for the given canon verbs. It holds nothing
// that varies per project, machine or day, so the same registry gives the same
// bytes (init regenerates an unedited file identically).
func Body(verbs []Verb) string {
	var b strings.Builder
	b.WriteString("# AGENTS.md\n\nThis project runs on nSelf. Use the `nself` CLI for every backend operation; do not hand-write Docker Compose files or run SQL against the database directly.\n\n")
	b.WriteString("## Two commands\n\n```\nnself init     # scaffold the project (no prompts when NSELF_NONINTERACTIVE=1)\nnself start    # build and run the stack\n```\n\nRun `nself doctor` when something fails and `nself status` to see what is up.\n\n")
	b.WriteString("## Commands\n\n")
	for _, v := range verbs {
		fmt.Fprintf(&b, "- `nself %s`: %s\n", v.Name, v.Summary)
	}
	b.WriteString("\nRun `nself <command> --help` for flags, `nself help --json` for the full machine-readable command registry.\n\n")
	b.WriteString("## Output and exit codes\n\n")
	b.WriteString("- `--json` prints one document: `{\"schema_version\":\"1\",\"command\":\"<path>\",\"data\":{...}}` on success, or `{\"schema_version\":\"1\",\"command\":\"<path>\",\"error\":{...}}` on failure. Parse stdout only; messages go to stderr.\n")
	b.WriteString("- Exit codes: 0 ok, 1 user error (bad input), 2 infrastructure error (Docker, network), 3 auth error, 4 destructive action blocked.\n")
	b.WriteString("- Every error carries a code (`E401`) with a fix: `nself help --json` and the `nself://errors` MCP resource list them.\n\n")
	b.WriteString("## MCP\n\n")
	b.WriteString("`nself mcp` serves the CLI as MCP tools over stdio. Register it with your client: `nself mcp setup --client claude-code --write` (also `cursor`; `codex` and `generic` print the config). Tools mirror the commands above; destructive tools ask for a confirmation round trip first.\n")
	return b.String()
}

func bodyHash(body string) string {
	s := sha256.Sum256([]byte(body))
	return hex.EncodeToString(s[:])
}

// Render returns the full AGENTS.md: the generated marker line, then the body.
func Render(verbs []Verb) string {
	body := Body(verbs)
	return fmt.Sprintf(markerFmt, bodyHash(body)) + "\n" + body
}

// Unedited reports whether content is a file nself generated and nobody has
// changed since: the first line is the marker and its hash matches the rest.
func Unedited(content string) bool {
	first, body, ok := strings.Cut(content, "\n")
	if !ok {
		return false
	}
	m := markerRe.FindStringSubmatch(first)
	return m != nil && m[1] == bodyHash(body)
}

// MayWrite reports whether nself may write AGENTS.md over the existing content:
// the file is absent (exists false) or is an unedited generated file.
func MayWrite(exists bool, content string) bool {
	return !exists || Unedited(content)
}
