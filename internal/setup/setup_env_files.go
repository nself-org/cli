// setup_env_files.go — .env file generation for a new project.
//
// Purpose: write the standard and demo .env files (and set their permissions) for a freshly initialized project, used by Initialize in setup.go, split out for file size.
// The .env.example and --full multi-environment builders live in setup_env_files_full.go (further split for the same reason).
// Inputs: the resolved Options and secrets from setup_resolve.go.
// Outputs: .env files written to the project directory with 0600 permissions.
// Constraints: pure move from setup.go (CLI-R12 Batch E); no behaviour change. Per the CLI go.md rule, any code writing a .env* file chmods 0600 immediately after -- preserved as-is.

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/nself-org/cli/internal/compat"
)

// WriteEnvFile writes env file content to path with restrictive 0600
// permissions (owner read/write only). Parent directories are created
// as needed.
func WriteEnvFile(path string, content []byte) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0755); err != nil {
		return fmt.Errorf("creating directory for env file: %w", err)
	}
	if err := os.WriteFile(path, content, 0600); err != nil {
		return fmt.Errorf("write env file %s: %w", path, err)
	}
	return nil
}

// EnsureEnvFilePermissions fixes the permissions of an existing env file to
// 0600 if they are more permissive. It is a no-op if the file does not exist.
func EnsureEnvFilePermissions(path string) error {
	info, err := os.Stat(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("stat env file %s: %w", path, err)
	}
	if info.Mode().Perm() != 0600 {
		if err := os.Chmod(path, 0600); err != nil {
			return fmt.Errorf("chmod env file %s: %w", path, err)
		}
	}
	return nil
}

// buildDomainLine builds the BASE_DOMAIN line with an optional preceding comment.
func buildDomainLine(baseDomain, domainComment string) string {
	if domainComment != "" {
		return domainComment + "\nBASE_DOMAIN=" + baseDomain
	}
	return "BASE_DOMAIN=" + baseDomain
}

