package plugincheck

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const openConf = "server { listen 80; server_name backup.example.test; location / { proxy_pass http://backup:3050; } }\n"

func writePlugin(t *testing.T, dir, name, manifest string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Join(dir, name), 0o755); err != nil {
		t.Fatal(err)
	}
	if manifest != "" {
		if err := os.WriteFile(filepath.Join(dir, name, "plugin.json"), []byte(manifest), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func TestLeaveClosedByDefault(t *testing.T) {
	dir := t.TempDir()
	for name, manifest := range map[string]string{
		"false":     `{"nginx":{"public":false}}`,
		"string":    `{"nginx":{"public":"true"}}`,
		"malformed": `{"nginx":`,
		"absent":    `{"name":"absent"}`,
		"missing":   "",
	} {
		writePlugin(t, dir, name, manifest)
		if Public(dir, name) {
			t.Errorf("%s: read as public", name)
		}
		why, fix := Leave(dir, name, openConf, nil, true)
		if why != HoldReason || !strings.Contains(fix, `"nginx": {"public": true}`) || !strings.Contains(fix, name) {
			t.Errorf("%s: Leave = %q, %q", name, why, fix)
		}
	}
}

func TestLeaveInjects(t *testing.T) {
	dir := t.TempDir()
	writePlugin(t, dir, "stripe", `{"name":"stripe","nginx":{"public":true}}`)
	if why, _ := Leave(dir, "stripe", openConf, nil, true); why != "" {
		t.Errorf("declared public conf left out: %s", why)
	}
	gated := "server { listen 80; allow 127.0.0.1; allow ::1; deny all; location / { proxy_pass http://cron:1; } }"
	if why, _ := Leave(dir, "cron", gated, nil, true); why != "" {
		t.Errorf("loopback-gated conf left out: %s", why)
	}
	// nginx refusing the file comes first, public or not.
	if why, _ := Leave(dir, "stripe", "location / { }", nil, true); !strings.Contains(why, "top-level location") {
		t.Errorf("Skip reason lost: %q", why)
	}
}

type memSites map[string]string

func (m memSites) ReadFile(p string) ([]byte, error) {
	if v, ok := m[p]; ok {
		return []byte(v), nil
	}
	return nil, os.ErrNotExist
}

func (m memSites) Remove(p string) error { delete(m, p); return nil }

func TestDropOwn(t *testing.T) {
	s := memSites{"own": "# Generated by nself build\n" + OwnerPrefix + "proj/backup\nserver {}", "other": OwnerPrefix + "other/backup\n", "core": "server {}"}
	for _, p := range []string{"own", "other", "core", "absent"} {
		if err := DropOwn(s, p, "proj/backup"); err != nil {
			t.Fatal(err)
		}
	}
	if _, ok := s["own"]; ok {
		t.Error("own copy kept")
	}
	if _, ok := s["other"]; !ok {
		t.Error("another owner's file removed")
	}
	if _, ok := s["core"]; !ok {
		t.Error("an unstamped file removed")
	}
}

// unreadableSites fails every read with an error other than "not found".
type unreadableSites struct{}

func (unreadableSites) ReadFile(string) ([]byte, error) { return nil, os.ErrPermission }
func (unreadableSites) Remove(string) error             { return nil }

func TestDropOwnFailsOnUnreadableFile(t *testing.T) {
	if err := DropOwn(unreadableSites{}, "own", "proj/backup"); err == nil {
		t.Fatal("an unreadable file passed as cleaned; a stale ungated conf could keep serving")
	}
}

// failingRemove reads a stamped file but cannot remove it.
type failingRemove struct{ err error }

func (f failingRemove) ReadFile(string) ([]byte, error) {
	return []byte(OwnerPrefix + "proj/backup\n"), nil
}
func (f failingRemove) Remove(string) error { return f.err }

func TestDropOwnRemoveErrors(t *testing.T) {
	if err := DropOwn(failingRemove{os.ErrPermission}, "own", "proj/backup"); err == nil {
		t.Fatal("a stale ungated conf that could not be removed passed as cleaned")
	}
	// A file that vanished between the read and the remove is already gone.
	if err := DropOwn(failingRemove{os.ErrNotExist}, "own", "proj/backup"); err != nil {
		t.Fatalf("already-removed file failed the build: %v", err)
	}
}

func TestOwnerOf(t *testing.T) {
	for _, c := range []struct{ name, in, want string }{
		{"second line", "# Generated\n" + OwnerPrefix + " a/b \nx", "a/b"},
		{"none", "server {}\n", ""},
		{"past the header", "1\n2\n3\n4\n5\n" + OwnerPrefix + "a/b\n", ""},
	} {
		if got := OwnerOf(c.in); got != c.want {
			t.Errorf("%s: OwnerOf = %q, want %q", c.name, got, c.want)
		}
	}
}
