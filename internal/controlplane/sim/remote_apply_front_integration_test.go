//go:build integration

package sim_test

// P7-DEPL-30 simulation: a project fronted by another stack's nginx. A real sshd
// host (the deploy-sim stub host of remote_apply_integration_test.go) receives the
// fronting stack's nginx/sites as the second artifact root through
// deploy.ApplyRemote. The host has no docker daemon: the docker stub of that file
// is installed as docker-base, and a thin wrapper in front of it answers the
// fronting nginx commands (docker ps by compose labels, docker inspect, docker exec)
// and records them in /tmp/sim-front.log. Requires INTEGRATION=1 and Docker.

import (
	"context"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/nself-org/cli/internal/deploy"
)

const frontCID = "feedfacefeedfacefeedfacefeedfacefeedfacefeedfacefeedfacefeedface"

// frontDockerWrapper answers the fronting nginx commands and hands everything else
// to the project's docker stub.
const frontDockerWrapper = `#!/bin/sh
case "$1" in
  ps) echo "$*" >> /tmp/sim-front.log; cat /tmp/sim-front-ps.txt; exit 0 ;;
  inspect)
    case "$*" in
      *"{{.State.Running}}"*) echo "$*" >> /tmp/sim-front.log; cat /tmp/sim-front-running 2>/dev/null || echo true; exit 0 ;;
      *".Mounts"*) echo "$*" >> /tmp/sim-front.log; cat /tmp/sim-front-mounts.txt; exit 0 ;;
    esac ;;
  exec)
    echo "$*" >> /tmp/sim-front.log
    if [ -f /tmp/sim-front-nginx-fail ]; then echo "nginx: [emerg] simulated failure" >&2; exit 1; fi
    exit 0 ;;
esac
exec /usr/local/bin/docker-base "$@"
`

func TestSimRemoteApplyFrontRoot(t *testing.T) {
	h := startHost(t)
	ctx := context.Background()
	front := filepath.Dir(h.rp)
	h.put("/usr/local/bin/docker-base", dockerStub)
	h.put("/usr/local/bin/docker", frontDockerWrapper)
	h.sh("chmod 755 /usr/local/bin/docker /usr/local/bin/docker-base")
	// The project has no nginx service of its own: the fronting stack's nginx serves it.
	h.scenario(" Container proj-web-1 Recreate\n")
	h.put("/tmp/sim-model.json", `{"name":"proj","services":{"web":{"image":"web:1","restart":"always"},"db":{"image":"postgres:16","restart":"unless-stopped","healthcheck":{"test":["CMD","pg_isready"]},"volumes":[{"type":"volume","source":"pgdata","target":"/var/lib/postgresql/data"}]}}}`)
	h.put("/tmp/sim-services.txt", "db\nweb\n")
	h.put("/tmp/sim-front-ps.txt", frontCID+"\tnself-web-nginx-1\t"+front+"\nbeef\tother-stack-nginx\t/srv/other\n")
	h.put("/tmp/sim-front-mounts.txt", "bind|"+front+"/nginx|/etc/nginx\nbind|"+front+"/ssl|/etc/nginx/ssl\n")
	// The fronting stack: its own .env and compose file, another project's site, and
	// this project's site as the previous deploy left it.
	oldAPI := "# Generated by nself build - DO NOT EDIT MANUALLY\n# front v1\n"
	h.put(front+"/.env", "FRONT_SECRET=1\n")
	h.put(front+"/docker-compose.yml", "services: {nginx: {image: nginx}}\n")
	h.put(front+"/nginx/sites/api.conf", oldAPI)
	h.put(front+"/nginx/sites/sibling.conf", "# Generated by nself build - DO NOT EDIT MANUALLY\n# another project\n")
	h.put(h.rp+"/docker-compose.yml", "# v0\n")
	h.put(h.rp+"/.env", "HOST_ONLY=1\n")
	h.own()
	own := h.sh("sha256sum " + front + "/.env " + front + "/docker-compose.yml " + front + "/nginx/sites/sibling.conf")
	inode := h.sh("stat -c %i " + front + "/nginx")

	set, _ := stageSet(t, h.rp, "1")
	newAPI := "# Generated by nself build - DO NOT EDIT MANUALLY\n# front v2\n"
	stageDir := localStage(t, map[string]string{
		"nginx/sites/api.conf": newAPI,
		"nginx/sites/new.conf": "# Generated by nself build - DO NOT EDIT MANUALLY\n# new\n",
	})
	set.Front = &deploy.FrontRoot{StageDir: stageDir, RemotePath: front, Files: []string{"nginx/sites/api.conf", "nginx/sites/new.conf"}}
	opts := func() deploy.ApplyOptions {
		o := h.options(set, h.remote(), true)
		o.Previous = nil
		return o
	}

	// 1. nginx -t fails in the fronting container: both roots are put back, nothing reloaded.
	h.put("/tmp/sim-front-nginx-fail", "1")
	if _, err := deploy.ApplyRemote(ctx, opts()); err == nil || !strings.Contains(err.Error(), "nginx -t failed in the fronting container") {
		t.Fatalf("failing nginx -t: %v", err)
	}
	if got := h.sh("cat " + front + "/nginx/sites/api.conf"); got+"\n" != oldAPI {
		t.Errorf("api.conf after the failed deploy = %q, want the old bytes", got)
	}
	if h.sh("test -e "+front+"/nginx/sites/new.conf && echo left || echo gone") != "gone" {
		t.Error("the front file the failed deploy created survived")
	}
	if got := h.sh("cat " + h.rp + "/docker-compose.yml"); got != "# v0" {
		t.Errorf("the main root was not restored: %q", got)
	}
	if strings.Contains(h.sh("cat /tmp/sim-front.log"), "reload") {
		t.Error("nginx was reloaded after a failed nginx -t")
	}
	h.sh("rm -f /tmp/sim-front-nginx-fail /tmp/sim-front.log /tmp/sim-docker.log /tmp/sim-nself.log /tmp/sim-up-*")

	// 2. The deploy: front files shipped, nginx -t then reload on the label-resolved container ID.
	res, err := deploy.ApplyRemote(ctx, opts())
	if err != nil {
		t.Fatal(err)
	}
	for rel, want := range map[string]string{"nginx/sites/api.conf": newAPI, "nginx/sites/new.conf": "# new"} {
		if got := h.sh("cat " + front + "/" + rel); !strings.Contains(got, strings.TrimSpace(strings.TrimPrefix(want, "# Generated by nself build - DO NOT EDIT MANUALLY\n"))) {
			t.Errorf("%s on the host = %q", rel, got)
		}
	}
	if got := h.sh("sha256sum " + front + "/.env " + front + "/docker-compose.yml " + front + "/nginx/sites/sibling.conf"); got != own {
		t.Errorf("the fronting stack's own files changed:\n%s\nwas:\n%s", got, own)
	}
	if got := h.sh("tar -tzf " + res.FrontTar); got != "nginx/sites/api.conf" {
		t.Errorf("front tar holds %q, want only the previously present shipped path", got)
	}
	log := h.sh("cat /tmp/sim-front.log")
	prev := -1
	for _, want := range []string{"ps --no-trunc", "exec " + frontCID + " nginx -t", "exec " + frontCID + " nginx -s reload"} {
		i := strings.Index(log, want)
		if i <= prev {
			t.Fatalf("%q out of order in:\n%s", want, log)
		}
		prev = i
	}
	if strings.Contains(h.dockerLog(), "nginx -s reload") {
		t.Error("the project model's nginx was reloaded")
	}
	if h.sh("stat -c %i "+front+"/nginx") != inode {
		t.Error("the fronting stack's nginx/ directory was replaced: its inode changed")
	}

	// 3. Rollback restores the front files in place from the recorded front tar and reloads.
	h.sh("rm -f /tmp/sim-front.log")
	if err := deploy.RollbackRemote(ctx, deploy.RollbackOptions{
		Remote: h.remote(), RemotePath: h.rp, Tar: res.PreDeployTar, BackupID: res.BackupID, Changed: res.Changed, Absent: res.Absent,
		FrontTar: res.FrontTar, FrontChanged: res.FrontChanged, FrontAbsent: res.FrontAbsent, StrictHasura: true,
	}); err != nil {
		t.Fatal(err)
	}
	if got := h.sh("cat " + front + "/nginx/sites/api.conf"); got+"\n" != oldAPI {
		t.Errorf("api.conf after the rollback = %q", got)
	}
	if h.sh("test -e "+front+"/nginx/sites/new.conf && echo left || echo gone") != "gone" {
		t.Error("the front file the deploy created survived the rollback")
	}
	if got := h.sh("sha256sum " + front + "/.env " + front + "/docker-compose.yml " + front + "/nginx/sites/sibling.conf"); got != own {
		t.Errorf("the rollback changed the fronting stack's own files")
	}
	log = h.sh("cat /tmp/sim-front.log")
	if i, j := strings.Index(log, "nginx -t"), strings.Index(log, "nginx -s reload"); i < 0 || j <= i {
		t.Errorf("rollback did not run nginx -t then reload:\n%s", log)
	}
	if h.sh("stat -c %i "+front+"/nginx") != inode {
		t.Error("the rollback replaced the fronting stack's nginx/ directory")
	}
}

// localStage writes files (relative path -> body) into a new local stage dir.
func localStage(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for rel, body := range files {
		p := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}
