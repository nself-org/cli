package frontcheck

import (
	"reflect"
	"strings"
	"testing"
)

func TestBuildMarkerMustBeWithinHeader(t *testing.T) {
	const marker = "# Generated by nself"
	for _, tc := range []struct {
		conf string
		want bool
	}{
		{marker + " build\nserver {}", true},
		{strings.Repeat("# header\n", 4) + marker, true},
		{strings.Repeat("# header\n", 5) + marker, false},
		{" " + marker, false},
		{"server {}", false},
	} {
		if got := HasBuildMarker(tc.conf, marker); got != tc.want {
			t.Errorf("marker in %q = %t, want %t", tc.conf, got, tc.want)
		}
	}
}

func TestServerNamesEstablishOwnership(t *testing.T) {
	conf := "# server_name foreign.example;\nserver { server_name b.example a.example; }\nserver_name a.example; # server_name ignored.example;\n"
	got := ServerNameSet(conf)
	want := []string{"a.example", "b.example"}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("names = %v, want %v", got, want)
	}
	if !SameNames(got, want) {
		t.Fatal("identical sorted names must establish ownership")
	}
	if SameNames(got, []string{"a.example"}) || SameNames(nil, nil) || SameNames(got, nil) {
		t.Fatal("different or empty names must not establish ownership")
	}
	if names := ServerNameSet("# server_name comment.example;"); len(names) != 0 {
		t.Fatalf("comment establishes ownership: %v", names)
	}
}
