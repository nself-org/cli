package deploy

// Purpose: the second artifact root of a project fronted by another stack's
//          nginx (NGINX_FRONTED_BY, D-0425). The build writes the per-service
//          nginx/sites/*.conf files into the fronting stack's directory, not the
//          project's, so a deploy has to stage them as their own root whose
//          remote path is path.Dir(remote_path).
// Inputs:  StageInput.FrontScratch (local scratch root of the fronting stack,
//          the parent of Map.ScratchRoot), StageInput.FrontedBy, the NginxPolicy.
// Outputs: ArtifactSet.Front (stage dir, remote path, relative files).
// Constraints: only nginx/sites/*.conf files generated by this build ship from
//              the front root, never ssl and nothing else. The same guards as the
//              main root apply: size cap, safe relative paths, no surviving
//              local path. The host layout must follow the convention
//              (path.Base(path.Dir(remote_path)) == FrontedBy), else E485 and
//              nothing is sent. Paths are rewritten in this order: the project
//              root (<front>/<leaf>) to remote_path, then the front root to
//              path.Dir(remote_path) (PathMap.FrontRoot, longest first).
//              ApplyRemote ships a Front with the same guards (apply_remote_front.go).

import (
	"fmt"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"

	"github.com/nself-org/cli/internal/errs"
)

// FrontRoot is the fronting stack's artifact root.
type FrontRoot struct {
	StageDir   string   // where the files are staged locally
	RemotePath string   // the fronting stack's directory on the host
	Files      []string // relative to StageDir and RemotePath ("nginx/sites/<x>.conf")
	// Previous are, per host (the Remote label), the front paths this project's
	// previous deploy shipped there (the local deploy.json record); only they may
	// be pruned. Set by the command.
	Previous map[string][]string
	// PreviousNames are, per host and path, the server_name set that deploy shipped
	// there; a path without an entry is unknown (an old record) and is never pruned.
	PreviousNames map[string]map[string][]string
}

// checkFrontLayout validates the fronted inputs of in: both or neither of
// FrontScratch and FrontedBy, FrontScratch is the parent of the scratch project,
// and the host's remote_path sits directly under a directory named FrontedBy.
func checkFrontLayout(in StageInput) error {
	if in.FrontScratch == "" && in.FrontedBy == "" {
		return nil
	}
	if in.FrontScratch == "" || in.FrontedBy == "" || filepath.Dir(in.Map.ScratchRoot) != in.FrontScratch {
		return fmt.Errorf("deploy: inconsistent fronted layout (front root %q, fronted by %q, project %q); nothing was sent", in.FrontScratch, in.FrontedBy, in.Map.ScratchRoot)
	}
	if got := path.Base(path.Dir(in.Map.RemotePath)); got != in.FrontedBy {
		return errs.New("E485", fmt.Sprintf("NGINX_FRONTED_BY=%s but remote_path %q is not directly under a directory named %q on the host", in.FrontedBy, in.Map.RemotePath, in.FrontedBy)).
			WithFix(fmt.Sprintf("lay the project out on the host as <dir>/%s/<project> and set the server's remote_path to it, or unset NGINX_FRONTED_BY if this project fronts itself; nothing was sent", in.FrontedBy))
	}
	return nil
}

// stageFront stages the fronting stack's nginx/sites/*.conf files that this
// build generated. It returns nil for a project that runs its own nginx.
func stageFront(in StageInput) (*FrontRoot, error) {
	if in.FrontScratch == "" {
		return nil, nil
	}
	front := &FrontRoot{StageDir: in.StageDir + "-front", RemotePath: path.Dir(in.Map.RemotePath)}
	if err := os.RemoveAll(front.StageDir); err != nil {
		return nil, fmt.Errorf("clearing %s: %w", front.StageDir, err)
	}
	if err := os.MkdirAll(front.StageDir, 0o700); err != nil {
		return nil, fmt.Errorf("creating %s: %w", front.StageDir, err)
	}
	nginxDir, relRoot := nginxDirOf(in.FrontScratch)
	sites := filepath.Join(nginxDir, "sites")
	entries, err := os.ReadDir(sites)
	if err != nil && !os.IsNotExist(err) {
		return nil, fmt.Errorf("reading %s: %w", sites, err)
	}
	for _, e := range entries {
		rel := path.Join(relRoot, "sites", e.Name())
		if !e.Type().IsRegular() || !strings.HasSuffix(e.Name(), ".conf") || !pruneable(rel) {
			continue
		}
		src := filepath.Join(sites, e.Name())
		head, err := readHead(src)
		if err != nil {
			return nil, fmt.Errorf("reading the head of %s: %w", src, err)
		}
		if !in.Nginx.generated(head) {
			continue // not written by this build: never shipped from the front root
		}
		data, err := readCapped(src)
		if err != nil {
			return nil, err
		}
		dst := filepath.Join(front.StageDir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
			return nil, err
		}
		if err := os.WriteFile(dst, []byte(in.Map.Rewrite(string(data))), 0o644); err != nil {
			return nil, err
		}
		front.Files = append(front.Files, rel)
	}
	sort.Strings(front.Files)
	return front, checkNoLocalPaths(in.Map, front.StageDir, front.Files)
}
