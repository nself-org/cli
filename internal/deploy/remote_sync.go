package deploy

// Purpose: put an ArtifactSet on a host in place and tidy only what the
//          generator owns (D24 steps 5): rsync with no delete, env files
//          0600 and asserted, and a remote prune that removes a file only
//          when it carries the generated marker and the new set dropped it.
// Inputs:  a Remote, the staged ArtifactSet.
// Outputs: the list of files the prune removed.
// Constraints: no rsync --delete, no other delete over a directory. The prune
//              reads the first lines of each candidate for the marker before
//              it removes that one file. Nothing under a conf.d*/ dir and no
//              unmarked file is ever a candidate (a shipped nginx/conf.d/<name>.conf
//              is synced and restored but never pruned: PrunePrevious uses
//              pruneable, not shippable). No directory is moved.

import (
	"context"
	"fmt"
	"os"
	"path"
	"sort"
	"strings"
)

// GeneratedMarker is the case-insensitive text every generated file carries in
// its first lines: "GENERATED BY nself ... DO NOT HAND EDIT" and the nginx
// templates' "Generated by nself build - DO NOT EDIT MANUALLY".
const GeneratedMarker = "generated by nself"

// ShippedFile lists, one relative path per line, what the last v1.5 deploy
// shipped to the host. The prune only ever considers paths from this list, so a
// marker-carrying file nSelf never shipped here (another project's conf) stays.
const ShippedFile = ".nself/deploy-shipped.txt"

// SyncArtifacts copies the set into remotePath in place, then checks the env
// file modes. It never deletes anything.
func SyncArtifacts(ctx context.Context, r Remote, set ArtifactSet) error {
	if err := checkConfDFiles(set.Files); err != nil {
		return err
	}
	if set.KeepHostEnv {
		script := fmt.Sprintf(`umask 077; mkdir -p %s; if [ ! -e %s ]; then : > %s; fi`, q(set.RemotePath), q(path.Join(set.RemotePath, ".env")), q(path.Join(set.RemotePath, ".env")))
		if _, err := r.Run(ctx, shScript(script)); err != nil {
			return fmt.Errorf("preparing .env on %s: %w", r.Label(), err)
		}
	}
	if len(set.Files) > 0 {
		if err := rsyncList(ctx, r, set, set.Files, nil); err != nil {
			return err
		}
	}
	if len(set.EnvFiles) > 0 {
		if err := rsyncList(ctx, r, set, set.EnvFiles, []string{"--chmod=F600"}); err != nil {
			return err
		}
		if err := assertEnvModes(ctx, r, set); err != nil {
			return err
		}
	}
	return writeShipped(ctx, r, set)
}

// checkConfDFiles refuses a set that lists a path under a conf.d* dir other than
// a generated nginx/conf.d/<name>.conf (see shippable): conf.d stays hand-managed.
func checkConfDFiles(files []string) error {
	for _, f := range files {
		if strings.Contains(f, "conf.d") && !shippable(f) {
			return fmt.Errorf("the artifact set lists %q under conf.d, which only a generated nginx/conf.d/<name>.conf may enter; nothing was synced", f)
		}
	}
	return nil
}

// writeShipped records what this deploy shipped (atomically: temp file, rename).
func writeShipped(ctx context.Context, r Remote, set ArtifactSet) error {
	file := path.Join(set.RemotePath, ShippedFile)
	lines := append(append([]string{}, set.Files...), set.EnvFiles...)
	script := fmt.Sprintf(`umask 077; mkdir -p %s; rm -f -- %s; printf '%%s\n' %s > %s && mv -f %s %s`,
		q(path.Dir(file)), q(file+".new"), strings.Join(quoteAll(lines), " "), q(file+".new"), q(file+".new"), q(file))
	if _, err := r.Run(ctx, shScript(script)); err != nil {
		return fmt.Errorf("recording the shipped file list on %s: %w", r.Label(), err)
	}
	return nil
}

func rsyncList(ctx context.Context, r Remote, set ArtifactSet, rels, flags []string) error {
	linked, err := ResolveDirs(ctx, r, set.RemotePath, layoutDirs(rels))
	if err != nil {
		return err
	}
	// Parents are made here (umask 022), never transferred by rsync: an implied
	// parent dir would take the stage dir's mode and re-mode the host's own.
	if dirs := layoutDirsOnly(rels); len(dirs) > 0 {
		mk := fmt.Sprintf(`cd %s && (umask 022; mkdir -p %s)`, q(set.RemotePath), strings.Join(quoteAll(dirs), " "))
		if _, err := r.Run(ctx, shScript(mk)); err != nil {
			return fmt.Errorf("creating directories on %s: %w", r.Label(), err)
		}
	}
	// One rsync per destination directory over bare file names, so no directory
	// entry is ever transferred (no --no-implied-dirs, which Apple's rsync 2.6.9
	// rejects). A directory that is, or sits behind, a symlink inside remote_path
	// goes to its real path: rsync >= 3.4 refuses to traverse a symlink in the
	// destination even with --keep-dirlinks, and a real dir must never replace it.
	byDir := map[string][]string{}
	for _, rel := range rels {
		byDir[path.Dir(rel)] = append(byDir[path.Dir(rel)], path.Base(rel))
	}
	dirs := make([]string, 0, len(byDir))
	for d := range byDir {
		dirs = append(dirs, d)
	}
	sort.Strings(dirs)
	for _, d := range dirs {
		src, dest := set.StageDir, set.RemotePath
		if d != "." {
			src, dest = path.Join(set.StageDir, d), path.Join(set.RemotePath, d)
		}
		if real, ok := linked[d]; ok {
			dest = real
		}
		if err := rsyncFiles(ctx, r, flags, byDir[d], src, dest); err != nil {
			return err
		}
	}
	return nil
}

func rsyncFiles(ctx context.Context, r Remote, flags, rels []string, srcDir, destDir string) error {
	list, err := os.CreateTemp("", "nself-deploy-files-*")
	if err != nil {
		return err
	}
	defer func() { _ = os.Remove(list.Name()) }()
	_, werr := list.WriteString(strings.Join(rels, "\n") + "\n")
	if cerr := list.Close(); werr == nil {
		werr = cerr
	}
	if werr != nil {
		return werr
	}
	return r.Rsync(ctx, flags, list.Name(), srcDir, destDir)
}

// assertEnvModes fails unless every shipped env file is mode 600 on the host.
func assertEnvModes(ctx context.Context, r Remote, set ArtifactSet) error {
	var quoted []string
	for _, rel := range set.EnvFiles {
		quoted = append(quoted, q(path.Join(set.RemotePath, rel)))
	}
	script := fmt.Sprintf(`for f in %s; do m=$(stat -c %%a "$f" 2>/dev/null || stat -f %%Lp "$f"); printf '%%s %%s\n' "$m" "$f"; done`, strings.Join(quoted, " "))
	out, err := r.Run(ctx, shScript(script))
	if err != nil {
		return fmt.Errorf("checking env file modes on %s: %w", r.Label(), err)
	}
	for _, line := range strings.Split(strings.TrimSpace(string(out)), "\n") {
		if mode, file, ok := strings.Cut(line, " "); !ok || mode != "600" {
			return fmt.Errorf("env file %s on %s has mode %s, want 600", file, r.Label(), mode)
		}
	}
	return nil
}

// PrunePrevious removes the files the previous deploy shipped that the new set
// dropped and that carry the generated marker. What may be removed is decided by
// recorded, the local record of that deploy (deploy.json); the host's own shipped
// list (informational) can only narrow it. With no record nothing is removed.
// It returns the files it removed.
func PrunePrevious(ctx context.Context, r Remote, remotePath string, keep map[string]bool, recorded []string) ([]string, error) {
	if len(recorded) == 0 {
		return nil, nil
	}
	known := map[string]bool{}
	for _, f := range recorded {
		known[f] = true
	}
	prev, err := remoteLines(ctx, r, path.Join(remotePath, ShippedFile))
	if err != nil {
		return nil, err
	}
	var cand []string
	for _, f := range prev {
		if known[f] && !keep[f] {
			cand = append(cand, f)
		}
	}
	return PruneMarked(ctx, r, remotePath, cand)
}

// PruneMarked removes, from the candidates (paths relative to remotePath), the
// files that carry the generated marker in their first lines. Entries that are not
// safe project-relative paths (see pruneable) are skipped. A batch in which any
// path resolves outside the project (or is itself a symlink) is refused whole: nothing in it is deleted and the
// error names the path. It returns the files it removed.
func PruneMarked(ctx context.Context, r Remote, remotePath string, candidates []string) ([]string, error) {
	var cand []string
	for _, f := range candidates {
		if pruneable(f) {
			cand = append(cand, f)
		}
	}
	var removed []string
	for len(cand) > 0 {
		n := min(len(cand), 50)
		body := fmt.Sprintf(`if [ -f "$2" ] && head -n 5 -- "$2" 2>/dev/null | grep -qi %s; then rm -f -- "$2" && printf '%%s\n' "$1"; fi`, q(GeneratedMarker))
		out, err := r.Run(ctx, shScript(guardedScript(remotePath, cand[:n], body)))
		if err != nil {
			return removed, fmt.Errorf("pruning generated files on %s: %w", r.Label(), err)
		}
		if err := refusedPaths(out); err != nil {
			return removed, err
		}
		for _, f := range strings.Split(strings.TrimSpace(string(out)), "\n") {
			if f != "" {
				removed = append(removed, f)
			}
		}
		cand = cand[n:]
	}
	return removed, nil
}

// pruneable reports whether rel is a safe project-relative file path: not empty,
// clean, no ".", ".." or empty component, not absolute, not the host's own .env,
// no newline, and not under a conf.d* dir.
func pruneable(rel string) bool {
	if rel == "" || rel != path.Clean(rel) || rel == ".env" || strings.HasPrefix(rel, "/") || strings.Contains(rel, "\n") {
		return false
	}
	for _, seg := range strings.Split(rel, "/") {
		if seg == "" || seg == "." || seg == ".." || strings.HasPrefix(seg, "conf.d") {
			return false
		}
	}
	return true
}

// checkPaths returns an error naming the first entry of a locally recorded list
// that is not a safe shippable path (shippable: a pruneable path or a generated
// nginx/conf.d/<name>.conf); such a list is never acted on. It gates the
// pre-deploy tar and the restore, which therefore cover the shipped conf.d files.
func checkPaths(what string, paths []string) error {
	for _, p := range paths {
		if !shippable(p) {
			return fmt.Errorf("%s holds an unsafe path %q; refusing to act on it", what, p)
		}
	}
	return nil
}

func quoteAll(in []string) []string {
	out := make([]string, len(in))
	for i, s := range in {
		out[i] = q(s)
	}
	return out
}

// KeepSet is the set's relative paths as a lookup.
func (s ArtifactSet) KeepSet() map[string]bool {
	m := map[string]bool{}
	for _, f := range append(append([]string{}, s.Files...), s.EnvFiles...) {
		m[f] = true
	}
	return m
}

// layoutDirsOnly are the distinct parent directories (not ".") of rels, sorted.
func layoutDirsOnly(rels []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, d := range dirsOf(rels) {
		if d != "." && !seen[d] {
			seen[d] = true
			out = append(out, d)
		}
	}
	sort.Strings(out)
	return out
}
