package deploy

// Purpose: the host-file rules for the fronting stack's nginx/sites (D-0425).
//          The generated site names carry no project prefix (hasura.conf,
//          auth.conf, ...), so two projects fronted by one stack can ship the
//          same path. This file replaces CheckNotOverwritingForeign and
//          PruneMarked for the front root.
// Inputs:  a Remote, the front root, the local stage dir, the shipped paths and
//          the paths this host's previous deploy shipped (the local record).
// Outputs: E485 before the lock when a shipped path would overwrite another
//          project's or an unmarked file; the paths the strict prune removed.
// Constraints: only nginx/sites/<name>.conf paths are read (head -c, one quoted
//              script) and nothing else in the front root, ShippedFile
//              included. "Ours" means the strict build marker: a line of the
//              first 5 that starts with BuildNginxMarker (the rule of
//              KeptHostConfD); "# hand-written, NOT generated by nself build"
//              is not ours. A shipped path that this host's record does not list
//              may only replace a marked file whose server_name set equals the
//              shipped file's, so a sibling project's hasura.conf is never
//              replaced while a file the fronting stack generated earlier for
//              this project can be adopted. The prune uses the same marker rule.

import (
	"context"
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// frontConfMax caps how much of a host conf is read.
const frontConfMax = 262144

var serverNameRe = regexp.MustCompile(`\bserver_name[ \t]+([^;]+);`)

// hasBuildMarker is the strict marker rule on conf text.
func hasBuildMarker(conf string) bool {
	for i, line := range strings.Split(conf, "\n") {
		if i >= 5 {
			break
		}
		if strings.HasPrefix(line, BuildNginxMarker) {
			return true
		}
	}
	return false
}

// serverNameSet is the sorted, unique server_name values of the conf (comments dropped).
func serverNameSet(conf string) []string {
	seen := map[string]bool{}
	for _, line := range strings.Split(conf, "\n") {
		line, _, _ = strings.Cut(line, "#")
		for _, m := range serverNameRe.FindAllStringSubmatch(line, -1) {
			for _, n := range strings.Fields(m[1]) {
				seen[n] = true
			}
		}
	}
	out := make([]string, 0, len(seen))
	for n := range seen {
		out = append(out, n)
	}
	sort.Strings(out)
	return out
}

// readFrontConfs reads (head -c) the existing regular, non-symlink files among
// paths in the front root, in one quoted script. A nonce line frames each file.
func readFrontConfs(ctx context.Context, r Remote, front string, paths []string) (map[string]string, error) {
	out := map[string]string{}
	if len(paths) == 0 {
		return out, nil
	}
	var nb [8]byte
	_, _ = rand.Read(nb[:])
	nonce := "@@" + hex.EncodeToString(nb[:])
	script := fmt.Sprintf(`cd %s 2>/dev/null || exit 0; for f in %s; do if [ -f "$f" ] && [ ! -L "$f" ]; then printf '%%s %%s\n' %s "$f"; head -c %d -- "$f"; printf '\n'; fi; done; exit 0`,
		q(front), strings.Join(quoteAll(paths), " "), q(nonce), frontConfMax)
	raw, err := r.Run(ctx, shScript(script))
	if err != nil {
		return nil, fmt.Errorf("reading the fronting stack's existing sites on %s: %w", r.Label(), err)
	}
	inSet := map[string]bool{}
	for _, f := range paths {
		inSet[f] = true
	}
	var cur *strings.Builder
	got := map[string]*strings.Builder{}
	for _, line := range strings.Split(string(raw), "\n") {
		if p, ok := strings.CutPrefix(line, nonce+" "); ok && inSet[p] && got[p] == nil {
			cur = &strings.Builder{}
			got[p] = cur
		} else if cur != nil {
			cur.WriteString(line + "\n")
		}
	}
	for p, b := range got {
		out[p] = b.String()
	}
	return out, nil
}

func localServerNames(stage, rel string) ([]string, error) {
	f, err := os.Open(filepath.Join(stage, filepath.FromSlash(rel)))
	if err != nil {
		return nil, err
	}
	defer func() { _ = f.Close() }()
	b, err := io.ReadAll(io.LimitReader(f, frontConfMax))
	if err != nil {
		return nil, err
	}
	return serverNameSet(string(b)), nil
}

// pruneFrontMarked removes, from the candidates (front paths this host's record
// says the previous deploy shipped), the files that carry the strict build
// marker and, inside the same script, whose server_name set is still the one in
// names (the set read at the check, so a file replaced since then stays). It
// returns the files it removed and a [kept] line for each file it left because
// its set changed.
func pruneFrontMarked(ctx context.Context, r Remote, front string, candidates []string, names map[string][]string) (removed, kept []string, err error) {
	var cand []string
	for _, f := range candidates {
		if frontPathOK(f) {
			cand = append(cand, f)
		}
	}
	pat := q("^" + strings.ReplaceAll(BuildNginxMarker, " ", "[ ]"))
	for len(cand) > 0 {
		n := min(len(cand), 50)
		var want strings.Builder
		for _, f := range cand[:n] {
			if set := names[f]; len(set) > 0 {
				fmt.Fprintf(&want, "%s) want=%s;; ", q(f), q(strings.Join(set, " ")))
			}
		}
		body := strings.NewReplacer("@WANT@", want.String(), "@PAT@", pat, "@MAX@", fmt.Sprint(frontConfMax)).Replace(frontPruneBody)
		out, err := r.Run(ctx, shScript(guardedScript(front, cand[:n], body)))
		if err != nil {
			return removed, kept, fmt.Errorf("pruning generated files on %s: %w", r.Label(), err)
		}
		if err := refusedPaths(out); err != nil {
			return removed, kept, err
		}
		asked := map[string]bool{}
		for _, f := range cand[:n] {
			asked[f] = true
		}
		for _, f := range strings.Split(strings.TrimSpace(string(out)), "\n") {
			if p, ok := strings.CutPrefix(f, "KEPT "); ok && asked[p] {
				kept = append(kept, fmt.Sprintf("[kept] %s/%s (server_name changed since it was checked; not pruned)", front, p))
			} else if asked[f] {
				removed = append(removed, f)
			}
		}
		cand = cand[n:]
	}
	return removed, kept, nil
}

// frontPruneBody is the per-path prune step: the marker rule, then the same
// server_name set as serverNameSet (comments dropped, sorted, unique) compared
// with the recorded one. A path with no recorded set is never removed.
const frontPruneBody = `if [ -f "$2" ] && head -n 5 -- "$2" 2>/dev/null | grep -q @PAT@; then
want=; case "$1" in @WANT@esac
got=$(head -c @MAX@ -- "$2" 2>/dev/null | sed 's/#.*//' | grep -oE '(^|[^[:alnum:]_])server_name[[:space:]]+[^;]+;' | sed -E 's/^.*server_name[[:space:]]+//; s/;$//' | tr -s '[:space:]' '\n' | grep -v '^$' | LC_ALL=C sort -u | tr '\n' ' ')
got=${got% }
if [ -n "$want" ] && [ "$got" = "$want" ]; then rm -f -- "$2" && printf '%s\n' "$1"; else printf 'KEPT %s\n' "$1"; fi
fi`
