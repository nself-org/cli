// buildScratch lays out a scratch project the way a v1.5 build leaves it, with
// local paths everywhere a build writes them.
func buildScratch(t *testing.T) (m PathMap, compose, envs []string, snapshot string) {
	t.Helper()
	return buildScratchFor(t, "/opt/nself")
}

func buildScratchFor(t *testing.T, remotePath string) (m PathMap, compose, envs []string, snapshot string) {
	t.Helper()
	base := t.TempDir()
	operator := filepath.Join(base, "operator", "proj")
	scratch := filepath.Join(operator, ".nself", "deploy-build", "prod")
	plugins := filepath.Join(base, "home", ".nself", "plugins")
	home := filepath.Join(base, "home")
	m = PathMap{ScratchRoot: scratch, OperatorRoot: operator, PluginDir: plugins, Home: home, RemotePath: remotePath}
	writeFile(t, filepath.Join(scratch, "docker-compose.yml"), "services:\n  nginx:\n    volumes:\n      - "+scratch+"/nginx:/etc/nginx:ro\n      - "+scratch+"/ssl:/etc/nginx/ssl:ro\n  web:\n    env_file: "+operator+"/.env\n", 0o644)
	writeFile(t, filepath.Join(plugins, "ai", "docker-compose.plugin.yml"), "services:\n  ai:\n    build:\n      context: "+plugins+"/ai\n", 0o644)
	writeFile(t, filepath.Join(scratch, ".env"), "PROJECT=x\nNSELF_PLUGIN_DIR="+plugins+"\n", 0o600)
	writeFile(t, filepath.Join(scratch, ".nself", "compose.env"), "NSELF_PLUGIN_DIR="+plugins+"\n", 0o644)
	writeFile(t, filepath.Join(scratch, "nginx", "nginx.conf"), "# Generated by nself build - DO NOT EDIT MANUALLY\ninclude "+scratch+"/nginx/sites/*.conf;\n", 0o644)
	writeFile(t, filepath.Join(scratch, "nginx", "sites", "api.conf"), "# Generated by nself build - DO NOT EDIT MANUALLY\nssl_certificate /etc/nginx/ssl/certificates/api-example-com/fullchain.pem;\n", 0o644)
	writeFile(t, filepath.Join(scratch, "nginx", "conf.d", "default.conf"), "# Generated by nself build\n", 0o644)
	writeFile(t, filepath.Join(scratch, "hasura", "metadata", "version.yaml"), "version: 3\n", 0o644)
	writeFile(t, filepath.Join(scratch, "ssl", "certificates", "api-example-com", "fullchain.pem"), "STUB", 0o644)
	snapshot = filepath.Join(scratch, ".nself-deploy-env.tmp")
	writeFile(t, snapshot, "ENV=prod\nHASURA=http://x\n", 0o600)
	return m, []string{filepath.Join(scratch, "docker-compose.yml"), filepath.Join(plugins, "ai", "docker-compose.plugin.yml")},
		[]string{filepath.Join(scratch, ".env"), filepath.Join(scratch, ".nself", "compose.env")}, snapshot
}

func stageIn(m PathMap, compose, envs []string, snapshot string, stage string) StageInput {
	return StageInput{Map: m, StageDir: stage, Compose: compose, EnvFiles: envs, EnvSnapshot: snapshot, EnvName: "prod"}
}

func TestPathMapNoLocalPath(t *testing.T) {
	m, compose, envs, snap := buildScratch(t)
	stage := t.TempDir()
	set, err := Stage(stageIn(m, compose, envs, snap, stage))
	if err != nil {
		t.Fatal(err)
	}
	all := append(append([]string{}, set.Files...), set.EnvFiles...)
	for _, rel := range all {
		body := readFile(t, filepath.Join(stage, rel))
		for _, root := range []string{m.ScratchRoot, m.OperatorRoot, m.PluginDir, m.Home} {
			if strings.Contains(body, root) {
				t.Errorf("shipped file %s still names %s:\n%s", rel, root, body)
			}
		}
	}
	got := readFile(t, filepath.Join(stage, "docker-compose.yml"))
	if !strings.Contains(got, "/opt/nself/nginx:/etc/nginx:ro") || !strings.Contains(got, "env_file: /opt/nself/.env") {
		t.Errorf("compose not mapped to the remote path:\n%s", got)
	}
	if got := readFile(t, filepath.Join(stage, ".nself", "plugins", "ai", "docker-compose.plugin.yml")); !strings.Contains(got, "context: /opt/nself/.nself/plugins/ai") {
		t.Errorf("fragment not mapped to .nself/plugins:\n%s", got)
	}
	if got := readFile(t, filepath.Join(stage, ".nself", "compose-files.txt")); got != "/opt/nself/docker-compose.yml\n/opt/nself/.nself/plugins/ai/docker-compose.plugin.yml\n" {
		t.Errorf("compose-files.txt = %q", got)
	}
	if got := readFile(t, filepath.Join(stage, ".nself", "compose-env-files.txt")); got != "/opt/nself/.env\n/opt/nself/.nself/compose.env\n" {
		t.Errorf("compose-env-files.txt = %q", got)
	}
	// ssl is never shipped, conf.d is never shipped, the env snapshot is an env file.
	for _, rel := range all {
		if strings.HasPrefix(rel, "ssl/") || strings.Contains(rel, "conf.d") {
			t.Errorf("%s must not be shipped", rel)
		}
	}
	if !contains(set.EnvFiles, ".env.prod") || !contains(set.EnvFiles, ".env") || !contains(set.EnvFiles, ".nself/compose.env") {
		t.Errorf("env files %v", set.EnvFiles)
	}
	for _, rel := range set.EnvFiles {
		if info, _ := os.Stat(filepath.Join(stage, rel)); info.Mode().Perm() != 0o600 {
			t.Errorf("staged env file %s mode %v", rel, info.Mode().Perm())
		}
	}
}

func TestPathMapRefusesLeftoverHome(t *testing.T) {
	m, compose, envs, snap := buildScratch(t)
	writeFile(t, envs[0], "KEY="+m.Home+"/.ssh/id\n", 0o600) // home cannot be mapped
	_, err := Stage(stageIn(m, compose, envs, snap, t.TempDir()))
	if err == nil || !strings.Contains(err.Error(), "the home dir") || !strings.Contains(err.Error(), ".env") {
		t.Fatalf("a home path in a shipped file must fail Stage, got %v", err)
	}
	m2, compose2, envs2, snap2 := buildScratch(t)
	other := filepath.Join(filepath.Dir(m2.OperatorRoot), "elsewhere", "docker-compose.yml")
	writeFile(t, other, "x\n", 0o644)
	if _, err := Stage(stageIn(m2, append(compose2, other), envs2, snap2, t.TempDir())); err == nil || !strings.Contains(err.Error(), "outside the scratch project") {
		t.Fatalf("a compose file outside the scratch project and plugin dir must fail, got %v", err)
	}
}

func TestPathMapBoundaries(t *testing.T) {
	m := PathMap{ScratchRoot: "/s/p", OperatorRoot: "/o/proj", PluginDir: "/h/.nself/plugins", Home: "/h", RemotePath: "/opt/nself"}
	got := m.Rewrite("a=/o/proj/x b=/o/proj2/x c=/opt/o/proj/x d=/o/proj e=\"/h/.nself/plugins/ai\"")
	want := "a=/opt/nself/x b=/o/proj2/x c=/opt/o/proj/x d=/opt/nself e=\"/opt/nself/.nself/plugins/ai\""
	if got != want {
		t.Fatalf("rewrite\n got %s\nwant %s", got, want)
	}
	if l := m.Leftovers("/opt/nself/a /h/x"); len(l) != 1 || !strings.Contains(l[0], "home") {
		t.Fatalf("leftovers %v", l)
	}
	// A remote path that starts with the local home is not a leftover.
	m2 := PathMap{ScratchRoot: "/s/p", OperatorRoot: "/o/proj", PluginDir: "/h/.nself/plugins", Home: "/home/u", RemotePath: "/home/u/nself"}
	if l := m2.Leftovers("/home/u/nself/docker-compose.yml"); len(l) != 0 {
		t.Fatalf("remote path under the home dir flagged: %v", l)
	}
}

func contains(ss []string, s string) bool {
	for _, x := range ss {
		if x == s {
			return true
		}
	}
	return false
}
