// frontScratch lays a fronted scratch: <front> holds nginx/sites written by the
// build, <front>/backend is the project. It returns the StageInput for a host at
// remotePath.
func frontScratch(t *testing.T, remotePath string) (StageInput, string) {
	t.Helper()
	base := t.TempDir()
	operator := filepath.Join(base, "operator", "proj")
	front := filepath.Join(operator, ".nself", "deploy-build", "prod", "nself-web")
	scratch := filepath.Join(front, "backend")
	writeFile(t, filepath.Join(scratch, "docker-compose.yml"), "services:\n  web:\n    volumes:\n      - "+scratch+"/nginx:/etc/nginx:ro\n      - "+front+"/nginx/sites:/etc/nginx/sites:ro\n", 0o644)
	writeFile(t, filepath.Join(scratch, ".env"), "PROJECT=x\n", 0o600)
	writeFile(t, filepath.Join(scratch, "nginx", "nginx.conf"), buildMarker+"include "+front+"/nginx/sites/*.conf;\n", 0o644)
	writeFile(t, filepath.Join(front, "nginx", "sites", "api.conf"), buildMarker+"# root "+scratch+"/public\n# front "+front+"/nginx\n", 0o644)
	writeFile(t, filepath.Join(front, "nginx", "sites", "api-docs.conf"), buildMarker, 0o644)
	writeFile(t, filepath.Join(front, "nginx", "sites", "other-stack.conf"), "# not generated by this build\n", 0o644)
	writeFile(t, filepath.Join(front, "nginx", "sites", "note.txt"), buildMarker, 0o644)
	writeFile(t, filepath.Join(front, "ssl", "certificates", "x", "fullchain.pem"), "STUB", 0o644)
	m := PathMap{ScratchRoot: scratch, OperatorRoot: operator, PluginDir: filepath.Join(base, "plugins"), Home: filepath.Join(base, "home"), RemotePath: remotePath}
	return StageInput{
		Map: m, StageDir: filepath.Join(t.TempDir(), "stage"), Compose: []string{filepath.Join(scratch, "docker-compose.yml")},
		EnvFiles: []string{filepath.Join(scratch, ".env")}, EnvName: "prod", Nginx: testPolicy(),
		FrontScratch: front, FrontedBy: "nself-web",
	}, front
}

func TestStageFrontRoot(t *testing.T) {
	in, front := frontScratch(t, "/srv/nself-web/backend")
	if err := os.MkdirAll(in.StageDir, 0o700); err != nil {
		t.Fatal(err)
	}
	set, err := Stage(in)
	if err != nil {
		t.Fatal(err)
	}
	if set.Front == nil || set.Front.RemotePath != "/srv/nself-web" {
		t.Fatalf("Front = %+v", set.Front)
	}
	if got := strings.Join(set.Front.Files, ","); got != "nginx/sites/api-docs.conf,nginx/sites/api.conf" {
		t.Errorf("front files = %q: only marked nginx/sites/*.conf of this build ship from the front root", got)
	}
	if exists(filepath.Join(set.Front.StageDir, "ssl")) {
		t.Error("the front root staged ssl")
	}
	body := readFile(t, filepath.Join(set.Front.StageDir, "nginx", "sites", "api.conf"))
	if !strings.Contains(body, "# root /srv/nself-web/backend/public") || !strings.Contains(body, "# front /srv/nself-web/nginx") || strings.Contains(body, front) {
		t.Errorf("front file not rewritten (project root to remote_path, front root to its parent):\n%s", body)
	}
	compose := readFile(t, filepath.Join(in.StageDir, "docker-compose.yml"))
	if !strings.Contains(compose, "- /srv/nself-web/backend/nginx:/etc/nginx:ro") || !strings.Contains(compose, "- /srv/nself-web/nginx/sites:/etc/nginx/sites:ro") {
		t.Errorf("main compose not mapped in both directions:\n%s", compose)
	}
	for _, f := range set.Files {
		if strings.Contains(f, "sites/api") && strings.HasPrefix(f, "nginx/sites/") {
			t.Errorf("%s from the front root leaked into the main set", f)
		}
	}
	if !contains(set.Files, "nginx/nginx.conf") {
		t.Errorf("main nginx.conf missing: %v", set.Files)
	}
}

func TestStageFrontLayoutMismatchRefused(t *testing.T) {
	for _, remote := range []string{"/srv/other/backend", "/backend", "/srv/nself-web-2/backend"} {
		in, _ := frontScratch(t, remote)
		_, err := Stage(in)
		var ce *errs.CLIError
		if !errors.As(err, &ce) || ce.Code != "E485" || !strings.Contains(err.Error(), "nself-web") {
			t.Errorf("remote_path %q: err = %v, want E485 naming the fronting stack", remote, err)
		}
		if exists(in.StageDir) {
			if entries, _ := os.ReadDir(in.StageDir); len(entries) > 0 {
				t.Errorf("remote_path %q: files were staged before the refusal", remote)
			}
		}
	}
	in, _ := frontScratch(t, "/srv/nself-web/backend")
	in.FrontedBy = ""
	if _, err := Stage(in); err == nil {
		t.Error("a front root without FrontedBy was accepted")
	}
}

func TestPathMapFrontRootBothDirections(t *testing.T) {
	m := PathMap{ScratchRoot: "/w/proj/.nself/deploy-build/prod/nself-web/backend", OperatorRoot: "/w/proj", PluginDir: "/h/.nself/plugins", Home: "/h", RemotePath: "/srv/nself-web/backend", FrontRoot: "/w/proj/.nself/deploy-build/prod/nself-web"}
	in := "a=/w/proj/.nself/deploy-build/prod/nself-web/backend/nginx b=/w/proj/.nself/deploy-build/prod/nself-web/nginx/sites c=/w/proj/.nself/deploy-build/prod/nself-web2/x"
	got := m.Rewrite(in)
	if !strings.Contains(got, "a=/srv/nself-web/backend/nginx") || !strings.Contains(got, "b=/srv/nself-web/nginx/sites") {
		t.Errorf("Rewrite = %q", got)
	}
	if !strings.Contains(got, "c=/srv/nself-web/backend/.nself/deploy-build/prod/nself-web2/x") {
		t.Errorf("a sibling of the front root (nself-web2) must not match the front root on a path boundary: %q", got) // it falls to the operator root
	}
	if left := m.Leftovers(got); len(left) != 0 {
		t.Errorf("Leftovers after rewrite = %v", left)
	}
	if left := m.Leftovers("x " + m.FrontRoot + "/nginx"); len(left) == 0 || !strings.Contains(strings.Join(left, ","), "fronting scratch root") {
		t.Errorf("a surviving front root path is not detected: %v", left)
	}
	if clean := m.Leftovers(path.Join("/srv/nself-web", "nginx") + " /srv/nself-web/backend/x"); len(clean) != 0 {
		t.Errorf("remote paths reported as leftovers: %v", clean)
	}
	// Without a front root the parent is not rewritten to the host's parent dir.
	m.FrontRoot = ""
	if got := m.Rewrite("/w/proj/.nself/deploy-build/prod/nself-web/nginx"); got != "/srv/nself-web/backend/.nself/deploy-build/prod/nself-web/nginx" {
		t.Errorf("Rewrite without a front root = %q", got)
	}
}

func TestStageFrontLeftoverAndGuards(t *testing.T) {
	// A front file that still names the operator's home cannot be rewritten: refused.
	in, front := frontScratch(t, "/srv/nself-web/backend")
	writeFile(t, filepath.Join(front, "nginx", "sites", "api.conf"), buildMarker+"# cert "+in.Map.Home+"/certs\n", 0o644)
	if _, err := Stage(in); err == nil || !strings.Contains(err.Error(), "still names a local path") {
		t.Errorf("a front file naming the home dir: err = %v", err)
	}
	// An oversize front file is refused by the same size cap as the main root.
	in, front = frontScratch(t, "/srv/nself-web/backend")
	writeFile(t, filepath.Join(front, "nginx", "sites", "big.conf"), buildMarker+strings.Repeat("x", maxStagedFile), 0o644)
	if _, err := Stage(in); err == nil || !strings.Contains(err.Error(), "byte limit") {
		t.Errorf("an oversize front file: err = %v", err)
	}
	// A symlink in the front sites dir is not a regular file and never ships.
	in, front = frontScratch(t, "/srv/nself-web/backend")
	if err := os.Symlink(filepath.Join(front, "nginx", "sites", "api.conf"), filepath.Join(front, "nginx", "sites", "link.conf")); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	set, err := Stage(in)
	if err != nil {
		t.Fatal(err)
	}
	if contains(set.Front.Files, "nginx/sites/link.conf") {
		t.Errorf("a symlink was staged: %v", set.Front.Files)
	}
	// A project without a fronting stack has no front root.
	in, _ = frontScratch(t, "/opt/nself")
	in.FrontScratch, in.FrontedBy = "", ""
	if set, err := Stage(in); err != nil || set.Front != nil {
		t.Errorf("unfronted: front %+v err %v", set.Front, err)
	}
}
