const markedConf = "# Generated by nself build - DO NOT EDIT MANUALLY\nserver { listen 80; }\n"

func TestArtifactsSyncNoDelete(t *testing.T) {
	m, compose, envs, snap := buildScratch(t)
	set, err := Stage(stageIn(m, compose, envs, snap, t.TempDir()))
	if err != nil {
		t.Fatal(err)
	}
	f := newFakeRemote(t)
	rp := t.TempDir()
	set.RemotePath = rp
	// What the host has already.
	writeFile(t, filepath.Join(rp, "nginx", "sites", "foreign.conf"), "# written by hand\nserver { listen 8080; }\n", 0o644)
	writeFile(t, filepath.Join(rp, "nginx", "sites", "old-generated.conf"), markedConf, 0o644)
	writeFile(t, filepath.Join(rp, "nginx", "sites", "api.conf"), markedConf+"# stale\n", 0o644)
	writeFile(t, filepath.Join(rp, "nginx", "conf.d", "block.conf"), markedConf, 0o644) // marked, but under conf.d: never touched
	writeFile(t, filepath.Join(rp, "nginx", "conf.d", "hand.conf"), "# hand written\n", 0o644)
	writeFile(t, filepath.Join(rp, "hasura", "notes.txt"), "mine\n", 0o644)
	writeFile(t, filepath.Join(rp, ".env"), "OLD=1\n", 0o644)
	foreign := readFile(t, filepath.Join(rp, "nginx", "sites", "foreign.conf"))
	blockBefore := readFile(t, filepath.Join(rp, "nginx", "conf.d", "block.conf"))

	ctx := context.Background()
	if err := SyncArtifacts(ctx, f, set); err != nil {
		t.Fatal(err)
	}
	removed, err := PruneMarked(ctx, f, rp, set.KeepSet())
	if err != nil {
		t.Fatal(err)
	}
	if len(removed) != 1 || removed[0] != "nginx/sites/old-generated.conf" {
		t.Fatalf("pruned %v, want only the dropped marked conf", removed)
	}
	if exists(filepath.Join(rp, "nginx", "sites", "old-generated.conf")) {
		t.Error("the dropped generated conf survived")
	}
	if got := readFile(t, filepath.Join(rp, "nginx", "sites", "foreign.conf")); got != foreign {
		t.Error("the unmarked foreign conf changed")
	}
	if got := readFile(t, filepath.Join(rp, "nginx", "conf.d", "block.conf")); got != blockBefore {
		t.Error("a conf.d file changed")
	}
	if !exists(filepath.Join(rp, "nginx", "conf.d", "hand.conf")) || !exists(filepath.Join(rp, "hasura", "notes.txt")) {
		t.Error("an unmarked file was removed")
	}
	// Shipped files match the staged bytes; env files are 0600.
	for _, rel := range append(append([]string{}, set.Files...), set.EnvFiles...) {
		if readFile(t, filepath.Join(rp, rel)) != readFile(t, filepath.Join(set.StageDir, rel)) {
			t.Errorf("%s differs from the staged file", rel)
		}
	}
	for _, rel := range set.EnvFiles {
		if info, _ := os.Stat(filepath.Join(rp, rel)); info.Mode().Perm() != 0o600 {
			t.Errorf("env file %s mode %v, want 0600", rel, info.Mode().Perm())
		}
	}
	// No argv anywhere carries a delete.
	for _, c := range f.commands() {
		if strings.Contains(c, "--delete") || strings.Contains(c, "rm -rf") || strings.Contains(c, "rsync") && strings.Contains(c, "delete") {
			t.Errorf("recorded command deletes: %q", c)
		}
	}
	for _, fl := range f.flags {
		for _, x := range fl {
			if strings.HasPrefix(x, "--delete") {
				t.Errorf("rsync flag %q", x)
			}
		}
	}
	// The real rsync argv builder refuses a delete flag whoever asks, and never emits one.
	spec := remote.HostSpec{User: "deploy", Host: "h.example", Port: 2222}
	argv, err := rsyncArgv(spec, []string{"-i", "/k", "-o", "StrictHostKeyChecking=yes"}, []string{"--chmod=F600"}, "/tmp/list", "/stage", "/opt/nself")
	if err != nil {
		t.Fatal(err)
	}
	joined := strings.Join(argv, " ")
	if strings.Contains(joined, "--delete") || !strings.Contains(joined, "--files-from=/tmp/list") || !strings.Contains(joined, "deploy@h.example:/opt/nself/") || !strings.Contains(joined, "-p 2222") {
		t.Errorf("rsync argv %q", joined)
	}
	for _, bad := range []string{"--delete", "--delete-after", "--remove-source-files", "-e", "notaflag"} {
		if _, err := rsyncArgv(spec, nil, []string{bad}, "/l", "/s", "/opt/nself"); err == nil {
			t.Errorf("rsyncArgv accepted %q", bad)
		}
	}
	if _, err := rsyncArgv(spec, nil, nil, "/l", "/s", "/opt/../etc"); err == nil {
		t.Error("rsyncArgv accepted a .. destination")
	}
}

func TestEnvModeAssertionFails(t *testing.T) {
	f := newFakeRemote(t)
	rp := t.TempDir()
	writeFile(t, filepath.Join(rp, ".env"), "A=1\n", 0o644)
	err := assertEnvModes(context.Background(), f, ArtifactSet{RemotePath: rp, EnvFiles: []string{".env"}})
	if err == nil || !strings.Contains(err.Error(), "want 600") {
		t.Fatalf("a 0644 env file must fail the assertion, got %v", err)
	}
}

func TestPruneRefusesUnsafePaths(t *testing.T) {
	for rel, ok := range map[string]bool{
		"nginx/sites/a.conf": true, "nginx/conf.d/a.conf": false, "nginx/conf.d2/a.conf": false,
		"../etc/passwd": false, "/etc/passwd": false, "nginx/../x": false,
	} {
		if pruneable(rel) != ok {
			t.Errorf("pruneable(%q) = %v", rel, !ok)
		}
	}
}

func TestArtifactsKeepHostEnv(t *testing.T) {
	m, compose, envs, snap := buildScratch(t)
	set, err := Stage(stageIn(m, compose, envs, snap, t.TempDir()))
	if err != nil {
		t.Fatal(err)
	}
	for _, hasEnv := range []bool{true, false} {
		f := newFakeRemote(t)
		rp := filepath.Join(t.TempDir(), "proj") // does not exist yet on a first deploy
		set.RemotePath = rp
		if hasEnv {
			writeFile(t, filepath.Join(rp, ".env"), "HOST_ONLY=1\nPLUGIN_DIR=/srv/plugins\n", 0o600)
		}
		if err := SyncArtifacts(context.Background(), f, set); err != nil {
			t.Fatal(err)
		}
		got := readFile(t, filepath.Join(rp, ".env"))
		info, _ := os.Stat(filepath.Join(rp, ".env"))
		switch {
		case hasEnv && got != "HOST_ONLY=1\nPLUGIN_DIR=/srv/plugins\n":
			t.Errorf("the host's .env was overwritten: %q", got)
		case !hasEnv && (got != "" || info.Mode().Perm() != 0o600):
			t.Errorf("a missing .env must be created empty and 0600, got %q %v", got, info.Mode().Perm())
		}
	}
}
