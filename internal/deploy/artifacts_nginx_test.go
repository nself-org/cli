const buildMarker = "# Generated by nself build - DO NOT EDIT MANUALLY\n"

// testPolicy marks a file generated when its head holds the build marker, the
// way build.IsGeneratedNginxConf does (that package is not imported here).
func testPolicy(include ...string) *NginxPolicy {
	return &NginxPolicy{Generated: func(h []byte) bool { return bytes.Contains(h, []byte("# Generated by nself build")) }, Include: include}
}

// nginxScratch lays a scratch project with a mix of marked, unmarked and
// conf.d nginx files and returns the StageInput for it.
func nginxScratch(t *testing.T, policy *NginxPolicy) StageInput {
	t.Helper()
	base := t.TempDir()
	scratch := filepath.Join(base, "proj", ".nself", "deploy-build", "prod")
	files := map[string]string{
		"nginx/nginx.conf":                  buildMarker + "# main\n",
		"nginx/sites/api.conf":              buildMarker + "# api\n",
		"nginx/sites/hand.conf":             "# hand written\n",
		"nginx/includes/rate-limits.conf":   buildMarker,
		"nginx/includes/extra.conf":         "# hand extra\n",
		"nginx/includes/extra.txt":          "# hand text\n",
		"nginx/conf.d/default.conf":         buildMarker + "# default\n",
		"nginx/conf.d/hand.conf":            "# hand written conf.d\n",
		"nginx/conf.d/other.conf":           "# hand other\n",
		"nginx/conf.d/sub/nested.conf":      buildMarker,
		"nginx/conf.d-prod/default.conf":    buildMarker,
		"nginx/sites/conf.d-x/inner.conf":   buildMarker,
		"nginx/conf.d/.hidden.conf":         buildMarker,
		"nginx/conf.d/notconf.txt":          buildMarker,
		"nginx/conf.d/api-docs.conf.backup": buildMarker,
		"hasura/metadata/version.yaml":      "version: 3\n",
	}
	for rel, body := range files {
		writeFile(t, filepath.Join(scratch, filepath.FromSlash(rel)), body, 0o644)
	}
	m := PathMap{ScratchRoot: scratch, OperatorRoot: filepath.Join(base, "proj"), PluginDir: filepath.Join(base, "plugins"), Home: filepath.Join(base, "home"), RemotePath: "/opt/nself"}
	return StageInput{Map: m, StageDir: t.TempDir(), EnvName: "prod", Nginx: policy}
}

func TestStageNginxMarkedUnmarkedAllowlisted(t *testing.T) {
	cases := []struct {
		name       string
		policy     *NginxPolicy
		shipped    []string
		notShipped []string
	}{
		{
			name:       "marker only",
			policy:     testPolicy(),
			shipped:    []string{"nginx/nginx.conf", "nginx/sites/api.conf", "nginx/includes/rate-limits.conf", "nginx/conf.d/default.conf", "hasura/metadata/version.yaml"},
			notShipped: []string{"nginx/includes/extra.conf", "nginx/includes/extra.txt", "nginx/sites/hand.conf"},
		},
		{
			name:       "allowlist ships the named unmarked files and reports the rest",
			policy:     testPolicy("sites/hand.conf", "includes/*.conf"),
			shipped:    []string{"nginx/sites/hand.conf", "nginx/includes/extra.conf", "nginx/sites/api.conf", "nginx/conf.d/default.conf"},
			notShipped: []string{"nginx/includes/extra.txt"},
		},
		{
			name:       "a glob never reaches conf.d",
			policy:     testPolicy("*/other.conf", "conf.d/other.conf", "*/*.conf"),
			shipped:    []string{"nginx/includes/extra.conf", "nginx/sites/hand.conf", "nginx/conf.d/default.conf"},
			notShipped: []string{"nginx/includes/extra.txt"},
		},
		{
			name:       "segment count must match",
			policy:     testPolicy("sites/*"),
			shipped:    []string{"nginx/sites/hand.conf", "nginx/sites/api.conf"},
			notShipped: []string{"nginx/includes/extra.conf", "nginx/includes/extra.txt"},
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			in := nginxScratch(t, c.policy)
			set, err := Stage(in)
			if err != nil {
				t.Fatal(err)
			}
			for _, want := range c.shipped {
				if !contains(set.Files, want) || !exists(filepath.Join(in.StageDir, filepath.FromSlash(want))) {
					t.Errorf("%s was not shipped: %v", want, set.Files)
				}
			}
			if got := strings.Join(set.NotShipped, ","); got != strings.Join(c.notShipped, ",") {
				t.Errorf("NotShipped = %v, want %v", set.NotShipped, c.notShipped)
			}
			for _, f := range set.Files {
				for _, never := range []string{"conf.d-prod", "conf.d/sub", "conf.d-x", "conf.d/hand.conf", "conf.d/other.conf", ".hidden", "notconf", "api-docs.conf.backup"} {
					if strings.Contains(f, never) {
						t.Errorf("%s must never be shipped", f)
					}
				}
			}
			for _, np := range c.notShipped {
				if contains(set.Files, np) || exists(filepath.Join(in.StageDir, filepath.FromSlash(np))) {
					t.Errorf("%s is reported not shipped but was staged", np)
				}
			}
		})
	}
}

func TestStageNginxNilPolicyKeepsOldBehaviour(t *testing.T) {
	in := nginxScratch(t, nil)
	set, err := Stage(in)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"nginx/sites/hand.conf", "nginx/sites/api.conf", "nginx/includes/extra.txt"} {
		if !contains(set.Files, want) {
			t.Errorf("%s missing with a nil policy: %v", want, set.Files)
		}
	}
	for _, f := range set.Files {
		if strings.Contains(f, "conf.d") {
			t.Errorf("%s: a nil policy must not ship conf.d", f)
		}
	}
	if len(set.NotShipped) != 0 {
		t.Errorf("NotShipped = %v", set.NotShipped)
	}
}

func TestStageNginxHugeUnshippedFileDoesNotFail(t *testing.T) {
	in := nginxScratch(t, testPolicy())
	big := filepath.Join(in.Map.ScratchRoot, "nginx", "sites", "huge.conf")
	if err := os.WriteFile(big, bytes.Repeat([]byte("x"), maxStagedFile+1), 0o644); err != nil {
		t.Fatal(err)
	}
	set, err := Stage(in)
	if err != nil {
		t.Fatalf("an unshipped oversize file must be reported, not fail the stage: %v", err)
	}
	if !contains(set.NotShipped, "nginx/sites/huge.conf") {
		t.Errorf("NotShipped = %v", set.NotShipped)
	}
}

func TestParseNginxInclude(t *testing.T) {
	ok := map[string][]string{
		"":                                   nil,
		" , ,":                               nil,
		"sites/hand.conf":                    {"sites/hand.conf"},
		" sites/hand.conf , includes/*.conf": {"sites/hand.conf", "includes/*.conf"},
		"sites/[a-c]*.conf":                  {"sites/[a-c]*.conf"},
	}
	for raw, want := range ok {
		got, err := ParseNginxInclude(raw)
		if err != nil || strings.Join(got, "|") != strings.Join(want, "|") {
			t.Errorf("ParseNginxInclude(%q) = %v, %v; want %v", raw, got, err, want)
		}
	}
	for _, raw := range []string{
		"/etc/nginx/x.conf", "sites/../../etc/passwd", "../x.conf", "..", "sites/..", "conf.d/default.conf", "conf.d*/x.conf", "conf.d",
		"./sites/x.conf", "sites//x.conf", "sites/", "sites/x[.conf", "sites/x\x01.conf", `sites\x.conf`, "ok.conf,/abs",
	} {
		if got, err := ParseNginxInclude(raw); err == nil {
			t.Errorf("ParseNginxInclude(%q) = %v, want a refusal", raw, got)
		}
	}
}

func TestNginxPolicyAllowsPerSegment(t *testing.T) {
	p := testPolicy("sites/*.conf", "includes/a?.conf")
	for rel, want := range map[string]bool{
		"sites/x.conf": true, "sites/x.txt": false, "sites/sub/x.conf": false, "includes/ab.conf": true, "includes/abc.conf": false,
		"conf.d/x.conf": false, "x.conf": false,
	} {
		if p.allows(rel) != want {
			t.Errorf("allows(%q) = %v", rel, !want)
		}
	}
	var nilPolicy *NginxPolicy
	if nilPolicy.allows("sites/x.conf") || nilPolicy.generated([]byte(buildMarker)) {
		t.Error("a nil policy allows nothing and generates nothing")
	}
}
