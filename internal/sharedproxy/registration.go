// Package sharedproxy is contract:cli.shared-proxy v1: the registration file a
// project writes under a shared host proxy's nginx/shared/ directory.
//
// Purpose: EPIC ADOPT D2 (P7-ADOPT-03; read again by P7-ADOPT-21 and doctor).
// The owner of a shared nginx (NGINX_MODE=shared) keeps `_owner.json`; every
// fronted project nested under it keeps `<project>.json`. Both say which server
// names, services and files the project put on the proxy, so no project
// deletes or shadows another's.
// Inputs: registration bytes, or the nginx/shared/ directory.
// Outputs: Registration, Marshal (deterministic bytes), Parse (validated),
// Load (every registration), RegisteredFiles (a set of owner-relative paths).
// Constraints: keys are sorted and arrays sorted, `_generated` first; the file
// name must equal `<project>.json`; a duplicate project is refused; project_dir
// must resolve under the owner dir. Imports the standard library and
// internal/nginxtopo (L0) only.
package sharedproxy

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/nself-org/cli/internal/nginxtopo"
)

// Generated is the `_generated` marker; SchemaVersion the contract version;
// OwnerFile the owner's file name; Dir the directory under the owner's nginx/.
const (
	Generated     = "GENERATED BY nself build - DO NOT HAND EDIT"
	SchemaVersion = "1"
	OwnerFile     = "_owner.json"
	Dir           = "shared"
)

// Registration is one project's entry. Field order is the key order of the
// written file (sorted; `_generated` sorts first).
type Registration struct {
	Generated     string   `json:"_generated"`
	Files         []string `json:"files"`
	Network       string   `json:"network"`
	Project       string   `json:"project"`
	ProjectDir    string   `json:"project_dir"`
	SchemaVersion string   `json:"schema_version"`
	ServerNames   []string `json:"server_names"`
	ServiceNames  []string `json:"service_names"`
	UpstreamHosts []string `json:"verbatim_upstream_hosts"`
}

// DirOf returns the registration directory of the owner project at ownerRoot:
// <ownerRoot>/nginx/shared (the nginx dir comes from nginxtopo, the one owner of
// that path).
func DirOf(ownerRoot string) string {
	nginxDir, _ := nginxtopo.ServedNginxDir(ownerRoot, "") // cannot fail with an empty frontedBy
	return filepath.Join(nginxDir, Dir)
}

// FileName returns the registration file name of project: `<project>.json`.
func FileName(project string) string { return project + ".json" }

// New returns a Registration for project with the constant fields set.
func New(project, projectDir string) Registration {
	return Registration{Generated: Generated, SchemaVersion: SchemaVersion, Project: project,
		ProjectDir: projectDir, Network: project + "_network"}
}

// Sort sorts and de-duplicates every list and replaces nil with an empty list.
func (r *Registration) Sort() {
	for _, l := range []*[]string{&r.Files, &r.ServerNames, &r.ServiceNames, &r.UpstreamHosts} {
		set := map[string]bool{}
		out := []string{}
		for _, v := range *l {
			if v != "" && !set[v] {
				set[v] = true
				out = append(out, v)
			}
		}
		sort.Strings(out)
		*l = out
	}
}

// Marshal returns the deterministic file bytes (two-space indent, final newline).
func Marshal(r Registration) ([]byte, error) {
	r.Generated, r.SchemaVersion = Generated, SchemaVersion
	r.Sort()
	data, err := json.MarshalIndent(r, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}

// ValidFile reports whether rel is a path a registration may list: a plain
// relative path under nginx/sites/ or ssl/certificates/, never absolute, never
// containing `..` or an empty element.
func ValidFile(rel string) bool {
	if rel == "" || filepath.IsAbs(rel) || strings.Contains(rel, "\\") || strings.HasSuffix(rel, "/") {
		return false
	}
	for _, part := range strings.Split(rel, "/") {
		if part == "" || part == "." || part == ".." {
			return false
		}
	}
	return strings.HasPrefix(rel, "nginx/sites/") || strings.HasPrefix(rel, "ssl/certificates/")
}

// Parse decodes and validates data read from file name `name` (the base name)
// of an owner directory ownerDir. The owner file's project is not checked
// against its name, every other file's must equal `<project>.json`.
func Parse(name string, data []byte, ownerDir string) (Registration, error) {
	var r Registration
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&r); err != nil {
		return r, fmt.Errorf("%s: %w", name, err)
	}
	if r.SchemaVersion != SchemaVersion {
		return r, fmt.Errorf("%s: schema_version %q is not %q", name, r.SchemaVersion, SchemaVersion)
	}
	if r.Project == "" {
		return r, fmt.Errorf("%s: project is empty", name)
	}
	if name != OwnerFile && name != FileName(r.Project) {
		return r, fmt.Errorf("%s: file name must equal %s", name, FileName(r.Project))
	}
	if !under(ownerDir, r.ProjectDir) {
		return r, fmt.Errorf("%s: project_dir %q is not under the owner dir %q", name, r.ProjectDir, ownerDir)
	}
	for _, f := range r.Files {
		if !ValidFile(f) {
			return r, fmt.Errorf("%s: files entry %q is not a path under nginx/sites/ or ssl/certificates/", name, f)
		}
	}
	r.Sort()
	return r, nil
}

// under reports whether dir is ownerDir or below it, by cleaned path.
func under(ownerDir, dir string) bool {
	if ownerDir == "" || dir == "" {
		return false
	}
	rel, err := filepath.Rel(filepath.Clean(ownerDir), filepath.Clean(dir))
	return err == nil && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))
}

// Set is every registration found in one nginx/shared/ directory.
type Set struct {
	Owner    *Registration  // _owner.json, nil when absent
	Projects []Registration // sorted by project
}

// Load reads dir (`<owner>/nginx/shared`). A missing dir is an empty Set. A
// file that does not validate, or a second registration of one project, is an
// error naming the file: a fail-closed read, never a skipped entry.
func Load(dir, ownerDir string) (Set, error) {
	var set Set
	entries, err := os.ReadDir(dir)
	if errors.Is(err, fs.ErrNotExist) {
		return set, nil
	}
	if err != nil {
		return set, err
	}
	seen := map[string]string{}
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".json") {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return set, err
		}
		r, err := Parse(name, data, ownerDir)
		if err != nil {
			return set, err
		}
		if name == OwnerFile {
			set.Owner = &r
			continue
		}
		if prev, dup := seen[r.Project]; dup {
			return set, fmt.Errorf("%s and %s both register project %q", prev, name, r.Project)
		}
		seen[r.Project] = name
		set.Projects = append(set.Projects, r)
	}
	sort.Slice(set.Projects, func(i, j int) bool { return set.Projects[i].Project < set.Projects[j].Project })
	return set, nil
}

// RegisteredFiles returns every path (relative to the owner dir) any project
// registration lists, as a set. The owner's own file lists none.
func (s Set) RegisteredFiles() map[string]bool {
	out := map[string]bool{}
	for _, p := range s.Projects {
		for _, f := range p.Files {
			out[f] = true
		}
	}
	return out
}

// Others returns the project registrations other than project's own.
func (s Set) Others(project string) []Registration {
	var out []Registration
	for _, p := range s.Projects {
		if p.Project != project {
			out = append(out, p)
		}
	}
	return out
}

// Find returns the registration of project, or nil.
func (s Set) Find(project string) *Registration {
	for i := range s.Projects {
		if s.Projects[i].Project == project {
			return &s.Projects[i]
		}
	}
	return nil
}

// hasSymlink reports whether any component of rel below root is a symlink.
func hasSymlink(root, rel string) bool {
	p := root
	for _, part := range strings.Split(rel, "/") {
		p = filepath.Join(p, part)
		if fi, err := os.Lstat(p); err == nil && fi.Mode()&os.ModeSymlink != 0 {
			return true
		}
	}
	return false
}

// Removable reports whether project may delete rel (owner-relative): a valid
// registered path that no other project lists and that does not pass through a
// symlink (an ACME-managed pair is a symlink, and is never removed here).
func (s Set) Removable(ownerDir, project, rel string) bool {
	if !ValidFile(rel) || hasSymlink(ownerDir, rel) {
		return false
	}
	for _, o := range s.Others(project) {
		for _, f := range o.Files {
			if f == rel {
				return false
			}
		}
	}
	return true
}

// Write writes r as `<project>.json` (or `_owner.json` for name) into dir,
// creating dir, via a temp file and rename.
func Write(dir, name string, r Registration) error {
	data, err := Marshal(r)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(dir, ".reg-*")
	if err != nil {
		return err
	}
	defer func() { _ = os.Remove(tmp.Name()) }()
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), filepath.Join(dir, name))
}

// Unregister removes every file project's registration lists (only those
// Removable allows), empty certificate directories left behind, and then the
// registration itself. It returns the owner-relative files it removed. A
// missing registration is not an error. `nself uninstall` in a fronted project
// calls this.
func Unregister(ownerDir, project string) ([]string, error) {
	dir := DirOf(ownerDir)
	set, err := Load(dir, ownerDir)
	if err != nil {
		return nil, err
	}
	reg := set.Find(project)
	if reg == nil {
		return nil, nil
	}
	var removed []string
	for _, rel := range reg.Files {
		if !set.Removable(ownerDir, project, rel) {
			continue
		}
		path := filepath.Join(ownerDir, filepath.FromSlash(rel))
		if err := os.Remove(path); err == nil {
			removed = append(removed, rel)
		} else if !os.IsNotExist(err) {
			return removed, err
		}
		if strings.HasPrefix(rel, "ssl/certificates/") {
			_ = os.Remove(filepath.Dir(path)) // fails while the directory is not empty
		}
	}
	if err := os.Remove(filepath.Join(dir, FileName(project))); err != nil && !os.IsNotExist(err) {
		return removed, err
	}
	return removed, nil
}
