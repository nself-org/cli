package sharedproxy

// site_marker.go — does a conf in the owner's nginx/sites belong to a project?
//
// Purpose: review F5 of EPIC ADOPT D2 (P7-ADOPT-21). A registration is a JSON
// file anyone can edit; when it lists `nginx/sites/<project>.x` and that file
// is the owner's own (project name `default` for default.conf), the owner's
// start would quarantine it and Unregister would delete it. A site file is
// movable only when its name starts `<project>.` and its first lines carry the
// header the fronted build stamps on every conf it writes.
// Inputs: the owner dir, an owner-relative path, the project.
// Outputs: a bool.
// Constraints: the marker text is the one internal/build/shared_proxy_sink.go
// writes (sharedMarker = nginxGeneratedMarker + " (project <name>)", with
// nginxGeneratedMarker in nginx_sites_prune.go). It is duplicated here because
// sharedproxy must not import internal/build; change both together. Only the
// first siteMarkerLines lines count, and the file must be a regular file.

import (
	"bufio"
	"os"
	"path"
	"path/filepath"
	"strings"
)

// siteMarkerPrefix is `# Generated by nself build (project ` (see above).
const siteMarkerPrefix = "# Generated by nself build (project "

// siteMarkerLines is how many leading lines may carry the marker.
const siteMarkerLines = 3

// siteMarker returns the header line of project's confs.
func siteMarker(project string) string { return siteMarkerPrefix + project + ")" }

// siteOwnedBy reports whether rel (`nginx/sites/<file>`) is named `<project>.*`
// and starts with project's marker.
func siteOwnedBy(ownerDir, rel, project string) bool {
	if !strings.HasPrefix(path.Base(rel), project+".") {
		return false
	}
	p := filepath.Join(ownerDir, filepath.FromSlash(rel))
	if fi, err := os.Lstat(p); err != nil || !fi.Mode().IsRegular() {
		return false
	}
	f, err := os.Open(p)
	if err != nil {
		return false
	}
	defer func() { _ = f.Close() }()
	sc := bufio.NewScanner(f)
	for i := 0; i < siteMarkerLines && sc.Scan(); i++ {
		if strings.TrimRight(sc.Text(), " \t\r") == siteMarker(project) {
			return true
		}
	}
	return false
}
